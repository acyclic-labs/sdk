// The Rust executables repository tooling runs (generators, contract exporters, the protobuf code generator)
// are Bazel targets of the generated BUILD files. One `bazel build` brings every requested label up to date,
// so an unchanged executable costs no compile action, and the executable is run directly from Bazel's
// output tree as cquery names it: a path is never guessed. ACYCLIC_BAZEL names the Bazel command
// (bazel, bazelisk or a wrapper); it is the one way to run Bazel here.
import { execFileSync } from "node:child_process";
import { resolve } from "node:path";

export const bazelCommand = () => process.env.ACYCLIC_BAZEL || "bazel";

// The first line of every file scripts/bazel-build-files.mjs writes. The generator writes it and
// every reader that must tell a generated package from a hand-written one compares it, so it
// has exactly one spelling.
export const GENERATED_HEADER = "# Generated by scripts/bazel-build-files.mjs from the Cargo manifests. Do not edit.\n";

const LABEL = /^\/\/[A-Za-z0-9_./-]*:[A-Za-z0-9_.+-]+$/;
const FLAGS = ["--color=no", "--noshow_progress", "--ui_event_filters=-info"];
// cquery's Starlark environment reads a target's providers through providers(); DefaultInfo is not a global.
const EXPRESSION = "str(target.label) + '\\t' + str(getattr(providers(target)['DefaultInfo'].files_to_run.executable, 'path', None))";

/** @param {string} label */
export function assertLabel(label) {
  if (typeof label !== "string" || !LABEL.test(label)) {
    throw new Error(`STEP_FAILED bazel-label: ${JSON.stringify(label)} is not an absolute Bazel label (//package:target)`);
  }
  return label;
}

// cquery prints a main-repository label with its canonical @@ prefix.
const plain = label => label.replace(/^@@?(?=\/\/)/, "");

/**
 * The executable each requested label names, from cquery's `<label>\t<path>` lines. A label cquery does not
 * answer exactly once, or an answer for a label that was not requested, refuses: nothing is substituted.
 * @param {string[]} labels @param {string} output @param {string} executionRoot
 */
export function executablesFromCquery(labels, output, executionRoot) {
  const found = new Map();
  for (const line of output.split(/\r?\n/).filter(Boolean)) {
    const tab = line.indexOf("\t");
    const label = plain(line.slice(0, tab)), file = line.slice(tab + 1);
    if (tab < 0 || !labels.includes(label)) throw new Error(`STEP_FAILED bazel-executable: unexpected cquery answer ${JSON.stringify(line)}`);
    if (found.has(label)) throw new Error(`STEP_FAILED bazel-executable: cquery answered ${label} twice`);
    if (!file || file === "None") throw new Error(`STEP_FAILED bazel-executable: ${label} is not an executable target`);
    found.set(label, resolve(executionRoot, file));
  }
  return labels.map(label => {
    if (!found.has(label)) throw new Error(`STEP_FAILED bazel-executable: cquery did not answer ${label}`);
    return found.get(label);
  });
}

/**
 * Builds `labels` with Bazel and returns their executables, in order. Bazel's own diagnostics go to stderr, so
 * a generator's stdout stays its output.
 * @param {string} root @param {string[]} labels
 * @param {(phase: string, executable: string, args: string[]) => string} [capture] runs one Bazel step, returning stdout
 */
export function bazelExecutables(root, labels, capture = defaultCapture(root)) {
  const requested = [...new Set(labels.map(assertLabel))];
  if (requested.length !== labels.length) throw new Error(`STEP_FAILED bazel-label: duplicate label in ${labels.join(", ")}`);
  if (requested.length === 0) return [];
  const bazel = bazelCommand();
  // The caller runs each executable from the output tree, so a build without the bytes (a remote cache's
  // --remote_download_minimal) must still materialise the requested targets and their runfiles.
  capture("build", bazel, ["build", ...FLAGS, "--remote_download_outputs=toplevel", ...requested]);
  const executionRoot = capture("info", bazel, ["info", ...FLAGS, "execution_root"]).trim();
  const answers = capture("cquery", bazel, ["cquery", ...FLAGS, "--output=starlark", `--starlark:expr=${EXPRESSION}`, `set(${requested.join(" ")})`]);
  return executablesFromCquery(requested, answers, executionRoot);
}

/** One `bazel query` over `root`, its label output as text. */
export function bazelQuery(root, expression) {
  return execFileSync(bazelCommand(), ["query", ...FLAGS, "--output=label", expression], {
    cwd: root, encoding: "utf8", maxBuffer: Infinity, stdio: ["ignore", "pipe", "inherit"], windowsHide: true,
  });
}

function defaultCapture(root) {
  return (phase, executable, args) => execFileSync(executable, args, {
    cwd: root, encoding: "utf8", maxBuffer: Infinity, stdio: ["ignore", "pipe", "inherit"], windowsHide: true,
  });
}

const built = new Map();
/** One label's executable, built at most once per process. @param {string} root @param {string} label */
export function bazelExecutable(root, label) {
  const key = `${bazelCommand()}\0${root}\0${label}`;
  if (!built.has(key)) built.set(key, bazelExecutables(root, [label])[0]);
  return built.get(key);
}
