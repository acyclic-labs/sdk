const outputRelativePath = "typescript/packages/harness/src/component-label-contract.ts";

export const rust = [["acyclic-harness", "example", "component-label-contract"]];

function readRustContract(stdout) {
  const contract = JSON.parse(stdout);
  if (!Number.isSafeInteger(contract.max_bytes) || contract.max_bytes <= 0) {
    throw new Error("Harness component-label contract has an invalid byte limit");
  }
  if (!Array.isArray(contract.forbidden_exact) ||
      !contract.forbidden_exact.every(value => typeof value === "string" && value.length > 0) ||
      new Set(contract.forbidden_exact).size !== contract.forbidden_exact.length) {
    throw new Error("Harness component-label contract has invalid exact values");
  }
  if (!Array.isArray(contract.forbidden_separators) ||
      !contract.forbidden_separators.every(value => typeof value === "string" && [...value].length === 1) ||
      new Set(contract.forbidden_separators).size !== contract.forbidden_separators.length) {
    throw new Error("Harness component-label contract has invalid separators");
  }
  if (!Array.isArray(contract.invalid_ranges) || contract.invalid_ranges.some(range =>
    !Array.isArray(range) || range.length !== 2 ||
    !Number.isInteger(range[0]) || !Number.isInteger(range[1]) ||
    range[0] < 0 || range[1] < range[0] || range[1] > 0x10ffff)) {
    throw new Error("Harness component-label contract has invalid Unicode ranges");
  }
  if (!Array.isArray(contract.validation_vectors) || contract.validation_vectors.some(vector =>
    vector === null || typeof vector !== "object" || typeof vector.value !== "string" ||
    typeof vector.valid !== "boolean")) {
    throw new Error("Harness component-label contract has invalid validation vectors");
  }
  return contract;
}

function evaluatesGeneratedContract(contract, value) {
  if (value.length === 0 || new TextEncoder().encode(value).byteLength > contract.max_bytes ||
      contract.forbidden_exact.includes(value)) return false;
  for (const character of value) {
    const codePoint = character.codePointAt(0);
    if (codePoint === undefined || (codePoint >= 0xd800 && codePoint <= 0xdfff) ||
        contract.forbidden_separators.includes(character) ||
        contract.invalid_ranges.some(([start, end]) => codePoint >= start && codePoint <= end)) return false;
  }
  return true;
}

export function render([stdout]) {
  const contract = readRustContract(stdout);
  for (const vector of contract.validation_vectors) {
    if (evaluatesGeneratedContract(contract, vector.value) !== vector.valid) {
      throw new Error(`Harness component-label predicate drift for ${JSON.stringify(vector.value)}`);
    }
  }
  const header = "// @generated by scripts/generate-harness-component-label-contract.mjs; do not edit.\n\n";
  return { [outputRelativePath]: `${header}` +
    `export const COMPONENT_LABEL_MAX_BYTES = ${contract.max_bytes};\n` +
    `const FORBIDDEN_EXACT = new Set(${JSON.stringify(contract.forbidden_exact)});\n` +
    `const FORBIDDEN_SEPARATORS = new Set(${JSON.stringify(contract.forbidden_separators)});\n` +
    `const INVALID_RANGES = ${JSON.stringify(contract.invalid_ranges)} as readonly (readonly [number, number])[];\n\n` +
    `/** Mirrors Rust validate_component_label without requiring asynchronous WASM initialization. */\n` +
    `export function isValidComponentLabel(value: string): boolean {\n` +
    `  if (value.length === 0 || new TextEncoder().encode(value).byteLength > COMPONENT_LABEL_MAX_BYTES ||\n` +
    `    FORBIDDEN_EXACT.has(value)) return false;\n` +
    `  for (const character of value) {\n` +
    `    const codePoint = character.codePointAt(0);\n` +
    `    if (codePoint === undefined || (codePoint >= 0xd800 && codePoint <= 0xdfff) ||\n` +
    `      FORBIDDEN_SEPARATORS.has(character) ||\n` +
    `      INVALID_RANGES.some(([start, end]) => codePoint >= start && codePoint <= end)) return false;\n` +
    `  }\n` +
    `  return true;\n` +
    `}\n` };
}
