const BIGINT_FIELDS = new Set([
  "maximumObjectBytes",
  "maximumReadBytes",
  "maximumFilesPerGeneration",
  "maximumObjectsPerGeneration",
  "maximumGenerationBytes",
  "maximumBytes",
]);

const snakeToCamel = value => value.replace(/_([a-z])/g, (_, letter) => letter.toUpperCase());

function assertSafeIntegers(value, path = "defaults") {
  if (typeof value === "number") {
    if (!Number.isSafeInteger(value)) {
      throw new Error(`${path} contains a non-safe integer; preserve it as a string in the Rust generator`);
    }
    return;
  }
  if (Array.isArray(value)) {
    value.forEach((entry, index) => assertSafeIntegers(entry, `${path}[${index}]`));
    return;
  }
  if (value && typeof value === "object") {
    for (const [key, entry] of Object.entries(value)) assertSafeIntegers(entry, `${path}.${key}`);
  }
}

function renderValue(key, value, indent) {
  if (typeof value === "string") return JSON.stringify(value);
  if (typeof value === "number") {
    if (BIGINT_FIELDS.has(key)) return `${value}n`;
    return String(value);
  }
  if (value && typeof value === "object" && !Array.isArray(value)) return renderObject(value, indent);
  throw new Error(`unsupported Rust default value for ${key}`);
}

function renderObject(value, indent) {
  const entries = Object.entries(value).map(([snakeKey, entry]) => {
    const key = snakeToCamel(snakeKey);
    return `${" ".repeat(indent)}${key}: ${renderValue(key, entry, indent + 2)},`;
  });
  return `Object.freeze({\n${entries.join("\n")}\n${" ".repeat(indent - 2)}})`;
}

function renderDeclarationType(key, value, indent) {
  if (typeof value === "string") return "string";
  if (typeof value === "number") return BIGINT_FIELDS.has(key) ? "bigint" : "number";
  if (value && typeof value === "object" && !Array.isArray(value)) {
    return renderDeclarationShape(value, indent + 2);
  }
  throw new Error(`unsupported Rust default declaration value for ${key}`);
}

function renderDeclarationShape(value, indent) {
  const entries = Object.entries(value).map(([snakeKey, entry]) => {
    const key = snakeToCamel(snakeKey);
    return `${" ".repeat(indent)}readonly ${key}: ${renderDeclarationType(key, entry, indent)};`;
  });
  return `{\n${entries.join("\n")}\n${" ".repeat(indent - 2)}}`;
}

export const rust = [["acyclic-fs", "example", "filesystem-typescript-defaults"]];

export function render([stdout]) {
  const defaults = JSON.parse(stdout);
  assertSafeIntegers(defaults);
  const header = "// @generated by scripts/generate-filesystem-defaults.mjs; do not edit.\n\n";
  const source = `${header}export const DEFAULT_VOLUME_LIMITS = ${renderObject(defaults.volume_limits, 2)};\n\n` +
    `export const DEFAULT_OBJECT_CACHE_OPTIONS = ${renderObject(defaults.object_cache_options, 2)};\n\n` +
    `export const DEFAULT_HOSTED_OPTIONS = ${renderObject(defaults.hosted, 2)};\n`;
  const declaration = `${header}import type { NativeObjectCacheOptions, NativeVolumeLimits } from "./native/binding.js";\n\n` +
    "export declare const DEFAULT_VOLUME_LIMITS: Readonly<NativeVolumeLimits>;\n" +
    "export declare const DEFAULT_OBJECT_CACHE_OPTIONS: Readonly<NativeObjectCacheOptions>;\n" +
    `export declare const DEFAULT_HOSTED_OPTIONS: Readonly<${renderDeclarationShape(defaults.hosted, 2)}>;\n`;
  return {
    "typescript/packages/filesystem/generated/defaults.js": source,
    "typescript/packages/filesystem/generated/defaults.d.ts": declaration,
  };
}
