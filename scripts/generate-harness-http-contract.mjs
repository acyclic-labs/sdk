import { existsSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { spawnSync } from "node:child_process";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const scriptPath = fileURLToPath(import.meta.url);
const METHODS = new Set(["GET", "POST"]);

function readRustContract(root) {
  const result = spawnSync(
    process.env.ACYCLIC_CARGO_BIN || "cargo",
    [
      "run",
      "--manifest-path",
      join(root, "Cargo.toml"),
      "--package",
      "acyclic-harness-http",
      "--bin",
      "harness-http-contract",
      "--locked",
      "--quiet",
    ],
    { cwd: root, encoding: "utf8" },
  );
  if (result.status !== 0) {
    process.stderr.write(result.stdout ?? "");
    process.stderr.write(result.stderr ?? "");
    throw new Error(`Rust Harness HTTP route contract generator failed with status ${result.status ?? "unknown"}`);
  }
  const lines = (result.stdout ?? "").trim().split(/\r?\n/).filter(Boolean);
  const json = lines.at(-1);
  if (!json) throw new Error("Rust Harness HTTP route contract generator produced no JSON");
  const contract = JSON.parse(json);
  if (!Array.isArray(contract) || contract.length === 0 || contract.some(entry =>
    !Array.isArray(entry) || entry.length !== 3 || typeof entry[0] !== "string" ||
    typeof entry[1] !== "string" || !METHODS.has(entry[1]) || typeof entry[2] !== "string" ||
    !entry[2].startsWith("/"))) {
    throw new Error("Harness HTTP route contract has an invalid shape");
  }
  const names = new Set(contract.map(([name]) => name));
  const paths = new Set(contract.map(([, , path]) => path));
  if (names.size !== contract.length || paths.size !== contract.length) {
    throw new Error("Harness HTTP route contract contains duplicate names or paths");
  }
  return contract;
}

function renderSources(root) {
  const contract = readRustContract(root);
  const paths = contract.map(([name, , path]) => `  ${JSON.stringify(name)}: ${JSON.stringify(path)},`).join("\n");
  const methods = contract.map(([name, method]) => `  ${JSON.stringify(name)}: ${JSON.stringify(method)},`).join("\n");
  const header = "// @generated by scripts/generate-harness-http-contract.mjs; do not edit.\n\n";
  const source = `${header}export const HTTP_ROUTE_CONTRACT = Object.freeze({\n${paths}\n} as const);\n\n` +
    `export const HTTP_ROUTE_METHODS = Object.freeze({\n${methods}\n} as const);\n\n` +
    `export type HttpRoute = keyof typeof HTTP_ROUTE_CONTRACT;\n` +
    `export type HttpRouteMethod<Route extends HttpRoute> = typeof HTTP_ROUTE_METHODS[Route];\n`;
  return { source };
}

export function generateHarnessHttpContract(root, outputDirectory) {
  const output = outputDirectory ?? join(root, "typescript/packages/harness/src");
  writeFileSync(join(output, "http-contract.ts"), renderSources(root).source);
}

export function checkHarnessHttpContract(root) {
  const temporary = mkdtempSync(join(tmpdir(), "acyclic-harness-http-contract-"));
  try {
    generateHarnessHttpContract(root, temporary);
    const committed = join(root, "typescript/packages/harness/src/http-contract.ts");
    if (!existsSync(committed) || !readFileSync(join(temporary, "http-contract.ts")).equals(readFileSync(committed))) {
      throw new Error("Harness HTTP route contract is stale; run bun run generate");
    }
  } finally {
    rmSync(temporary, { recursive: true, force: true });
  }
}

if (resolve(process.argv[1] ?? "") === resolve(scriptPath)) {
  const root = join(dirname(scriptPath), "..");
  const mode = process.argv[2] ?? "write";
  if (mode === "check") checkHarnessHttpContract(root);
  else if (mode === "write") generateHarnessHttpContract(root);
  else throw new Error(`unknown mode: ${mode}`);
}
