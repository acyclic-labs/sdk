export const rust = [["acyclic-objects", "example", "objects-typescript-timeouts"]];

export function render([stdout]) {
  const values = stdout.trim().split(/\s+/);
  if (values.length !== 2 || values.some(value => !/^\d+$/.test(value))) {
    throw new Error("Rust Objects timeout generator produced invalid deadlines");
  }
  const [request, transfer] = values.map(Number);
  if (![request, transfer].every(value => Number.isSafeInteger(value) && value > 0)
    || request > transfer) throw new Error("Rust Objects timeout bounds are invalid");
  const header = "// @generated by scripts/generate-objects-timeouts.mjs; do not edit.\n\n";
  return {
    "typescript/packages/objects/generated/timeouts.js": `${header}export const DEFAULT_REQUEST_TIMEOUT_MS = ${request};\n`
      + `export const MAX_TRANSFER_TIMEOUT_MS = ${transfer};\n`,
    "typescript/packages/objects/generated/timeouts.d.ts": `${header}export declare const DEFAULT_REQUEST_TIMEOUT_MS: number;\n`
      + "export declare const MAX_TRANSFER_TIMEOUT_MS: number;\n",
  };
}
