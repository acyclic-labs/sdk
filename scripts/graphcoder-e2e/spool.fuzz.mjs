import assert from "node:assert/strict";
import { createWriteStream, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { PassThrough, Readable } from "node:stream";
import { finished } from "node:stream/promises";
import { Spool } from "./process.mjs";

const captured = JSON.parse(readFileSync(new URL("./fixtures/shipping-output.json", import.meta.url)))
  .captures["jsonl-reopen"];
const original = Buffer.from(captured.stdout);
// Identifier mutation supplies a second independent indexed range without
// inventing another provider response fixture.
const event = JSON.parse(captured.stdout);
const distinct = Buffer.from(JSON.stringify({ ...event, id: event.id + "\0" }) + "\n");
const key = event => event && typeof event.id === "string" ? [event.id, `alias:${event.id}`] : [];

// Node's whole-buffer UTF-8/JSON decode is the independent reference. Compare
// the original Spool's incremental admission, first-key index and terminal;
// generated byte mutations never replace the retained shipping wire seed.
function expected(bytes, unique) {
  const lines = bytes.toString("utf8").split("\n");
  if (lines.at(-1) === "") lines.pop();
  const events = [], written = [], index = new Map();
  let sequence = 0;
  for (const line of lines) {
    let event;
    try { event = JSON.parse(line); }
    catch { return { events, written, index, sequence, kind: "malformed" }; }
    written.push(event);
    sequence++;
    for (const id of key(event)) {
      if (index.has(id) && unique) return { events, written, index, sequence, kind: "duplicate" };
      if (!index.has(id)) index.set(id, event);
    }
    events.push(event);
  }
  return { events, written, index, sequence, kind: "eof" };
}

async function replay(bytes, unique, partition, closedFirst, path) {
  const reference = expected(bytes, unique), chunks = [];
  for (let offset = 0; offset < bytes.length;) {
    const end = partition === "whole" ? bytes.length
      : Math.min(bytes.length, offset + (partition === "bytes" ? 1 : 1 + bytes[offset]));
    chunks.push(bytes.subarray(offset, end)); offset = end;
  }
  const source = Readable.from(chunks);
  let close;
  const closed = new Promise(resolve => { close = resolve; });
  const transcript = path ? createWriteStream(path) : undefined;
  const persisted = transcript && finished(transcript);
  const spool = new Spool(source, closed, { key, unique, transcript });
  const events = [];
  spool.subscribe(event => events.push(event));
  const observed = promise => promise.then(value => ({ value }), error => ({ error }));
  const cancellation = new AbortController(), reason = Symbol("cancel original waiter");
  const cancelled = [observed(spool.next(() => false, { signal: cancellation.signal })),
    observed(spool.keyed(Symbol("cancelled key"), { signal: cancellation.signal }))];
  cancellation.abort(reason);
  cancelled.push(observed(spool.keyed(Symbol("already cancelled key"), { signal: cancellation.signal })));
  const first = observed(spool.next(() => true));
  const firstKey = reference.index.keys().next();
  const keyed = firstKey.done ? undefined : observed(spool.keyed(firstKey.value));
  const terminal = spool.next(() => false).then(() => assert.fail("a false predicate cannot resolve"), error => error);
  const missing = spool.keyed(Symbol("absent")).then(() => assert.fail("absent key cannot resolve"), error => error);
  const drained = finished(source);
  if (closedFirst) close(captured);
  else source.once("end", () => close(captured));
  const cause = await terminal;
  await drained;
  await persisted;
  for (const pending of cancelled) {
    const result = await pending;
    assert.equal(result.error?.kind, "cancelled", "original waiter cancellation must precede later source EOF");
    assert.equal(result.error.detail, reason, "cancellation retains its original reason");
  }
  assert.equal(cause.kind, reference.kind, "original terminal must survive byte partitions and physical-exit order");
  assert.equal(await missing, cause, "all original waiters must receive the same terminal");
  assert.equal(spool.ended, cause);
  assert.equal(spool.sequence, reference.sequence);
  assert.deepEqual(events, reference.events, "no event may follow the first malformed or duplicate terminal");
  if (reference.events.length) assert.deepEqual((await first).value, reference.events[0]);
  else assert.equal((await first).error, cause);
  if (keyed) assert.deepEqual((await keyed).value, reference.index.get(firstKey.value));
  for (const [id, event] of reference.index) {
    assert.equal(spool.has(id), true);
    let actual;
    await assert.doesNotReject(async () => { actual = await spool.keyed(id); }, "the original indexed event must remain readable");
    assert.deepEqual(actual, event, "late lookup must preserve the first committed event");
    const cancelled = await observed(spool.keyed(id, { signal: cancellation.signal }));
    assert.equal(cancelled.error?.kind, "cancelled", "retained indexed data cannot bypass caller cancellation");
    assert.equal(cancelled.error.detail, reason);
  }
  if (path) assert.deepEqual(await spool.history(), reference.written, "history contains only original completed transcript lines");
  await assert.rejects(spool.next(() => true), error => error === cause);
  await assert.rejects(spool.keyed(Symbol("still absent")), error => error === cause);
  if (cause.kind === "eof") assert.equal(cause.detail, captured, "EOF must retain the original native result");
}

// Exercise the original source and callback failure entrances. The stream is
// an in-memory adapter; the source cause is an actual filesystem refusal, not
// a claim about native pipe retirement or transcript write failure.
async function failure(bytes, mode, sourceError) {
  const source = new PassThrough();
  let close, refuse;
  const closed = new Promise((resolve, reject) => { close = resolve; refuse = reject; });
  const consumer = ["key", "listener", "predicate"].includes(mode);
  const error = consumer ? new Error("generated callback refusal") : sourceError;
  const dispatch = () => { throw error; };
  const spool = new Spool(source, closed, { key: mode === "key" ? dispatch : key });
  const events = [];
  spool.subscribe(event => events.push(event));
  if (mode === "listener") spool.subscribe(dispatch);
  const observed = promise => promise.then(() => assert.fail("failed dispatch cannot resolve"), error => error);
  const predicate = mode === "predicate" ? observed(spool.next(dispatch)) : undefined;
  const terminal = observed(spool.next(() => false));
  const missing = observed(spool.keyed(Symbol("missing after failure")));
  const drained = finished(source).then(() => undefined, error => error);
  if (consumer) source.write(original);
  else if (mode === "stream") source.destroy(error);
  else refuse(error);
  const cause = await terminal;
  assert.equal(cause.kind, consumer ? "consumer" : "source");
  assert.equal(cause.detail, error, "failure retains the original object");
  assert.equal(cause.cause, error, "native error cause remains inspectable");
  assert.equal(await missing, cause);
  if (predicate) assert.equal(await predicate, cause);
  // Later output and physical completion cannot replace the first terminal.
  if (mode !== "stream") source.end(Buffer.concat([bytes, original]));
  close(captured);
  assert.equal(await drained, mode === "stream" ? error : undefined);
  assert.equal(spool.ended, cause);
  assert.equal(spool.sequence, consumer ? 1 : 0);
  assert.deepEqual(events, consumer && mode !== "key" ? [event] : []);
  assert.equal(await observed(spool.next(() => true)), cause);
  assert.equal(await observed(spool.keyed(Symbol("later missing"))), cause);
}

// The original file writer supplies the failure, before any source output or
// process completion. Empty history needs no file; readers after the refusal
// retain its original cause.
async function transcriptFailure(directory) {
  const source = new PassThrough();
  const transcript = createWriteStream(join(directory, "absent", "events.jsonl"));
  const failed = finished(transcript).then(() => assert.fail("missing parent cannot accept a transcript"), error => error);
  let close;
  const spool = new Spool(source, new Promise(resolve => { close = resolve; }), { key, transcript });
  const terminal = spool.next(() => false).catch(error => error);
  const missing = spool.keyed(Symbol("missing transcript key")).catch(error => error);
  const history = spool.history().catch(error => error);
  const cause = await terminal, error = await failed;
  assert.equal(error.code, "ENOENT");
  assert.equal(cause.kind, "spool");
  assert.equal(cause.detail, error);
  assert.equal(cause.cause, error);
  assert.equal(await missing, cause);
  assert.deepEqual(await history, [], "history before the first completed write needs no file");
  await assert.rejects(spool.history(), error => error === cause, "late history cannot bypass transcript failure");
  await assert.rejects(spool.next(() => true), error => error === cause);
  await assert.rejects(spool.keyed(Symbol("late transcript key")), error => error === cause);
  source.end(original);
  close(captured);
  await finished(source);
  assert.equal(spool.sequence, 0, "later source output cannot replace the writer refusal");
  assert.equal(spool.ended, cause);
}

// Mutate the original completed file, then compare its two indexed ranges and
// completed history with independent whole-buffer decoding. These are format
// checks, not integrity certification for externally modified transcripts.
async function persisted(bytes, path) {
  const baseline = Buffer.concat([original, distinct]);
  const transcript = createWriteStream(path), written = finished(transcript);
  const spool = new Spool(Readable.from([baseline]), Promise.resolve(captured), { key, transcript });
  const terminal = await spool.next(() => false).catch(error => error);
  assert.equal(terminal.kind, "eof");
  await written;
  const ranges = [[event.id, 0, original.length], [event.id + "\0", original.length, distinct.length]];
  for (const mutation of [bytes, Buffer.concat([bytes, baseline])]) {
    writeFileSync(path, mutation);
    for (const [id, at, length] of ranges) {
      if (mutation.length < at + length) {
        await assert.rejects(spool.keyed(id), error => error.kind === "spool"
          && error.detail.at === at && error.detail.length === length);
      } else {
        let value, invalid;
        try { value = JSON.parse(mutation.subarray(at, at + length).toString("utf8")); }
        catch (error) { invalid = error; }
        if (invalid) await assert.rejects(spool.keyed(id), error => error.kind === "spool" && error.cause instanceof SyntaxError);
        else assert.deepEqual(await spool.keyed(id), value);
      }
    }
    if (mutation.length < baseline.length) {
      await assert.rejects(spool.history(), error => error.kind === "spool" && error.detail.completed === baseline.length);
    } else {
      let values, invalid;
      try { values = mutation.subarray(0, baseline.length).toString("utf8").split("\n").filter(Boolean).map(JSON.parse); }
      catch (error) { invalid = error; }
      if (invalid) await assert.rejects(spool.history(), SyntaxError);
      else assert.deepEqual(await spool.history(), values);
    }
    assert.equal(spool.ended, terminal, "a historical read cannot replace the original process terminal");
  }
}

export async function fuzz(data) {
  const bytes = Buffer.from(data);
  const directory = mkdtempSync(join(tmpdir(), "spool-corpus-"));
  try {
    let sourceError;
    try { readFileSync(join(directory, "absent")); }
    catch (error) { sourceError = error; }
    assert.equal(sourceError?.code, "ENOENT");
    for (const mode of ["key", "listener", "predicate", "stream", "closed"])
      await failure(bytes, mode, sourceError);
    await transcriptFailure(directory);
    await persisted(bytes, join(directory, "mutated.jsonl"));
    for (const input of [bytes, Buffer.concat([bytes, original]), Buffer.concat([original, bytes]),
      Buffer.concat([original, original, bytes]), Buffer.concat([original, distinct, bytes])])
      for (const unique of [false, true])
        for (const closedFirst of [false, true]) {
          for (const partition of ["whole", "bytes", "input"]) await replay(input, unique, partition, closedFirst);
          await replay(input, unique, "input", closedFirst, join(directory, "events.jsonl"));
        }
  } finally { rmSync(directory, { recursive: true }); }
}
