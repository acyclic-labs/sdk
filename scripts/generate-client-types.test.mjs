import assert from "node:assert/strict";
import test from "node:test";
import { render as renderHttp, rust as httpSource } from "./generate-stream-http-contract.mjs";
import { render as renderTokens, rust as tokenSource } from "./generate-stream-token-operations.mjs";
import { render as renderWidths, rust as widthSource } from "./generate-inference-widths.mjs";
import { render as renderChildPage } from "./generate-harness-child-page-contract.mjs";

test("Stream HTTP generator keeps route result types without a runtime contract export", () => {
  assert.deepEqual(httpSource, [["acyclic-stream", "bin", "stream-http-contract"]]);
  const source = renderHttp([JSON.stringify([["tail", "sequence"], ["read", "records"]])])["typescript/packages/stream/src/http-contract.ts"];
  assert.match(source, /type HttpResponseContract = \{\n  "tail": "sequence";\n  "read": "records";\n\};/);
  assert.match(source, /export type HttpRoute = keyof HttpResponseContract;/);
  assert.match(source, /HttpResponseByKind\[HttpResponseContract\[Route\]\]/);
  assert.match(source, /return decodeHttpResponseWasm\(route, responseJson\);/);
  assert.doesNotMatch(source, /HTTP_RESPONSE_CONTRACT|Object\.freeze|export const/);
});

test("Stream token generator emits only the Rust-owned operation union", () => {
  assert.deepEqual(tokenSource, [["acyclic-stream", "example", "token-operations"]]);
  assert.equal(renderTokens([JSON.stringify(["list", "future-operation"])])["typescript/packages/stream/src/token-operations.ts"],
    "// @generated by scripts/generate-stream-token-operations.mjs; do not edit.\n\n" +
    'export type TokenOperation = "list" | "future-operation";\n');
});

test("Stream generators retain malformed source inventory rejection", () => {
  for (const value of [null, {}, ["tail"], [["tail", "unknown"]], [[1, "sequence"]]]) {
    assert.throws(() => renderHttp([JSON.stringify(value)]), /Rust Stream HTTP contract has an invalid shape/);
  }
  for (const value of [null, {}, [], [""], [1], ["list", "list"]]) {
    assert.throws(() => renderTokens([JSON.stringify(value)]), /Rust Stream token operation inventory/);
  }
});

test("inference generator retains named Rust widths without publishing the unused raw dump", () => {
  assert.deepEqual(widthSource, [["acyclic-inference-wasm", "example", "inference-typescript-widths"]]);
  const files = renderWidths([JSON.stringify({ runId: 16, contextRevision: 32, futureWidth: 7 })]);
  assert.deepEqual(Object.keys(files).sort(), [
    "typescript/packages/inference/generated/widths.d.ts", "typescript/packages/inference/generated/widths.js",
  ]);
  assert.match(files["typescript/packages/inference/generated/widths.js"], /export const INFERENCE_FIXED_WIDTHS = Object\.freeze\(/);
  assert.match(files["typescript/packages/inference/generated/widths.d.ts"], /readonly "runId": 16;/);
  assert.match(files["typescript/packages/inference/generated/widths.d.ts"], /readonly "contextRevision": 32;/);
  assert.match(files["typescript/packages/inference/generated/widths.d.ts"], /readonly "futureWidth": 7;/);
});

test("child-page generator admits only the one positive safe-integer default", () => {
  const key = "typescript/packages/harness/src/child-page-contract.ts";
  assert.match(renderChildPage([JSON.stringify({ default_page: 345 })])[key], /HARNESS_CHILD_PAGE_DEFAULT = 345 as number;/);
  for (const contract of [{}, { other: 1 }, { default_page: 1, extra: 1 }, { ",default_page": 1 }]) {
    assert.throws(() => renderChildPage([JSON.stringify(contract)]), /child-page contract field inventory drift/);
  }
  for (const value of [0, -1, 1.5, Number.MAX_SAFE_INTEGER + 1, null, "1"]) {
    assert.throws(() => renderChildPage([JSON.stringify({ default_page: value })]), /has invalid default_page/);
  }
});
