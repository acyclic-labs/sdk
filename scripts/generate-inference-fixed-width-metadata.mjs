import { existsSync, readFileSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { spawnSync } from "node:child_process";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const scriptPath = fileURLToPath(import.meta.url);

function readRustMetadata(root) {
  const result = spawnSync(
    process.env.ACYCLIC_CARGO_BIN || "cargo",
    [
      "run",
      "--manifest-path", join(root, "Cargo.toml"),
      "--package", "acyclic-inference-wasm",
      "--example", "inference-typescript-fixed-width-metadata",
      "--locked",
      "--quiet",
    ],
    { cwd: root, encoding: "utf8" },
  );
  if (result.status !== 0) {
    process.stderr.write(result.stdout ?? "");
    process.stderr.write(result.stderr ?? "");
    throw new Error(`Rust inference fixed-width metadata generator failed with status ${result.status ?? "unknown"}`);
  }
  const raw = (result.stdout ?? "").trim().split(/\r?\n/).filter(Boolean).at(-1);
  if (raw === undefined) throw new Error("Rust inference fixed-width metadata generator produced no JSON");
  let metadata;
  try {
    metadata = JSON.parse(raw);
  } catch (error) {
    throw new Error(`Rust inference fixed-width metadata is not JSON: ${String(error)}`);
  }
  if (!Array.isArray(metadata) || metadata.length === 0 || metadata.some(item =>
    item === null || typeof item !== "object" ||
    typeof item.message !== "string" || !/^inference\.customer\.v1\.[A-Z][A-Za-z0-9]*$/.test(item.message) ||
    typeof item.field !== "string" || !/^[a-z][a-z0-9_]*$/.test(item.field) ||
    !Number.isSafeInteger(item.width) || item.width <= 0)) {
    throw new Error("Rust inference fixed-width metadata has an invalid entry");
  }
  const keys = metadata.map(item => `${item.message}.${item.field}`);
  if (new Set(keys).size !== metadata.length) {
    throw new Error("Rust inference fixed-width metadata has duplicate fields");
  }
  return metadata;
}

function render(metadata) {
  const header = "// @generated by scripts/generate-inference-fixed-width-metadata.mjs; do not edit.\n\n";
  const entries = metadata.map(item => `  Object.freeze(${JSON.stringify(item)})`).join(",\n");
  return {
    source: `${header}export const INFERENCE_FIXED_WIDTH_METADATA = Object.freeze([\n${entries}\n]);\n`,
    declaration: `${header}export interface InferenceFixedWidthMetadata {\n` +
      "  readonly message: string;\n  readonly field: string;\n  readonly width: number;\n}\n" +
      "export declare const INFERENCE_FIXED_WIDTH_METADATA: readonly InferenceFixedWidthMetadata[];\n",
  };
}

export function generateInferenceFixedWidthMetadata(root, outputDirectory) {
  const metadata = readRustMetadata(root);
  const output = outputDirectory ?? join(root, "typescript/packages/inference/generated");
  const { source, declaration } = render(metadata);
  writeFileSync(join(output, "fixed-width-metadata.js"), source);
  writeFileSync(join(output, "fixed-width-metadata.d.ts"), declaration);
}

export function checkInferenceFixedWidthMetadata(root) {
  const temporary = mkdtempSync(join(root, ".tmp-inference-fixed-width-metadata-"));
  try {
    generateInferenceFixedWidthMetadata(root, temporary);
    for (const file of ["fixed-width-metadata.js", "fixed-width-metadata.d.ts"]) {
      const committed = join(root, "typescript/packages/inference/generated", file);
      if (!existsSync(committed) || !readFileSync(join(temporary, file)).equals(readFileSync(committed))) {
        throw new Error(`inference fixed-width metadata is stale; run bun run generate (${file})`);
      }
    }
  } finally {
    rmSync(temporary, { recursive: true, force: true });
  }
}

if (resolve(process.argv[1] ?? "") === resolve(scriptPath)) {
  const root = join(dirname(scriptPath), "..");
  const mode = process.argv[2] ?? "write";
  if (mode === "check") checkInferenceFixedWidthMetadata(root);
  else if (mode === "write") generateInferenceFixedWidthMetadata(root);
  else throw new Error(`unknown mode: ${mode}`);
}
