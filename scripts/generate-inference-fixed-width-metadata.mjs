export const rust = [
  ["acyclic-inference-wasm", "example", "inference-typescript-fixed-width-metadata"],
  ["acyclic-inference-wasm", "example", "inference-typescript-widths"],
];

function readRustMetadata(stdout) {
  const metadata = JSON.parse(stdout);
  if (!Array.isArray(metadata) || metadata.length === 0 || metadata.some(item =>
    item === null || typeof item !== "object" ||
    typeof item.message !== "string" || !/^inference\.customer\.v1\.[A-Z][A-Za-z0-9]*$/.test(item.message) ||
    typeof item.field !== "string" || !/^[a-z][a-z0-9_]*$/.test(item.field) ||
    !Number.isSafeInteger(item.width) || item.width <= 0)) {
    throw new Error("Rust inference fixed-width metadata has an invalid entry");
  }
  const keys = metadata.map(item => `${item.message}.${item.field}`);
  if (new Set(keys).size !== metadata.length) {
    throw new Error("Rust inference fixed-width metadata has duplicate fields");
  }
  return metadata;
}

export function render([stdout, widthsStdout]) {
  const metadata = readRustMetadata(stdout);
  const header = "// @generated by scripts/generate-inference-fixed-width-metadata.mjs; do not edit.\n\n";
  const entries = metadata.map(item => `  Object.freeze(${JSON.stringify(item)})`).join(",\n");
  const widths = JSON.parse(widthsStdout);
  const literalFields = Object.entries(widths).map(([name, width]) => `  readonly ${JSON.stringify(name)}: ${JSON.stringify(width)};`).join("\n");
  return {
    "typescript/packages/inference/generated/widths.js": `${header}export const INFERENCE_FIXED_WIDTHS = Object.freeze(${JSON.stringify(widths, null, 2)});\n`,
    "typescript/packages/inference/generated/widths.d.ts": `${header}export declare const INFERENCE_FIXED_WIDTHS: {\n${literalFields}\n};\n`,
    "typescript/packages/inference/generated/fixed-width-metadata.js": `${header}export const INFERENCE_FIXED_WIDTH_METADATA = Object.freeze([\n${entries}\n]);\n`,
    "typescript/packages/inference/generated/fixed-width-metadata.d.ts": `${header}export interface InferenceFixedWidthMetadata {\n` +
      "  readonly message: string;\n  readonly field: string;\n  readonly width: number;\n}\n" +
      "export declare const INFERENCE_FIXED_WIDTH_METADATA: readonly InferenceFixedWidthMetadata[];\n",
  };
}
