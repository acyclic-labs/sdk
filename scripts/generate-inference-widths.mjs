export const rust = [["acyclic-inference-wasm", "example", "inference-typescript-widths"]];

export function render([stdout]) {
  const widths = JSON.parse(stdout);
  const header = "// @generated by scripts/generate-inference-widths.mjs; do not edit.\n\n";
  const literalFields = Object.entries(widths).map(([name, width]) => `  readonly ${JSON.stringify(name)}: ${JSON.stringify(width)};`).join("\n");
  return {
    "typescript/packages/inference/generated/widths.js": `${header}export const INFERENCE_FIXED_WIDTHS = Object.freeze(${JSON.stringify(widths, null, 2)});\n`,
    "typescript/packages/inference/generated/widths.d.ts": `${header}export declare const INFERENCE_FIXED_WIDTHS: {\n${literalFields}\n};\n`,
  };
}
