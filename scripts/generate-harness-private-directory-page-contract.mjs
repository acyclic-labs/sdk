import { existsSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { spawnSync } from "node:child_process";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const scriptPath = fileURLToPath(import.meta.url);
const outputRelativePath = "typescript/packages/harness/src/private-directory-page-contract.ts";
const fields = ["default_page", "maximum_page"];

function readRustContract(root) {
  const result = spawnSync(
    process.env.ACYCLIC_CARGO_BIN || "cargo",
    [
      "run", "--manifest-path", join(root, "Cargo.toml"), "--package", "acyclic-harness",
      "--example", "private-directory-page-contract", "--no-default-features", "--locked", "--quiet",
    ],
    { cwd: root, encoding: "utf8" },
  );
  if (result.status !== 0) {
    process.stderr.write(result.stdout ?? "");
    process.stderr.write(result.stderr ?? "");
    throw new Error(`Rust Harness private-directory page contract generator failed with status ${result.status ?? "unknown"}`);
  }
  const jsonLine = (result.stdout ?? "").trim().split(/\r?\n/).filter(Boolean).at(-1);
  if (!jsonLine) throw new Error("Rust Harness private-directory page contract generator produced no JSON");
  const contract = JSON.parse(jsonLine);
  const actual = Object.keys(contract).sort();
  if (JSON.stringify(actual) !== JSON.stringify([...fields].sort())) {
    throw new Error(`Harness private-directory page contract field inventory drift: expected ${fields.join(",")}, got ${actual.join(",")}`);
  }
  for (const field of fields) {
    if (!Number.isSafeInteger(contract[field]) || contract[field] <= 0) {
      throw new Error(`Harness private-directory page contract has invalid ${field}`);
    }
  }
  if (contract.default_page > contract.maximum_page) {
    throw new Error("Harness private-directory page default exceeds its maximum");
  }
  return contract;
}

function renderContract(root) {
  const contract = readRustContract(root);
  return [
    "// @generated by scripts/generate-harness-private-directory-page-contract.mjs; do not edit.",
    "",
    `export const HARNESS_PRIVATE_DIRECTORY_PAGE_DEFAULT = ${contract.default_page} as number;`,
    `export const HARNESS_PRIVATE_DIRECTORY_PAGE_MAXIMUM = ${contract.maximum_page} as number;`,
    "",
  ].join("\n");
}

export function generateHarnessPrivateDirectoryPageContract(root, outputDirectory) {
  const output = outputDirectory ?? dirname(join(root, outputRelativePath));
  writeFileSync(join(output, "private-directory-page-contract.ts"), renderContract(root));
}

export function checkHarnessPrivateDirectoryPageContract(root) {
  const temporary = mkdtempSync(join(tmpdir(), "acyclic-harness-private-directory-page-contract-"));
  try {
    generateHarnessPrivateDirectoryPageContract(root, temporary);
    const committed = join(root, outputRelativePath);
    if (!existsSync(committed) || !readFileSync(join(temporary, "private-directory-page-contract.ts")).equals(readFileSync(committed))) {
      throw new Error("Harness private-directory page contract is stale; run bun run generate");
    }
  } finally {
    rmSync(temporary, { recursive: true, force: true });
  }
}

if (resolve(process.argv[1] ?? "") === resolve(scriptPath)) {
  const root = join(dirname(scriptPath), "..");
  const mode = process.argv[2] ?? "write";
  if (mode === "check") checkHarnessPrivateDirectoryPageContract(root);
  else if (mode === "write") generateHarnessPrivateDirectoryPageContract(root);
  else throw new Error(`unknown mode: ${mode}`);
}
