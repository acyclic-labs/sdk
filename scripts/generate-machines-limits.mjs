export const rust = [["acyclic-machines", "bin", "machines-limits"]];

export function render([stdout]) {
  const limits = JSON.parse(stdout);
  if (![limits.maxPageSize, limits.maxEventPageSize, limits.maxOutputReadBytes]
    .every(value => Number.isSafeInteger(value) && value > 0)) {
    throw new Error("Machines limits must be positive safe integers");
  }
  const header = "// @generated by scripts/generate-machines-limits.mjs; do not edit.\n\n";
  return {
    "typescript/packages/machines/src/limits.ts": `${header}export const MACHINES_LIMITS = Object.freeze({
  maxPageSize: ${limits.maxPageSize},
  maxEventPageSize: ${limits.maxEventPageSize},
  maxOutputReadBytes: ${limits.maxOutputReadBytes},
} as const);
`,
  };
}
