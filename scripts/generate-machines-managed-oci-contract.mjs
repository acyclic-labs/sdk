import { existsSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { spawnSync } from "node:child_process";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const scriptPath = fileURLToPath(import.meta.url);

function readRustContract(root) {
  const result = spawnSync(
    process.env.ACYCLIC_CARGO_BIN || "cargo",
    ["run", "--manifest-path", join(root, "Cargo.toml"), "--package", "acyclic-machines", "--bin", "machines-managed-oci-contract", "--locked", "--quiet"],
    { cwd: root, encoding: "utf8" },
  );
  if (result.status !== 0) {
    process.stderr.write(result.stdout ?? "");
    process.stderr.write(result.stderr ?? "");
    throw new Error(`Rust Machines OCI contract generator failed with status ${result.status ?? "unknown"}`);
  }
  const lines = (result.stdout ?? "").trim().split(/\r?\n/).filter(Boolean);
  const json = lines.at(-1);
  if (!json) throw new Error("Rust Machines OCI contract generator produced no JSON");
  const contract = JSON.parse(json);
  if (typeof contract.separator !== "string" || !contract.separator ||
      !Number.isInteger(contract.digestHexLength) || contract.digestHexLength <= 0 ||
      typeof contract.hexDigits !== "string" || !contract.hexDigits ||
      typeof contract.zeroDigit !== "string" || contract.zeroDigit.length !== 1) {
    throw new Error("Machines OCI contract has an invalid shape");
  }
  if (!Number.isInteger(contract.maxPageSize) || contract.maxPageSize <= 0 ||
      !Number.isInteger(contract.maxEventPageSize) || contract.maxEventPageSize <= 0) {
    throw new Error("Machines page-limit contract has an invalid shape");
  }
  return contract;
}

function renderSource(root) {
  const contract = readRustContract(root);
  const header = "// @generated by scripts/generate-machines-managed-oci-contract.mjs; do not edit.\n\n";
  return `${header}export const MANAGED_OCI_CONTRACT = Object.freeze({
  separator: ${JSON.stringify(contract.separator)},
  digestHexLength: ${contract.digestHexLength},
  hexDigits: ${JSON.stringify(contract.hexDigits)},
  zeroDigit: ${JSON.stringify(contract.zeroDigit)},
  maxPageSize: ${contract.maxPageSize},
  maxEventPageSize: ${contract.maxEventPageSize},
} as const);
`;
}

export function generateMachinesManagedOciContract(root, outputDirectory) {
  const output = outputDirectory ?? join(root, "typescript/packages/machines/src");
  writeFileSync(join(output, "managed-oci-contract.ts"), renderSource(root));
}

export function checkMachinesManagedOciContract(root) {
  const temporary = mkdtempSync(join(tmpdir(), "acyclic-machines-managed-oci-contract-"));
  try {
    generateMachinesManagedOciContract(root, temporary);
    const committed = join(root, "typescript/packages/machines/src/managed-oci-contract.ts");
    if (!existsSync(committed) || !readFileSync(join(temporary, "managed-oci-contract.ts")).equals(readFileSync(committed))) {
      throw new Error("Machines OCI contract is stale; run bun run generate");
    }
  } finally {
    rmSync(temporary, { recursive: true, force: true });
  }
}

if (resolve(process.argv[1] ?? "") === resolve(scriptPath)) {
  const root = join(dirname(scriptPath), "..");
  const mode = process.argv[2] ?? "write";
  if (mode === "check") checkMachinesManagedOciContract(root);
  else if (mode === "write") generateMachinesManagedOciContract(root);
  else throw new Error(`unknown mode: ${mode}`);
}
