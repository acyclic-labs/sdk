import { copyFile, mkdir, mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { createReadStream } from "node:fs";
import { createHash } from "node:crypto";
import { createSecureServer } from "node:http2";
import { tmpdir } from "node:os";
import { basename, dirname, isAbsolute, join, resolve } from "node:path";
import { createRequire } from "node:module";
import { spawn, spawnSync } from "node:child_process";
import { fileURLToPath, pathToFileURL } from "node:url";
import { create } from "@bufbuild/protobuf";
import { Code, ConnectError } from "@connectrpc/connect";
import { connectNodeAdapter } from "@connectrpc/connect-node";
import { ActorsService } from "../typescript/packages/actors/generated/proto/actors/v1/actors_pb.js";

// This qualification script does not build or select a customer transport. It
// loads the Rust-owned N-API bridge produced by acyclic-actors-napi and checks
// its stable generated surface before an artifact is staged for a platform
// package. Installed-package qualification additionally uses the maintained
// loopback TLS fixture below to exercise the package facade end to end.
const libraryNames = {
  win32: "acyclic_actors_napi.dll",
  linux: "libacyclic_actors_napi.so",
  darwin: "libacyclic_actors_napi.dylib",
};
const libraryName = libraryNames[process.platform];
if (libraryName === undefined) {
  throw new Error(`unsupported Actors N-API qualification platform ${process.platform}`);
}

const { version } = JSON.parse(await readFile(
  new URL("../typescript/packages/actors/package.json", import.meta.url), "utf8",
));
if (typeof version !== "string" || !/^[0-9]+\.[0-9]+\.[0-9]+(?:-[0-9A-Za-z.-]+)?$/.test(version)) {
  throw new Error("invalid Actors package version");
}
const declarationPath = new URL("../typescript/packages/actors/generated/native/binding.d.ts", import.meta.url);

const childBinding = process.env.ACYCLIC_ACTORS_NAPI_CHILD_BINDING;
if (childBinding !== undefined) {
  await qualify(childBinding);
  process.exit(0);
}

const positional = process.argv.slice(2);
let output;
let installedPackage;
for (let index = 0; index < positional.length; index += 1) {
  const argument = positional[index];
  if (argument === "--installed-package") {
    installedPackage = positional[++index];
    if (installedPackage === undefined) {
      throw new Error("--installed-package requires an absolute package root");
    }
  } else if (output === undefined) {
    output = argument;
  } else {
    throw new Error("usage: check-actors-napi.mjs [ABSOLUTE_OUTPUT] [--installed-package ABSOLUTE_PACKAGE_ROOT]");
  }
}
if (
  (output !== undefined && !isAbsolute(output)) ||
  (installedPackage !== undefined && !isAbsolute(installedPackage))
) {
  throw new Error("output and installed package paths must be absolute");
}

const targetRoot = resolve(process.env.CARGO_TARGET_DIR ?? "target");
const profile = process.env.ACYCLIC_ACTORS_NAPI_PROFILE ?? "debug";
const source = join(targetRoot, profile, libraryName);
const temporary = await mkdtemp(join(tmpdir(), "acyclic-actors-napi-"));
const bindingPath = join(temporary, `${basename(libraryName)}.node`);
try {
  await copyFile(source, bindingPath);
  await new Promise((resolveChild, rejectChild) => {
    const childEnvironment = {
      ...process.env,
      ACYCLIC_ACTORS_NAPI_CHILD_BINDING: bindingPath,
    };
    if (installedPackage !== undefined) {
      childEnvironment.ACYCLIC_ACTORS_NAPI_INSTALLED_PACKAGE = installedPackage;
    }
    const child = spawn(process.execPath, [fileURLToPath(import.meta.url)], {
      env: childEnvironment,
      stdio: "inherit",
    });
    child.once("error", rejectChild);
    child.once("exit", (code, signal) => {
      if (code === 0) resolveChild();
      else rejectChild(new Error(`N-API child exited with code ${code} and signal ${signal}`));
    });
  });
  if (output !== undefined) {
    // Stage only the private copy loaded by the successful child.
    await mkdir(dirname(output), { recursive: true });
    await mkdir(output);
    const name = `acyclic-actors-${version}-${process.platform}-${process.arch}.node`;
    await copyFile(bindingPath, join(output, name));
    const digest = createHash("sha256");
    for await (const chunk of createReadStream(join(output, name))) digest.update(chunk);
    await writeFile(join(output, "SHA256SUMS"), `${digest.digest("hex")}  ${name}\n`, { flag: "wx" });
  }
} finally {
  await rm(temporary, { recursive: true, force: true });
}

async function qualify(bindingPath) {
  const declarations = await readFile(declarationPath, "utf8");
  if (!declarations.startsWith("/* auto-generated by NAPI-RS */")) {
    throw new Error("Actors N-API declarations are not archived NAPI-RS output");
  }
  if (!declarations.includes("@acyclic-labs/actors/types")) {
    throw new Error("Actors N-API declarations are not bound to the Rust-owned public types");
  }
  for (const exportName of [
    "NativeActorsClient",
    "NativeActorsCancellation",
    "NativeActorsConnectResult",
    "ActorId",
    "CodeSha256",
    "connectResult",
    "createActorResult",
    "updateActorResult",
    "inspectActorResult",
    "addSubscriptionResult",
    "removeSubscriptionResult",
    "resumeSubscriptionResult",
    "checkpointActorResult",
    "invokeActorResult",
  ]) {
    if (!declarations.includes(exportName)) {
      throw new Error(`Actors N-API declarations are missing ${exportName}`);
    }
  }
  const binding = createRequire(import.meta.url)(bindingPath);
  if (typeof binding.NativeActorsClient !== "function") {
    throw new Error("Rust N-API bridge did not export NativeActorsClient");
  }
  if (typeof binding.NativeActorsCancellation !== "function") {
    throw new Error("Rust N-API bridge did not export NativeActorsCancellation");
  }
  if (typeof binding.NativeActorsClient.connectResult !== "function") {
    throw new Error("Rust N-API bridge did not export connectResult");
  }
  for (const method of [
    "createActorResult",
    "updateActorResult",
    "inspectActorResult",
    "addSubscriptionResult",
    "removeSubscriptionResult",
    "resumeSubscriptionResult",
    "checkpointActorResult",
    "invokeActorResult",
  ]) {
    if (typeof binding.NativeActorsClient.prototype[method] !== "function") {
      throw new Error(`Rust N-API bridge did not export ${method}`);
    }
  }
  if (typeof binding.ActorId !== "function" || typeof binding.CodeSha256 !== "function") {
    throw new Error("Rust N-API bridge did not export canonical Actors constructors");
  }
  if (binding.ActorId("actor-1") !== "actor-1") {
    throw new Error("Rust ActorId constructor changed its valid projection");
  }
  try {
    binding.ActorId("");
    throw new Error("Rust ActorId constructor accepted an empty identity");
  } catch (error) {
    if (!String(error).includes("empty_actor_id")) throw error;
  }
  const digest = binding.CodeSha256(new Uint8Array(32).fill(1));
  if (!(digest instanceof Uint8Array) || digest.byteLength !== 32) {
    throw new Error("Rust CodeSha256 constructor changed its valid projection");
  }
  try {
    binding.CodeSha256(new Uint8Array(31));
    throw new Error("Rust CodeSha256 constructor accepted a short digest");
  } catch (error) {
    if (!String(error).includes("invalid_code_sha256")) throw error;
  }
  try {
    binding.CodeSha256(new Uint8Array(32));
    throw new Error("Rust CodeSha256 constructor accepted an all-zero digest");
  } catch (error) {
    if (!String(error).includes("invalid_code_sha256")) throw error;
  }
  if (binding.NativeActorsClient.version() !== version) {
    throw new Error("Actors N-API version does not match the package");
  }
  const cancellation = new binding.NativeActorsCancellation();
  if (cancellation.cancelled) {
    throw new Error("Actors N-API cancellation handle started cancelled");
  }
  cancellation.cancel();
  if (!cancellation.cancelled) {
    throw new Error("Actors N-API cancellation handle did not become cancelled");
  }
  cancellation.cancel();
  if (!cancellation.cancelled) {
    throw new Error("Actors N-API cancellation handle was not monotonic");
  }

  const invalidConnection = await binding.NativeActorsClient.connectResult(
    "https://example.com",
    "",
  );
  if (invalidConnection.client != null) {
    throw new Error("Actors connectResult returned a client for invalid credentials");
  }
  if (invalidConnection.error == null) {
    throw new Error("Actors connectResult omitted configuration error metadata");
  }
  if (invalidConnection.error.code !== "invalid_argument") {
    throw new Error(`Actors connectResult returned ${invalidConnection.error.code} for invalid credentials`);
  }
  if (!String(invalidConnection.error.message).includes("invalid Actors bearer credential")) {
    throw new Error("Actors connectResult lost the Rust configuration error message");
  }

  const cancelledConnection = new binding.NativeActorsCancellation();
  cancelledConnection.cancel();
  const cancelledResult = await binding.NativeActorsClient.connectResult(
    "https://example.com",
    "token",
    cancelledConnection,
  );
  if (cancelledResult.client != null) {
    throw new Error("Actors connectResult returned a client for a cancelled connection");
  }
  if (cancelledResult.error == null || cancelledResult.error.code !== "cancelled") {
    throw new Error("Actors connectResult did not preserve pre-dispatch cancellation metadata");
  }
  if (cancelledResult.error.grpcCode !== 1 || cancelledResult.error.grpcName !== "cancelled") {
    throw new Error("Actors connectResult lost cancellation status metadata");
  }
  const installedPackage = process.env.ACYCLIC_ACTORS_NAPI_INSTALLED_PACKAGE;
  if (installedPackage !== undefined) {
    await qualifyInstalledPackage(installedPackage, bindingPath);
  }
  console.log(`acyclic-actors N-API ABI passed on ${process.platform}-${process.arch}`);
}

async function qualifyInstalledPackage(packageRoot, bindingPath) {
  if (!isAbsolute(packageRoot)) {
    throw new Error("ACYCLIC_ACTORS_NAPI_INSTALLED_PACKAGE must be absolute");
  }
  const packageManifestPath = join(packageRoot, "package.json");
  const packageManifest = JSON.parse(await readFile(packageManifestPath, "utf8"));
  if (packageManifest.version !== version) {
    throw new Error(
      `installed Actors package version ${packageManifest.version} does not match ${version}`,
    );
  }
  const loaderPath = join(packageRoot, "generated", "native", "binding.cjs");
  const loaderSource = await readFile(loaderPath, "utf8");
  if (!loaderSource.includes("/* auto-generated by NAPI-RS */")) {
    throw new Error("installed Actors package has no archived NAPI-RS native loader");
  }
  const nativeExport = packageManifest.exports?.["./native"]?.default;
  if (typeof nativeExport !== "string") {
    throw new Error("installed Actors package does not expose a default ./native entrypoint");
  }
  const nativeEntrypoint = resolve(packageRoot, nativeExport);
  const nativeModule = await import(pathToFileURL(nativeEntrypoint).href);
  if (typeof nativeModule.NativeActorsClient?.connect !== "function") {
    throw new Error("installed Actors package ./native entrypoint did not export NativeActorsClient.connect");
  }
  const rootExport = packageManifest.exports?.["."];
  const rootTarget = typeof rootExport === "string"
    ? rootExport
    : rootExport?.node?.default ?? rootExport?.default;
  if (typeof rootTarget !== "string") {
    throw new Error("installed Actors package does not expose a default Node root entrypoint");
  }
  const rootEntrypoint = resolve(packageRoot, rootTarget);
  const rootModule = await import(pathToFileURL(rootEntrypoint).href);
  if (typeof rootModule.ActorsClient?.connect !== "function") {
    throw new Error("installed Actors package root entrypoint did not export ActorsClient.connect");
  }

  const previousLibraryPath = process.env.NAPI_RS_NATIVE_LIBRARY_PATH;
  process.env.NAPI_RS_NATIVE_LIBRARY_PATH = bindingPath;
  try {
    await expectInvalidCredentialFailure(
      () => nativeModule.NativeActorsClient.connect("https://example.com", ""),
      "installed Actors package ./native",
    );
    await expectInvalidCredentialFailure(
      () => rootModule.ActorsClient.connect({ endpoint: "https://example.com", token: "" }),
      "installed Actors package root",
    );
    await qualifyInstalledTransport(packageRoot, rootModule, nativeModule, packageManifest);
  } finally {
    if (previousLibraryPath === undefined) delete process.env.NAPI_RS_NATIVE_LIBRARY_PATH;
    else process.env.NAPI_RS_NATIVE_LIBRARY_PATH = previousLibraryPath;
  }
  console.log(`acyclic-actors installed package entrypoint passed at ${packageRoot}`);
}

async function qualifyInstalledTransport(packageRoot, rootModule, nativeModule, packageManifest) {
  const protoTarget = packageManifest.exports?.["./proto"]?.default;
  if (typeof protoTarget !== "string") {
    throw new Error("installed Actors package does not expose a default ./proto entrypoint");
  }
  const proto = await import(pathToFileURL(resolve(packageRoot, protoTarget)).href);
  if (typeof proto.CreateActorRequestSchema !== "object") {
    throw new Error("installed Actors package ./proto entrypoint omitted CreateActorRequestSchema");
  }

  const generated = spawnSync(
    "cargo",
    ["run", "--quiet", "--locked", "-p", "acyclic-actors", "--example", "conformance-certificate"],
    { cwd: resolve(dirname(fileURLToPath(import.meta.url)), ".."), encoding: "utf8" },
  );
  if (generated.error || generated.status !== 0) {
    throw new Error(generated.stderr || generated.error?.message || "Actors TLS fixture certificate failed");
  }
  const identity = JSON.parse(generated.stdout);
  let requestSeenResolve;
  let releasePendingResolve;
  const requestSeen = new Promise(resolveSeen => { requestSeenResolve = resolveSeen; });
  const releasePending = new Promise(resolvePending => { releasePendingResolve = resolvePending; });
  const actorObservation = actorId => ({
    actorId,
    codeSha256: new Uint8Array(32).fill(1),
    homeRegion: "local",
    state: 1,
    subscriptions: [],
    checkpointEpoch: 9n,
    configurationRevision: 0n,
  });
  const responseFor = (method, request) => {
    if (method.name === "InvokeActor") return { status: 201, headers: [{ name: "location", value: "/result" }] };
    if (method.name === "CheckpointActor") return { actor: actorObservation("napi-checkpoint") };
    if (method.name === "CreateActor") return { actor: actorObservation(request.idempotencyKey === "napi-success" ? "napi-success" : "napi-createActor") };
    return { actor: actorObservation(`napi-${method.localName}`) };
  };
  const implementation = Object.fromEntries(ActorsService.methods.map(method => [
    method.localName,
    async (request, context) => {
      if (context.requestHeader.get("authorization") !== "Bearer napi-fixture") {
        throw new ConnectError("missing bearer", Code.Unauthenticated);
      }
      if (method.name === "CreateActor" && request.idempotencyKey === "napi-error") {
        throw new ConnectError("fixture operation failure", Code.InvalidArgument);
      }
      if (method.name === "CreateActor" && request.idempotencyKey === "napi-abort") {
        requestSeenResolve();
        await releasePending;
      }
      return create(method.output, responseFor(method, request));
    },
  ]));
  const adapter = connectNodeAdapter({
    routes(router) {
      router.service(ActorsService, implementation);
    },
  });
  const server = createSecureServer({ key: identity.key, cert: identity.certificate }, adapter);
  const sessions = new Set();
  server.on("session", session => {
    sessions.add(session);
    session.once("close", () => sessions.delete(session));
  });
  await new Promise((resolveListen, rejectListen) => {
    server.once("error", rejectListen);
    server.listen(0, "127.0.0.1", resolveListen);
  });
  try {
    const port = server.address().port;
    const client = await rootModule.ActorsClient.connect({
      endpoint: `https://localhost:${port}`,
      token: "napi-fixture",
      caCertificate: new TextEncoder().encode(identity.certificate),
    });
    if (client.transport !== "grpc") {
      throw new Error(`installed Actors root selected ${client.transport}, expected grpc`);
    }
    const actorRequest = values => create(proto.CreateActorRequestSchema, {
      codeSha256: new Uint8Array(32).fill(1),
      homeRegion: "local",
      idempotencyKey: values.idempotencyKey,
      limits: { handlerTimeoutMillis: 1000n, memoryBytes: 1024n, checkpointBytes: 1024n },
    });
    const success = await client.createActor(actorRequest({ idempotencyKey: "napi-success" }));
    if (success.actor?.actorId !== "napi-success") {
      throw new Error("installed Actors root did not return the local fixture response");
    }

    const requests = {
      updateActor: create(proto.UpdateActorRequestSchema, {
        actorId: "actor-a", codeSha256: new Uint8Array(32).fill(1), expectedConfigurationRevision: 0n,
        idempotencyKey: "napi-update",
      }),
      inspectActor: create(proto.InspectActorRequestSchema, { actorId: "actor-a" }),
      addSubscription: create(proto.AddSubscriptionRequestSchema, {
        actorId: "actor-a", subscription: { subscriptionId: "input", streamPath: "events/input" }, idempotencyKey: "napi-add",
      }),
      removeSubscription: create(proto.RemoveSubscriptionRequestSchema, {
        actorId: "actor-a", subscriptionId: "input", idempotencyKey: "napi-remove",
      }),
      resumeSubscription: create(proto.ResumeSubscriptionRequestSchema, {
        actorId: "actor-a", subscriptionId: "input", idempotencyKey: "napi-resume",
      }),
      checkpointActor: create(proto.CheckpointActorRequestSchema, {
        actorId: "actor-a", idempotencyKey: "napi-checkpoint",
      }),
      invokeActor: create(proto.InvokeActorRequestSchema, {
        actorId: "actor-a", method: "GET", url: "/", body: new Uint8Array(), headers: [],
      }),
    };
    for (const [method, input] of Object.entries(requests)) {
      const response = await client[method](input);
      if (method === "invokeActor") {
        if (response.status !== 201) throw new Error("installed Actors root lost InvokeActor status");
      } else if (response.actor?.actorId !== `napi-${method}`) {
        throw new Error(`installed Actors root did not return the ${method} fixture response`);
      }
    }

    let structured;
    try {
      await client.createActor(actorRequest({ idempotencyKey: "napi-error" }));
    } catch (error) {
      structured = error;
    }
    if (structured?.code !== "invalid_argument" || structured.grpcCode !== 3 || structured.grpcName !== "invalid_argument") {
      throw new Error("installed Actors root did not preserve structured operation error metadata");
    }

    if (await nativeModule.ActorId("actor-interop") !== "actor-interop") {
      throw new Error("installed Actors native ActorId wrapper changed its projection");
    }
    const interopDigest = await nativeModule.CodeSha256(new Uint8Array(32).fill(2));
    if (!(interopDigest instanceof Uint8Array) || interopDigest.length !== 32 || interopDigest[0] !== 2) {
      throw new Error("installed Actors native CodeSha256 wrapper changed its projection");
    }
    if (await nativeModule.PositiveU64(2n ** 63n) !== 2n ** 63n) {
      throw new Error("installed Actors native PositiveU64 wrapper lost bigint precision");
    }

    const controller = new AbortController();
    const pending = client.createActor(actorRequest({ idempotencyKey: "napi-abort" }), controller.signal);
    await requestSeen;
    controller.abort();
    let cancellation;
    try {
      await pending;
    } catch (error) {
      cancellation = error;
    } finally {
      releasePendingResolve();
    }
    if (cancellation === undefined || cancellation.code !== "cancelled") {
      throw new Error("installed Actors root did not preserve in-flight cancellation");
    }
  } finally {
    releasePendingResolve();
    for (const session of sessions) session.destroy();
    await new Promise(resolveClose => server.close(resolveClose));
  }
}

async function expectInvalidCredentialFailure(connect, label) {
  let packageError;
  try {
    await connect();
  } catch (error) {
    packageError = error;
  }
  if (packageError === undefined) {
    throw new Error(`${label} accepted invalid credentials`);
  }
  if (packageError.code !== "invalid_argument") {
    throw new Error(`${label} returned ${packageError.code} for invalid credentials`);
  }
  if (!String(packageError.message).includes("invalid Actors bearer credential")) {
    throw new Error(`${label} lost the Rust configuration error message`);
  }
}
