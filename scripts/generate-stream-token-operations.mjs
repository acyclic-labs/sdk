export const rust = [["acyclic-stream", "example", "token-operations"]];

export function render([stdout]) {
  const operations = JSON.parse(stdout);
  if (!Array.isArray(operations) || operations.length === 0 || operations.some(row => typeof row.operation !== "string" || row.operation.length === 0 || !Array.isArray(row.actions) || row.actions.length === 0 || row.actions.some(action => typeof action !== "string"))) {
    throw new Error("Rust Stream token admission must declare an operation and its actions");
  }
  if (new Set(operations.map(row => row.operation)).size !== operations.length) {
    throw new Error("Rust Stream token operation inventory contains duplicates");
  }
  return {
    "typescript/packages/stream/src/token-operations.ts": `// @generated by scripts/generate-stream-token-operations.mjs; do not edit.\n\n` +
      `export const TOKEN_AUTHORIZATION = ${JSON.stringify(operations, null, 2)} as const;\n` +
      `export type TokenOperation = typeof TOKEN_AUTHORIZATION[number]["operation"];\n`,
  };
}
