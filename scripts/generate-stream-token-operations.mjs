export const rust = [["acyclic-stream", "example", "token-operations"]];

export function render([stdout]) {
  const operations = JSON.parse(stdout);
  if (!Array.isArray(operations) || operations.length === 0 || operations.some(operation => typeof operation !== "string" || operation.length === 0)) {
    throw new Error("Rust Stream token operation inventory must be a non-empty string array");
  }
  if (new Set(operations).size !== operations.length) {
    throw new Error("Rust Stream token operation inventory contains duplicates");
  }
  const values = operations.map(operation => JSON.stringify(operation)).join(", ");
  return {
    "typescript/packages/stream/src/token-operations.ts": `// @generated by scripts/generate-stream-token-operations.mjs; do not edit.\n\n` +
      `export const TOKEN_OPERATIONS = [${values}] as const;\n` +
      `export type TokenOperation = (typeof TOKEN_OPERATIONS)[number];\n`,
  };
}
