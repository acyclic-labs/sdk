import { existsSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { spawnSync } from "node:child_process";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const scriptPath = fileURLToPath(import.meta.url);
const outputRelativePath = "typescript/packages/stream/src/token-operations.ts";

function readRustOperations(root) {
  const result = spawnSync(
    process.env.ACYCLIC_CARGO_BIN || "cargo",
    [
      "run", "--manifest-path", join(root, "Cargo.toml"),
      "--package", "acyclic-stream", "--example", "token-operations",
      "--no-default-features", "--locked", "--quiet",
    ],
    { cwd: root, encoding: "utf8" },
  );
  if (result.status !== 0) {
    process.stderr.write(result.stdout ?? "");
    process.stderr.write(result.stderr ?? "");
    throw new Error(`Rust Stream token operation generator failed with status ${result.status ?? "unknown"}`);
  }
  const lines = (result.stdout ?? "").trim().split(/\r?\n/).filter(Boolean);
  const json = lines.at(-1);
  if (!json) throw new Error("Rust Stream token operation generator produced no JSON");
  let operations;
  try {
    operations = JSON.parse(json);
  } catch (error) {
    throw new Error(`Rust Stream token operation generator produced invalid JSON: ${error}`);
  }
  if (!Array.isArray(operations) || operations.length === 0 || operations.some(operation => typeof operation !== "string" || operation.length === 0)) {
    throw new Error("Rust Stream token operation inventory must be a non-empty string array");
  }
  if (new Set(operations).size !== operations.length) {
    throw new Error("Rust Stream token operation inventory contains duplicates");
  }
  return operations;
}

function renderSource(root) {
  const operations = readRustOperations(root);
  const values = operations.map(operation => JSON.stringify(operation)).join(", ");
  return `// @generated by scripts/generate-stream-token-operations.mjs; do not edit.\n\n` +
    `export const TOKEN_OPERATIONS = [${values}] as const;\n` +
    `export type TokenOperation = (typeof TOKEN_OPERATIONS)[number];\n`;
}

export function generateStreamTokenOperations(root, outputDirectory) {
  const output = outputDirectory ?? join(root, "typescript/packages/stream/src");
  writeFileSync(join(output, "token-operations.ts"), renderSource(root));
}

export function checkStreamTokenOperations(root) {
  const temporary = mkdtempSync(join(tmpdir(), "acyclic-stream-token-operations-"));
  try {
    generateStreamTokenOperations(root, temporary);
    const committed = join(root, outputRelativePath);
    if (!existsSync(committed) || !readFileSync(join(temporary, "token-operations.ts")).equals(readFileSync(committed))) {
      throw new Error("Stream token operations are stale; run bun run generate");
    }
  } finally {
    rmSync(temporary, { recursive: true, force: true });
  }
}

if (resolve(process.argv[1] ?? "") === resolve(scriptPath)) {
  const root = join(dirname(scriptPath), "..");
  const mode = process.argv[2] ?? "write";
  if (mode === "check") checkStreamTokenOperations(root);
  else if (mode === "write") generateStreamTokenOperations(root);
  else throw new Error(`unknown mode: ${mode}`);
}
