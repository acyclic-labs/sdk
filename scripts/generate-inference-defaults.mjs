export const rust = [["acyclic-inference", "example", "inference-typescript-defaults"]];

export function render([stdout]) {
  const values = stdout.trim().split(/\s+/);
  if (values.length !== 1 || values.some(value => !/^\d+$/.test(value))) {
    throw new Error("Rust inference defaults generator produced invalid byte ceilings");
  }
  const [maximumMessageBytes] = values.map(Number);
  if (![maximumMessageBytes].every(value => Number.isSafeInteger(value) && value > 0)) {
    throw new Error("Rust inference byte ceilings are not positive safe integers");
  }
  const header = "// @generated by scripts/generate-inference-defaults.mjs; do not edit.\n\n";
  return {
    "typescript/packages/inference/generated/defaults.js": `${header}export const MAXIMUM_MESSAGE_BYTES = ${maximumMessageBytes};\n`,
    "typescript/packages/inference/generated/defaults.d.ts": `${header}export declare const MAXIMUM_MESSAGE_BYTES: number;\n`,
  };
}
