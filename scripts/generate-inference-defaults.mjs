import { existsSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { spawnSync } from "node:child_process";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const scriptPath = fileURLToPath(import.meta.url);

function readRustDefault(root) {
  const result = spawnSync(
    process.env.ACYCLIC_CARGO_BIN || "cargo",
    [
      "run",
      "--manifest-path", join(root, "Cargo.toml"),
      "--package", "acyclic-inference",
      "--example", "inference-typescript-defaults",
      "--no-default-features",
      "--locked",
      "--quiet",
    ],
    { cwd: root, encoding: "utf8" },
  );
  if (result.status !== 0) {
    process.stderr.write(result.stdout ?? "");
    process.stderr.write(result.stderr ?? "");
    throw new Error(`Rust inference defaults generator failed with status ${result.status ?? "unknown"}`);
  }
  const value = (result.stdout ?? "").trim().split(/\r?\n/).filter(Boolean).at(-1);
  if (value === undefined || !/^\d+$/.test(value)) {
    throw new Error("Rust inference defaults generator produced an invalid byte ceiling");
  }
  const number = Number(value);
  if (!Number.isSafeInteger(number) || number <= 0) {
    throw new Error("Rust inference byte ceiling is not a positive safe integer");
  }
  return number;
}

function renderSources(root) {
  const maximumMessageBytes = readRustDefault(root);
  const header = "// @generated by scripts/generate-inference-defaults.mjs; do not edit.\n\n";
  return {
    source: `${header}export const MAXIMUM_MESSAGE_BYTES = ${maximumMessageBytes};\n`,
    declaration: `${header}export declare const MAXIMUM_MESSAGE_BYTES: number;\n`,
  };
}

export function generateInferenceDefaults(root, outputDirectory) {
  const output = outputDirectory ?? join(root, "typescript/packages/inference/generated");
  const { source, declaration } = renderSources(root);
  writeFileSync(join(output, "defaults.js"), source);
  writeFileSync(join(output, "defaults.d.ts"), declaration);
}

export function checkInferenceDefaults(root) {
  const temporary = mkdtempSync(join(tmpdir(), "acyclic-inference-defaults-"));
  try {
    generateInferenceDefaults(root, temporary);
    for (const file of ["defaults.js", "defaults.d.ts"]) {
      const committed = join(root, "typescript/packages/inference/generated", file);
      if (!existsSync(committed) || !readFileSync(join(temporary, file)).equals(readFileSync(committed))) {
        throw new Error(`inference defaults are stale; run bun run generate (${file})`);
      }
    }
  } finally {
    rmSync(temporary, { recursive: true, force: true });
  }
}

if (resolve(process.argv[1] ?? "") === resolve(scriptPath)) {
  const root = join(dirname(scriptPath), "..");
  const mode = process.argv[2] ?? "write";
  if (mode === "check") checkInferenceDefaults(root);
  else if (mode === "write") generateInferenceDefaults(root);
  else throw new Error(`unknown mode: ${mode}`);
}
