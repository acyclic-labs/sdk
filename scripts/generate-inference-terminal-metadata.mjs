import { existsSync, readFileSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { spawnSync } from "node:child_process";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const scriptPath = fileURLToPath(import.meta.url);

async function readRustMetadata(root) {
  // Run the current Rust source directly. Reading generated WASM here would
  // allow an ignored or stale artifact to hide descriptor and option drift.
  const result = spawnSync(
    process.env.ACYCLIC_CARGO_BIN || "cargo",
    [
      "run",
      "--manifest-path", join(root, "Cargo.toml"),
      "--package", "acyclic-inference-wasm",
      "--example", "inference-typescript-terminal-metadata",
      "--locked",
      "--quiet",
    ],
    { cwd: root, encoding: "utf8" },
  );
  if (result.status !== 0) {
    process.stderr.write(result.stdout ?? "");
    process.stderr.write(result.stderr ?? "");
    throw new Error(`Rust inference terminal metadata generator failed with status ${result.status ?? "unknown"}`);
  }
  const raw = (result.stdout ?? "").trim().split(/\r?\n/).filter(Boolean).at(-1);
  if (raw === undefined) throw new Error("Rust inference terminal metadata generator produced no JSON");
  let metadata;
  try {
    metadata = JSON.parse(raw);
  } catch (error) {
    throw new Error(`Rust inference terminal metadata is not JSON: ${String(error)}`);
  }
  if (!Array.isArray(metadata) || metadata.length === 0 || metadata.some(item =>
    item === null || typeof item !== "object" ||
    !Number.isSafeInteger(item.number) || item.number <= 0 ||
    typeof item.kind !== "string" || !/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(item.kind) ||
    typeof item.partial !== "boolean")) {
    throw new Error("Rust inference terminal metadata has an invalid entry");
  }
  if (new Set(metadata.map(item => item.number)).size !== metadata.length ||
      new Set(metadata.map(item => item.kind)).size !== metadata.length) {
    throw new Error("Rust inference terminal metadata has duplicate descriptors");
  }
  return metadata;
}

async function renderSources(root) {
  const metadata = await readRustMetadata(root);
  const header = "// @generated by scripts/generate-inference-terminal-metadata.mjs; do not edit.\n\n";
  const entries = metadata.map(item => `  Object.freeze(${JSON.stringify(item)})`).join(",\n");
  const kinds = metadata.map(item => JSON.stringify(item.kind)).join(" | ");
  return {
    source: `${header}export const RUN_TERMINAL_METADATA = Object.freeze([\n${entries}\n]);\n`,
    declaration: `${header}export type RunTerminalKind = ${kinds};\n` +
      "export interface RunTerminalMetadata {\n" +
      "  readonly number: number;\n" +
      "  readonly kind: RunTerminalKind;\n" +
      "  readonly partial: boolean;\n" +
      "}\n" +
      "export declare const RUN_TERMINAL_METADATA: readonly RunTerminalMetadata[];\n",
  };
}

export async function generateInferenceTerminalMetadata(root, outputDirectory) {
  const output = outputDirectory ?? join(root, "typescript/packages/inference/generated");
  const { source, declaration } = await renderSources(root);
  writeFileSync(join(output, "terminal-metadata.js"), source);
  writeFileSync(join(output, "terminal-metadata.d.ts"), declaration);
}

export async function checkInferenceTerminalMetadata(root) {
  const temporary = mkdtempSync(join(root, ".tmp-inference-terminal-metadata-"));
  try {
    await generateInferenceTerminalMetadata(root, temporary);
    for (const file of ["terminal-metadata.js", "terminal-metadata.d.ts"]) {
      const committed = join(root, "typescript/packages/inference/generated", file);
      if (!existsSync(committed) ||
          !readFileSync(join(temporary, file)).equals(readFileSync(committed))) {
        throw new Error(`inference terminal metadata is stale; run bun run generate (${file})`);
      }
    }
  } finally {
    rmSync(temporary, { recursive: true, force: true });
  }
}

if (resolve(process.argv[1] ?? "") === resolve(scriptPath)) {
  const root = join(dirname(scriptPath), "..");
  const mode = process.argv[2] ?? "write";
  if (mode === "check") await checkInferenceTerminalMetadata(root);
  else if (mode === "write") await generateInferenceTerminalMetadata(root);
  else throw new Error(`unknown mode: ${mode}`);
}
