import assert from "node:assert/strict";
import { chmodSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import test from "node:test";
import {
  affectedTargets, bazelLabel, changedPathsFromGit, isGlobalInput, parseLabels, selectionExpression,
} from "./affected-bazel-targets.mjs";

const GENERATED = "# Generated by scripts/bazel-build-files.mjs from the Cargo manifests. Do not edit.\n";
const fixture = () => mkdtempSync(join(tmpdir(), "affected-bazel-targets-"));
const put = (root, path, content = "") => {
  mkdirSync(resolve(root, path, ".."), { recursive: true });
  writeFileSync(resolve(root, path), content);
};

test("build inputs every target reads select every test", () => {
  for (const path of ["MODULE.bazel", "MODULE.bazel.lock", "cargo.MODULE.bazel", "REPO.bazel", ".bazelrc", ".bazelversion", "BUILD.bazel",
    "rust/crates/a/BUILD.bazel", "toolchains/windows/BUILD.bazel", "windows_paths.bzl",
    "scripts/bazel-build-files.mjs", "rust/vendor/napi-3.15.0/BUILD.bazel", "patches/foo.patch",
    "cargo-bazel-lock.json", "cargo-bazel.Cargo.lock", "cargo-wasm-bazel-lock.json", "cargo-wasm-bazel.Cargo.lock"]) {
    assert.equal(isGlobalInput(path), true, path);
  }
  for (const path of ["rust/crates/a/src/lib.rs", "docs/readme.md", "scripts/affected-bazel-targets.mjs"]) {
    assert.equal(isGlobalInput(path), false, path);
  }
});

test("a generated package names the changed file, a hand-written or deleted one names the package", () => {
  const root = fixture();
  try {
    put(root, "BUILD.bazel", GENERATED);
    put(root, "rust/crates/a/BUILD.bazel", GENERATED);
    put(root, "rust/crates/a/src/lib.rs");
    put(root, "rust/crates/a/fuzz/BUILD.bazel", GENERATED);
    put(root, "rust/crates/a/fuzz/src/lib.rs");
    put(root, "plugin/BUILD.bazel", "load(\":x.bzl\", \"x\")\n");
    put(root, "plugin/src/lib.rs");
    put(root, "docs/readme.md");
    assert.equal(bazelLabel(root, "rust/crates/a/src/lib.rs"), "//rust/crates/a:src/lib.rs");
    assert.equal(bazelLabel(root, "rust/crates/a/fuzz/src/lib.rs"), "//rust/crates/a/fuzz:src/lib.rs");
    assert.equal(bazelLabel(root, "plugin/src/lib.rs"), "//plugin:all");
    assert.equal(bazelLabel(root, "rust/crates/a/src/deleted.rs"), "//rust/crates/a:all");
    assert.equal(bazelLabel(root, "docs/readme.md"), "//:docs/readme.md");
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
});

test("the query is rdeps over the changed files, or every test for a global input", () => {
  assert.equal(selectionExpression([], true), "tests(//...)");
  assert.equal(selectionExpression([], false), undefined);
  assert.equal(selectionExpression(["//b:src/lib.rs", "//a:src/lib.rs"], false),
    "tests(rdeps(//..., set(//a:src/lib.rs //b:src/lib.rs)))");
  assert.deepEqual(parseLabels("@@//b:test\n//a:test\n//a:test\n"), ["//a:test", "//b:test"]);
});

test("affected targets query only the changed packages and never query an empty selection", () => {
  const root = fixture();
  try {
    put(root, "BUILD.bazel", GENERATED);
    put(root, "rust/crates/a/BUILD.bazel", GENERATED);
    put(root, "rust/crates/a/src/lib.rs");
    const expressions = [];
    const query = expression => {
      expressions.push(expression);
      return "//rust/crates/a:test\n//rust/crates/b:test\n";
    };
    assert.deepEqual(affectedTargets({ root, changed: ["rust/crates/a/src/lib.rs"], query }),
      ["//rust/crates/a:test", "//rust/crates/b:test"]);
    assert.deepEqual(expressions, ["tests(rdeps(//..., set(//rust/crates/a:src/lib.rs)))"]);
    assert.deepEqual(affectedTargets({ root, changed: ["rust/crates/a/src/deleted.rs"], query }),
      ["//rust/crates/a:test", "//rust/crates/b:test"]);
    assert.equal(expressions[1], "tests(rdeps(//..., set(//rust/crates/a:all)))");
    assert.deepEqual(affectedTargets({ root, changed: ["MODULE.bazel"], query }),
      ["//rust/crates/a:test", "//rust/crates/b:test"]);
    assert.equal(expressions[2], "tests(//...)");
    assert.deepEqual(affectedTargets({ root, changed: [], query }), []);
    assert.equal(expressions.length, 3);
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
});

test("the command maps a base..head diff through the Bazel query", () => {
  const root = fixture();
  try {
    put(root, "BUILD.bazel", GENERATED);
    put(root, "rust/crates/a/BUILD.bazel", GENERATED);
    put(root, "rust/crates/a/src/lib.rs", "one\n");
    const git = args => {
      const result = spawnSync("git", args, { cwd: root, encoding: "utf8" });
      assert.equal(result.status, 0, result.stderr);
      return result.stdout.trim();
    };
    git(["init", "--quiet"]);
    git(["add", "."]);
    git(["-c", "commit.gpgsign=false", "-c", "user.name=Fixture", "-c", "user.email=fixture@example.invalid",
      "commit", "--quiet", "-m", "base"]);
    put(root, "rust/crates/a/src/lib.rs", "two\n");
    put(root, "rust/crates/a/src/naïve.rs", "two\n");
    git(["add", "."]);
    git(["-c", "commit.gpgsign=false", "-c", "user.name=Fixture", "-c", "user.email=fixture@example.invalid",
      "commit", "--quiet", "-m", "head"]);
    assert.deepEqual(changedPathsFromGit("HEAD~1", "HEAD", { cwd: root }),
      ["rust/crates/a/src/lib.rs", "rust/crates/a/src/naïve.rs"]);
    const capture = join(root, "query.txt");
    const bazel = join(root, "bazel");
    writeFileSync(bazel, `#!/bin/sh\nprintf '%s\\n' "$@" > ${JSON.stringify(capture)}\nprintf '//rust/crates/a:test\\n'\n`);
    chmodSync(bazel, 0o755);
    const run = args => spawnSync(process.execPath, [fileURLToPath(new URL("./affected-bazel-targets.mjs", import.meta.url)), "--root", root, ...args], {
      cwd: fileURLToPath(new URL("..", import.meta.url)), env: { ...process.env, ACYCLIC_BAZEL: bazel }, encoding: "utf8",
    });
    const selected = run(["--base", "HEAD~1", "--head", "HEAD", "--json"]);
    assert.equal(selected.status, 0, selected.stderr);
    assert.deepEqual(JSON.parse(selected.stdout), ["//rust/crates/a:test"]);
    assert.ok(readFileSync(capture, "utf8").includes(
      "tests(rdeps(//..., set(//rust/crates/a:src/lib.rs //rust/crates/a:src/naïve.rs)))"));
    const count = run(["--base", "HEAD~1", "--head", "HEAD", "--count"]);
    assert.equal(count.status, 0, count.stderr);
    assert.equal(count.stdout.trim(), "1");
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
});
