import { existsSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { spawnSync } from "node:child_process";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const scriptPath = fileURLToPath(import.meta.url);
const KINDS = new Set([
  "observation", "sequence", "append", "fork",
  "records", "children", "children_page", "commit", "envelope", "token",
]);

function readRustContract(root) {
  const result = spawnSync(
    process.env.ACYCLIC_CARGO_BIN || "cargo",
    [
      "run", "--manifest-path", join(root, "Cargo.toml"),
      "--package", "acyclic-stream", "--bin", "stream-http-contract",
      "--no-default-features", "--locked", "--quiet",
    ],
    { cwd: root, encoding: "utf8" },
  );
  if (result.status !== 0) {
    process.stderr.write(result.stdout ?? "");
    process.stderr.write(result.stderr ?? "");
    throw new Error(`Rust Stream HTTP contract generator failed with status ${result.status ?? "unknown"}`);
  }
  const lines = (result.stdout ?? "").trim().split(/\r?\n/).filter(Boolean);
  const json = lines.at(-1);
  if (!json) throw new Error("Rust Stream HTTP contract generator produced no JSON");
  const contract = JSON.parse(json);
  if (!Array.isArray(contract) || contract.some(entry =>
    !Array.isArray(entry) || entry.length !== 2 || typeof entry[0] !== "string" ||
    typeof entry[1] !== "string" || !KINDS.has(entry[1]))) {
    throw new Error("Rust Stream HTTP contract has an invalid shape");
  }
  return contract;
}

function renderSources(root) {
  const contract = readRustContract(root);
  const routes = contract.map(([route, kind]) => `  ${JSON.stringify(route)}: ${JSON.stringify(kind)},`).join("\n");
  const header = "// @generated by scripts/generate-stream-http-contract.mjs; do not edit.\n\n";
  const source = `${header}import { decodeHttpResponse as decodeHttpResponseWasm } from "../generated/wasm/acyclic_stream_wasm.js";
import type {
  AccessToken, AppendResult, ChildrenPage, CommittedEnvelope, EncodedRecord, ForkReceipt,
  IdempotencyObservation, CommitResult, Sequence,
} from "./types.js";

export const HTTP_RESPONSE_CONTRACT = Object.freeze({
${routes}
} as const);

export type HttpRoute = keyof typeof HTTP_RESPONSE_CONTRACT;

type HttpResponseByKind = {
  observation: IdempotencyObservation | undefined;
  sequence: Sequence;
  append: AppendResult;
  fork: ForkReceipt;
  records: readonly EncodedRecord[];
  children: readonly { readonly path: string }[];
  children_page: ChildrenPage;
  commit: CommitResult;
  envelope: CommittedEnvelope;
  token: AccessToken;
};

export type HttpResponseFor<Route extends HttpRoute> =
  HttpResponseByKind[typeof HTTP_RESPONSE_CONTRACT[Route]];

/**
 * Decode one Rust-validated hosted response with the route-specific public
 * result type derived from the canonical route/family table above.
 *
 * The implementation intentionally remains unknown at this boundary: the
 * Rust/WASM decoder owns runtime validation and projection, while these
 * overloads carry its generated route association into the TypeScript API.
 */
export function decodeHttpResponseFor<Route extends HttpRoute>(
  route: Route,
  responseJson: string,
): HttpResponseFor<Route>;
export function decodeHttpResponseFor(route: string, responseJson: string): unknown {
  return decodeHttpResponseWasm(route, responseJson);
}
`;
  return { source };
}

export function generateStreamHttpContract(root, outputDirectory) {
  const output = outputDirectory ?? join(root, "typescript/packages/stream/src");
  writeFileSync(join(output, "http-contract.ts"), renderSources(root).source);
}

export function checkStreamHttpContract(root) {
  const temporary = mkdtempSync(join(tmpdir(), "acyclic-stream-http-contract-"));
  try {
    generateStreamHttpContract(root, temporary);
    const committed = join(root, "typescript/packages/stream/src/http-contract.ts");
    if (!existsSync(committed) || !readFileSync(join(temporary, "http-contract.ts")).equals(readFileSync(committed))) {
      throw new Error("Stream HTTP contract is stale; run bun run generate");
    }
  } finally {
    rmSync(temporary, { recursive: true, force: true });
  }
}

if (resolve(process.argv[1] ?? "") === resolve(scriptPath)) {
  const root = join(dirname(scriptPath), "..");
  const mode = process.argv[2] ?? "write";
  if (mode === "check") checkStreamHttpContract(root);
  else if (mode === "write") generateStreamHttpContract(root);
  else throw new Error(`unknown mode: ${mode}`);
}
