const KINDS = new Set([
  "observation", "sequence", "append", "fork",
  "records", "children", "children_page", "commit", "envelope", "token",
]);

export const rust = [["acyclic-stream", "bin", "stream-http-contract"]];

function readRustContract(stdout) {
  const contract = JSON.parse(stdout);
  if (!Array.isArray(contract) || contract.some(entry =>
    !Array.isArray(entry) || entry.length !== 2 || typeof entry[0] !== "string" ||
    typeof entry[1] !== "string" || !KINDS.has(entry[1]))) {
    throw new Error("Rust Stream HTTP contract has an invalid shape");
  }
  return contract;
}

export function render([stdout]) {
  const contract = readRustContract(stdout);
  const routes = contract.map(([route, kind]) => `  ${JSON.stringify(route)}: ${JSON.stringify(kind)},`).join("\n");
  const header = "// @generated by scripts/generate-stream-http-contract.mjs; do not edit.\n\n";
  const source = `${header}import { decodeHttpResponse as decodeHttpResponseWasm } from "../generated/wasm/acyclic_stream_wasm.js";
import type {
  AccessToken, AppendResult, ChildrenPage, CommittedEnvelope, EncodedRecord, ForkReceipt,
  IdempotencyObservation, CommitResult, Sequence,
} from "./types.js";

export const HTTP_RESPONSE_CONTRACT = Object.freeze({
${routes}
} as const);

export type HttpRoute = keyof typeof HTTP_RESPONSE_CONTRACT;

type HttpResponseByKind = {
  observation: IdempotencyObservation | undefined;
  sequence: Sequence;
  append: AppendResult;
  fork: ForkReceipt;
  records: readonly EncodedRecord[];
  children: readonly { readonly path: string }[];
  children_page: ChildrenPage;
  commit: CommitResult;
  envelope: CommittedEnvelope;
  token: AccessToken;
};

export type HttpResponseFor<Route extends HttpRoute> =
  HttpResponseByKind[typeof HTTP_RESPONSE_CONTRACT[Route]];

/**
 * Decode one Rust-validated hosted response with the route-specific public
 * result type derived from the canonical route/family table above.
 *
 * The implementation intentionally remains unknown at this boundary: the
 * Rust/WASM decoder owns runtime validation and projection, while these
 * overloads carry its generated route association into the TypeScript API.
 */
export function decodeHttpResponseFor<Route extends HttpRoute>(
  route: Route,
  responseJson: string,
): HttpResponseFor<Route>;
export function decodeHttpResponseFor(route: string, responseJson: string): unknown {
  return decodeHttpResponseWasm(route, responseJson);
}
`;
  return { "typescript/packages/stream/src/http-contract.ts": source };
}
