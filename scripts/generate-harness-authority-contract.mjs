import { existsSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { spawnSync } from "node:child_process";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const scriptPath = fileURLToPath(import.meta.url);

function readRustContract(root) {
  const result = spawnSync(
    process.env.ACYCLIC_CARGO_BIN || "cargo",
    [
      "run",
      "--manifest-path", join(root, "Cargo.toml"),
      "--package", "acyclic-harness",
      "--example", "authority-id-contract",
      "--no-default-features",
      "--locked",
      "--quiet",
    ],
    { cwd: root, encoding: "utf8" },
  );
  if (result.status !== 0) {
    process.stderr.write(result.stdout ?? "");
    process.stderr.write(result.stderr ?? "");
    throw new Error(`Rust Harness authority contract generator failed with status ${result.status ?? "unknown"}`);
  }
  const jsonLine = (result.stdout ?? "").trim().split(/\r?\n/).filter(Boolean).at(-1);
  if (!jsonLine) throw new Error("Rust Harness authority contract generator produced no JSON");
  const contract = JSON.parse(jsonLine);
  if (!Array.isArray(contract.forbidden_exact) ||
      !contract.forbidden_exact.every(value => typeof value === "string" && value.length > 0) ||
      new Set(contract.forbidden_exact).size !== contract.forbidden_exact.length) {
    throw new Error("Harness authority contract has invalid exact values");
  }
  if (!Array.isArray(contract.forbidden_separators) ||
      !contract.forbidden_separators.every(value => typeof value === "string" && [...value].length === 1) ||
      new Set(contract.forbidden_separators).size !== contract.forbidden_separators.length) {
    throw new Error("Harness authority contract has invalid separators");
  }
  if (!Array.isArray(contract.control_ranges) || contract.control_ranges.some(range =>
    !Array.isArray(range) || range.length !== 2 ||
    !Number.isInteger(range[0]) || !Number.isInteger(range[1]) ||
    range[0] < 0 || range[1] < range[0] || range[1] > 0x10ffff)) {
    throw new Error("Harness authority contract has invalid control ranges");
  }
  return contract;
}

function renderSource(root) {
  const contract = readRustContract(root);
  const header = "// @generated by scripts/generate-harness-authority-contract.mjs; do not edit.\n\n";
  const source = `${header}` +
    `const FORBIDDEN_EXACT = new Set(${JSON.stringify(contract.forbidden_exact)});\n` +
    `const FORBIDDEN_SEPARATORS = new Set(${JSON.stringify(contract.forbidden_separators)});\n` +
    `const CONTROL_RANGES = ${JSON.stringify(contract.control_ranges)} as readonly (readonly [number, number])[];\n\n` +
    `/** Mirrors Rust Authority::stream_path without requiring asynchronous WASM initialization. */\n` +
    `export function isSafeAuthorityId(value: string): boolean {\n` +
    `  if (value.length === 0 || FORBIDDEN_EXACT.has(value)) return false;\n` +
    `  for (const character of value) {\n` +
    `    const codePoint = character.codePointAt(0);\n` +
    `    if (codePoint === undefined || (codePoint >= 0xd800 && codePoint <= 0xdfff) ||\n` +
    `      FORBIDDEN_SEPARATORS.has(character) ||\n` +
    `      CONTROL_RANGES.some(([start, end]) => codePoint >= start && codePoint <= end)) return false;\n` +
    `  }\n` +
    `  return true;\n` +
    `}\n`;
  return source;
}

export function generateHarnessAuthorityContract(root, outputDirectory) {
  const output = outputDirectory ?? join(root, "typescript/packages/harness/src");
  writeFileSync(join(output, "authority-contract.ts"), renderSource(root));
}

export function checkHarnessAuthorityContract(root) {
  const temporary = mkdtempSync(join(tmpdir(), "acyclic-harness-authority-contract-"));
  try {
    generateHarnessAuthorityContract(root, temporary);
    const committed = join(root, "typescript/packages/harness/src/authority-contract.ts");
    if (!existsSync(committed) || !readFileSync(join(temporary, "authority-contract.ts")).equals(readFileSync(committed))) {
      throw new Error("Harness authority contract is stale; run bun run generate");
    }
  } finally {
    rmSync(temporary, { recursive: true, force: true });
  }
}

if (resolve(process.argv[1] ?? "") === resolve(scriptPath)) {
  const root = join(dirname(scriptPath), "..");
  const mode = process.argv[2] ?? "write";
  if (mode === "check") checkHarnessAuthorityContract(root);
  else if (mode === "write") generateHarnessAuthorityContract(root);
  else throw new Error(`unknown mode: ${mode}`);
}
