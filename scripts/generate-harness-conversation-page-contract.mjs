import { existsSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { spawnSync } from "node:child_process";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const scriptPath = fileURLToPath(import.meta.url);
const outputRelativePath = "typescript/packages/harness/src/conversation-page-contract.ts";

function readRustContract(root) {
  const result = spawnSync(
    process.env.ACYCLIC_CARGO_BIN || "cargo",
    [
      "run", "--manifest-path", join(root, "Cargo.toml"), "--package", "acyclic-harness",
      "--example", "conversation-page-contract", "--no-default-features", "--locked", "--quiet",
    ],
    { cwd: root, encoding: "utf8" },
  );
  if (result.status !== 0) {
    process.stderr.write(result.stdout ?? "");
    process.stderr.write(result.stderr ?? "");
    throw new Error(`Rust Harness conversation page contract generator failed with status ${result.status ?? "unknown"}`);
  }
  const jsonLine = (result.stdout ?? "").trim().split(/\r?\n/).filter(Boolean).at(-1);
  if (!jsonLine) throw new Error("Rust Harness conversation page contract generator produced no JSON");
  const contract = JSON.parse(jsonLine);
  if (Object.keys(contract).sort().join(",") !== "maximum_messages") {
    throw new Error("Harness conversation page contract field inventory drift");
  }
  if (!Number.isSafeInteger(contract.maximum_messages) || contract.maximum_messages <= 0) {
    throw new Error("Harness conversation page contract has an invalid ceiling");
  }
  return contract;
}

function renderContract(root) {
  const { maximum_messages: maximumMessages } = readRustContract(root);
  return [
    "// @generated by scripts/generate-harness-conversation-page-contract.mjs; do not edit.",
    "",
    `export const HARNESS_CONVERSATION_PAGE_MAXIMUM = ${maximumMessages} as number;`,
    "",
  ].join("\n");
}

export function generateHarnessConversationPageContract(root, outputDirectory) {
  const output = outputDirectory ?? dirname(join(root, outputRelativePath));
  writeFileSync(join(output, "conversation-page-contract.ts"), renderContract(root));
}

export function checkHarnessConversationPageContract(root) {
  const temporary = mkdtempSync(join(tmpdir(), "acyclic-harness-conversation-page-contract-"));
  try {
    generateHarnessConversationPageContract(root, temporary);
    const committed = join(root, outputRelativePath);
    if (!existsSync(committed) || !readFileSync(join(temporary, "conversation-page-contract.ts")).equals(readFileSync(committed))) {
      throw new Error("Harness conversation page contract is stale; run bun run generate");
    }
  } finally {
    rmSync(temporary, { recursive: true, force: true });
  }
}

if (resolve(process.argv[1] ?? "") === resolve(scriptPath)) {
  const root = join(dirname(scriptPath), "..");
  const mode = process.argv[2] ?? "write";
  if (mode === "check") checkHarnessConversationPageContract(root);
  else if (mode === "write") generateHarnessConversationPageContract(root);
  else throw new Error(`unknown mode: ${mode}`);
}
