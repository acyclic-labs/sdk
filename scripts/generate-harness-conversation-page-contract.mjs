export const rust = [["acyclic-harness", "example", "conversation-page-contract"]];

export function render([stdout]) {
  const contract = JSON.parse(stdout);
  if (Object.keys(contract).sort().join(",") !== "default_messages,maximum_messages") {
    throw new Error("Harness conversation page contract field inventory drift");
  }
  if (!Number.isSafeInteger(contract.maximum_messages) || contract.maximum_messages <= 0) {
    throw new Error("Harness conversation page contract has an invalid ceiling");
  }
  if (!Number.isSafeInteger(contract.default_messages) || contract.default_messages <= 0 ||
      contract.default_messages > contract.maximum_messages) {
    throw new Error("Harness conversation page contract has an invalid default");
  }
  return {
    "typescript/packages/harness/src/conversation-page-contract.ts": [
      "// @generated by scripts/generate-harness-conversation-page-contract.mjs; do not edit.",
      "",
      `export const HARNESS_CONVERSATION_PAGE_DEFAULT = ${contract.default_messages} as number;`,
      `export const HARNESS_CONVERSATION_PAGE_MAXIMUM = ${contract.maximum_messages} as number;`,
      "",
    ].join("\n"),
  };
}
