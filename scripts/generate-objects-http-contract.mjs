import { spawnSync } from "node:child_process";
import {
  existsSync,
  mkdtempSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const scriptPath = fileURLToPath(import.meta.url);

function readRustContract(root) {
  const result = spawnSync(
    process.env.ACYCLIC_CARGO_BIN || "cargo",
    [
      "run",
      "--manifest-path",
      join(root, "Cargo.toml"),
      "--package",
      "acyclic-objects-wasm",
      "--bin",
      "objects-http-contract",
      "--locked",
      "--quiet",
    ],
    { cwd: root, encoding: "utf8" },
  );
  if (result.status !== 0) {
    process.stderr.write(result.stdout ?? "");
    process.stderr.write(result.stderr ?? "");
    throw new Error(`Rust Objects HTTP contract generator failed with status ${result.status ?? "unknown"}`);
  }
  const lines = (result.stdout ?? "").trim().split(/\r?\n/).filter(Boolean);
  const json = lines.at(-1);
  if (!json) throw new Error("Rust Objects HTTP contract generator produced no JSON");
  const contract = JSON.parse(json);
  if (!Array.isArray(contract) || contract.some(entry => !Array.isArray(entry) || entry.length !== 2 ||
      typeof entry[0] !== "string" || typeof entry[1] !== "string")) {
    throw new Error("Rust Objects HTTP contract has an invalid shape");
  }
  return contract;
}

function renderSources(root) {
  const contract = readRustContract(root);
  const routes = contract.map(([route, kind]) => `  ${JSON.stringify(route)}: ${JSON.stringify(kind)},`).join("\n");
  const header = "// @generated by scripts/generate-objects-http-contract.mjs; do not edit.\n\n";
  const source = `${header}import type { BucketRef, ListPage, MultipartUpload, ObjectVersion, SnapshotRef, StoredObject, UploadedPart } from "./index.js";\n\n` +
    `export const HTTP_RESPONSE_CONTRACT = Object.freeze({\n${routes}\n} as const);\n\n` +
    `export type HttpRoute = keyof typeof HTTP_RESPONSE_CONTRACT;\n\n` +
    `type HttpResponseByKind = {\n` +
    `  bucket: BucketRef;\n` +
    `  existed: boolean;\n` +
    `  version: ObjectVersion;\n` +
    `  stored: StoredObject;\n` +
    `  delete: { readonly existed: boolean; readonly marker?: ObjectVersion };\n` +
    `  list: ListPage;\n` +
    `  snapshot: SnapshotRef;\n` +
    `  multipart: MultipartUpload;\n` +
    `  part: UploadedPart;\n` +
    `  parts: readonly UploadedPart[];\n` +
    `};\n\n` +
    `export type HttpResponseFor<Route extends HttpRoute> = HttpResponseByKind[typeof HTTP_RESPONSE_CONTRACT[Route]];\n`;
  return { source };
}

export function generateObjectsHttpContract(root, outputDirectory) {
  const output = outputDirectory ?? join(root, "typescript/packages/objects/src");
  writeFileSync(join(output, "http-contract.ts"), renderSources(root).source);
}

export function checkObjectsHttpContract(root) {
  const temporary = mkdtempSync(join(tmpdir(), "acyclic-objects-http-contract-"));
  try {
    generateObjectsHttpContract(root, temporary);
    const committed = join(root, "typescript/packages/objects/src/http-contract.ts");
    if (!existsSync(committed) || !readFileSync(join(temporary, "http-contract.ts")).equals(readFileSync(committed))) {
      throw new Error("Objects HTTP contract is stale; run bun run generate");
    }
  } finally {
    rmSync(temporary, { recursive: true, force: true });
  }
}

if (resolve(process.argv[1] ?? "") === resolve(scriptPath)) {
  const root = join(dirname(scriptPath), "..");
  const mode = process.argv[2] ?? "write";
  if (mode === "check") checkObjectsHttpContract(root);
  else if (mode === "write") generateObjectsHttpContract(root);
  else throw new Error(`unknown mode: ${mode}`);
}
