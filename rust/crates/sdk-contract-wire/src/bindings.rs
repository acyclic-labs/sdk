//! Rust binding generation from the model-owned descriptor boundary.
//!
//! Public build scripts can consume this module when they regenerate prost or
//! tonic source. Each input is assembled from the Rust
//! contract model; the archived descriptor is exposed separately so a build
//! can retain the deployed handshake bytes while changing the schema input.

use std::{
    fmt, fs, io,
    path::{Path, PathBuf},
};

use prost::Message;
use prost_types::{
    source_code_info::Location, FileDescriptorProto, FileDescriptorSet, SourceCodeInfo,
};

use crate::{
    actors_descriptor,
    inference::{inference_descriptor, INFERENCE},
    machines::{machines_descriptor, MACHINES},
    objects::{objects_descriptor, OBJECTS_V2},
    stream::{stream_descriptor, STREAM},
    workers::{workers_descriptor, WORKERS},
    ContractSpec, ACTORS,
};

/// A public contract family with a model-owned Rust descriptor.
#[derive(Clone, Copy, Debug, Eq, Hash, PartialEq)]
pub enum BindingFamily {
    /// Actors v1 transport.
    Actors,
    /// Workers v1 transport.
    Workers,
    /// Objects v2 transport.
    Objects,
    /// Stream v2 transport.
    Stream,
    /// Inference customer v1 transport.
    Inference,
    /// Machines v1 transport.
    Machines,
    /// Filesystem v2 descriptor documentation overlay.
    Filesystem,
    /// Harness v2 descriptor documentation overlay.
    Harness,
}

impl BindingFamily {
    /// All families whose public Rust bindings are generated by this boundary.
    pub const ALL: &'static [Self] = &[
        Self::Actors,
        Self::Workers,
        Self::Objects,
        Self::Stream,
        Self::Inference,
        Self::Machines,
        Self::Filesystem,
        Self::Harness,
    ];

    /// Stable lowercase family name used in build diagnostics and manifests.
    pub const fn name(self) -> &'static str {
        match self {
            Self::Actors => "actors",
            Self::Workers => "workers",
            Self::Objects => "objects",
            Self::Stream => "stream",
            Self::Inference => "inference",
            Self::Machines => "machines",
            Self::Filesystem => "filesystem",
            Self::Harness => "harness",
        }
    }

    /// The typed Rust model consumed by this family.
    pub const fn model(self) -> &'static ContractSpec {
        match self {
            Self::Actors => &ACTORS,
            Self::Workers => &WORKERS,
            Self::Objects => &OBJECTS_V2,
            Self::Stream => &STREAM,
            Self::Inference => &INFERENCE,
            Self::Machines => &MACHINES,
            Self::Filesystem | Self::Harness => {
                panic!("Filesystem and Harness use ContractModel, not ContractSpec")
            }
        }
    }

    /// The model package qualified by this family.
    pub const fn package(self) -> &'static str {
        match self {
            Self::Actors => ACTORS.package,
            Self::Workers => WORKERS.package,
            Self::Objects => OBJECTS_V2.package,
            Self::Stream => STREAM.package,
            Self::Inference => INFERENCE.package,
            Self::Machines => MACHINES.package,
            Self::Filesystem => crate::filesystem::PACKAGE,
            Self::Harness => crate::harness::PACKAGE,
        }
    }

    /// The model file name qualified by this family.
    pub const fn file_name(self) -> &'static str {
        match self {
            Self::Actors => ACTORS.file_name,
            Self::Workers => WORKERS.file_name,
            Self::Objects => OBJECTS_V2.file_name,
            Self::Stream => STREAM.file_name,
            Self::Inference => INFERENCE.file_name,
            Self::Machines => MACHINES.file_name,
            Self::Filesystem => crate::filesystem::FILE_NAME,
            Self::Harness => crate::harness::FILE_NAME,
        }
    }

    /// Descriptor bytes emitted from the model, including model-owned raw
    /// options and any dependency closure represented by that model.
    pub fn model_descriptor(self) -> Vec<u8> {
        match self {
            Self::Actors => actors_descriptor(),
            Self::Workers => workers_descriptor(),
            Self::Objects => objects_descriptor(),
            Self::Stream => stream_descriptor(),
            Self::Inference => inference_descriptor(),
            Self::Machines => machines_descriptor(),
            Self::Filesystem => crate::filesystem::filesystem_descriptor(),
            Self::Harness => crate::harness::harness_descriptor(),
        }
    }

    /// The archived descriptor used by the corresponding runtime handshake.
    ///
    /// This is intentionally distinct from [`Self::model_descriptor`].  A
    /// schema descriptor can be source-info-free and model-owned while the
    /// deployed runtime still advertises an archived descriptor digest.
    pub const fn archived_runtime_descriptor(self) -> &'static [u8] {
        match self {
            Self::Actors => include_bytes!("../../actors/src/generated/acyclic-actors-v1.bin"),
            Self::Workers => include_bytes!("../../workers/src/generated/acyclic-workers-v1.bin"),
            Self::Objects => include_bytes!("../../objects/src/generated/acyclic-objects-v2.bin"),
            Self::Stream => include_bytes!("../../stream/proto/stream/v2/stream_descriptor.bin"),
            Self::Inference => include_bytes!("../../inference/inference_descriptor.bin"),
            Self::Machines => {
                include_bytes!("../../machines/src/generated/acyclic-machines-v1.bin")
            }
            Self::Filesystem => {
                include_bytes!("../../filesystem/src/generated/acyclic-filesystem-v2.bin")
            }
            Self::Harness => include_bytes!("../../harness/src/generated/harness-archived-v2.bin"),
        }
    }
}

/// Selects the generated Rust surface.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum BindingTransport {
    /// Generate transport-independent prost messages.
    Prost,
    /// Generate prost messages and tonic client/server modules.
    Tonic {
        /// Generate tonic clients.
        client: bool,
        /// Generate tonic servers.
        server: bool,
    },
}

/// Exact product generator settings for one contract family.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct ProductBindingConfig {
    /// Contract family selected by this configuration.
    pub family: BindingFamily,
    /// Generate byte fields as `prost::bytes::Bytes`.
    pub bytes: bool,
    /// Apply the Objects metadata BTreeMap override.
    pub object_metadata_btree_map: bool,
    /// Emit tonic clients.
    pub client: bool,
    /// Emit tonic servers.
    pub server: bool,
}

impl BindingFamily {
    /// Return the checked-in package generator settings for this family.
    pub const fn product_config(self) -> ProductBindingConfig {
        ProductBindingConfig {
            family: self,
            bytes: matches!(self, Self::Stream),
            object_metadata_btree_map: matches!(self, Self::Objects),
            client: !matches!(self, Self::Stream),
            server: !matches!(self, Self::Stream),
        }
    }
}

/// A generated binding output and its model provenance.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct BindingOutput {
    /// Family that was generated.
    pub family: BindingFamily,
    /// Directory containing generated Rust source files.
    pub output_dir: PathBuf,
    /// Model descriptor bytes passed to the generator.
    pub model_descriptor: Vec<u8>,
    /// Archived runtime descriptor retained for handshake identity.
    pub archived_runtime_descriptor: &'static [u8],
}

/// Errors returned by the reusable prost/tonic binding entrypoint.
#[derive(Debug)]
pub enum BindingGenerationError {
    /// The model descriptor could not be decoded.
    Decode(prost::DecodeError),
    /// The output directory or generator could not be written.
    Io(io::Error),
    /// A pinned prost or tonic plugin rejected the model descriptor.
    Plugin(String),
}

impl fmt::Display for BindingGenerationError {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::Decode(error) => write!(formatter, "decode model descriptor: {error}"),
            Self::Io(error) => write!(formatter, "generate Rust bindings: {error}"),
            Self::Plugin(error) => write!(formatter, "generate Rust bindings: {error}"),
        }
    }
}

impl std::error::Error for BindingGenerationError {}

impl From<prost::DecodeError> for BindingGenerationError {
    fn from(error: prost::DecodeError) -> Self {
        Self::Decode(error)
    }
}

impl From<io::Error> for BindingGenerationError {
    fn from(error: io::Error) -> Self {
        Self::Io(error)
    }
}

/// Generate prost or tonic Rust bindings from one model-owned descriptor.
///
/// `out_dir` is suitable for a Cargo `OUT_DIR` or a checked temporary
/// generation directory.  The function never reads a `.proto`, generated Rust
/// file, or archived descriptor as generation input.
pub fn generate_rust_bindings(
    family: BindingFamily,
    out_dir: impl AsRef<Path>,
    transport: BindingTransport,
) -> Result<BindingOutput, BindingGenerationError> {
    let out_dir = out_dir.as_ref();
    fs::create_dir_all(out_dir)?;
    let model_descriptor = family.model_descriptor();
    let descriptors = generation_descriptor_set(family, &model_descriptor)?;

    match transport {
        BindingTransport::Prost => {
            let mut config = prost_build::Config::new();
            config.out_dir(out_dir);
            if family == BindingFamily::Stream {
                config.bytes([format!(".{}", family.package())]);
            }
            config
                .compile_fds(descriptors)
                .map_err(BindingGenerationError::Io)?;
        }
        BindingTransport::Tonic { client, server } => {
            let mut config = prost_build::Config::new();
            if family == BindingFamily::Stream {
                config.bytes([format!(".{}", family.package())]);
            }
            tonic_prost_build::configure()
                .out_dir(out_dir)
                .build_client(client)
                .build_server(server)
                .compile_fds_with_config(descriptors, config)
                .map_err(BindingGenerationError::Io)?;
        }
    }

    Ok(BindingOutput {
        family,
        output_dir: out_dir.to_owned(),
        model_descriptor,
        archived_runtime_descriptor: family.archived_runtime_descriptor(),
    })
}

/// Generate the checked-in product layout from the Rust model.
///
/// Actors, Workers, and Objects use the pinned protoc plugins directly so the
/// split `*.rs`/`*.tonic.rs` files and insertion-point includes remain
/// compatible with the existing packages. Stream uses the build-script style
/// compiler and therefore emits one prost/tonic module.
pub fn generate_product_bindings(
    family: BindingFamily,
    out_dir: impl AsRef<Path>,
) -> Result<BindingOutput, BindingGenerationError> {
    let out_dir = out_dir.as_ref();
    fs::create_dir_all(out_dir)?;
    let model_descriptor = family.model_descriptor();
    let descriptors = generation_descriptor_set(family, &model_descriptor)?;
    let config = family.product_config();
    if matches!(
        family,
        BindingFamily::Actors | BindingFamily::Workers | BindingFamily::Objects
    ) {
        generate_plugin_files(family, out_dir, &descriptors, config)?;
    } else {
        let mut prost = tonic_prost_build::Config::new();
        if config.bytes {
            prost.bytes([format!(".{}", family.package())]);
        }
        tonic_prost_build::configure()
            .out_dir(out_dir)
            .build_client(config.client)
            .build_server(config.server)
            .compile_fds_with_config(descriptors, prost)
            .map_err(BindingGenerationError::Io)?;
    }
    Ok(BindingOutput {
        family,
        output_dir: out_dir.to_owned(),
        model_descriptor,
        archived_runtime_descriptor: family.archived_runtime_descriptor(),
    })
}

fn generate_plugin_files(
    family: BindingFamily,
    out_dir: &Path,
    descriptors: &FileDescriptorSet,
    config: ProductBindingConfig,
) -> Result<(), BindingGenerationError> {
    // The model descriptor may include the dependency closure (for example
    // the shared protocol file), so build the plugin request from the exact
    // closure selected for this family rather than from the target-only model
    // bytes. This keeps the CodeGeneratorRequest self-contained and avoids
    // silently dropping dependencies or their custom options.
    let mut raw_descriptor_files =
        raw_descriptor_files_with_docs(family, &family.model_descriptor())?;
    // `generation_descriptor_set` adds this small WKT descriptor because the
    // Objects model records the import edge but intentionally does not own the
    // archived google descriptor. Include the generated dependency in the
    // plugin request alongside the raw model bytes.
    if family == BindingFamily::Objects
        && descriptors
            .file
            .iter()
            .any(|file| file.name.as_deref() == Some("google/protobuf/timestamp.proto"))
        && raw_descriptor_files.len() < descriptors.file.len()
    {
        let timestamp = descriptors
            .file
            .iter()
            .find(|file| file.name.as_deref() == Some("google/protobuf/timestamp.proto"))
            .expect("timestamp descriptor present");
        raw_descriptor_files.push(timestamp.encode_to_vec());
    }
    let request = code_generator_request(
        descriptors,
        &raw_descriptor_files,
        family.file_name(),
        if config.object_metadata_btree_map {
            "btree_map=.acyclic.objects.v2.ObjectMetadata.user"
        } else {
            ""
        },
    );
    let prost_files = protoc_gen_prost::execute(&request)
        .map_err(|error| BindingGenerationError::Plugin(error.to_string()))?;
    write_plugin_files(out_dir, prost_files, family == BindingFamily::Objects)?;

    let mut tonic_params = Vec::new();
    if !config.client {
        tonic_params.push("no_client");
    }
    if !config.server {
        tonic_params.push("no_server");
    }
    let tonic_files = protoc_gen_tonic::execute(&code_generator_request(
        descriptors,
        &raw_descriptor_files,
        family.file_name(),
        &tonic_params.join(","),
    ))
    .map_err(|error| BindingGenerationError::Plugin(error.to_string()))?;
    write_plugin_files(out_dir, tonic_files, family == BindingFamily::Objects)
}

fn write_plugin_files(
    out_dir: &Path,
    files: Vec<prost_types::compiler::code_generator_response::File>,
    guard_grpc: bool,
) -> Result<(), BindingGenerationError> {
    for file in files {
        let name = file.name.ok_or_else(|| {
            BindingGenerationError::Plugin("generator returned unnamed file".into())
        })?;
        let path = out_dir.join(&name);
        if let Some(parent) = path.parent() {
            fs::create_dir_all(parent)?;
        }
        if let Some(insertion) = file.insertion_point {
            let mut current = fs::read_to_string(&path)?;
            let marker = format!("// @@protoc_insertion_point({insertion})");
            let offset = current.find(&marker).ok_or_else(|| {
                BindingGenerationError::Plugin(format!(
                    "missing insertion point {marker} in {name}"
                ))
            })?;
            let insertion = file.content.as_deref().unwrap_or_default();
            let insertion = if guard_grpc {
                guard_tonic_include(insertion)
            } else {
                insertion.to_owned()
            };
            current.insert_str(offset, &insertion);
            fs::write(path, current)?;
        } else {
            let content = file.content.unwrap_or_default();
            let content = if guard_grpc && name.ends_with(".tonic.rs") {
                guard_tonic_modules(&content)
            } else if guard_grpc {
                guard_tonic_include(&content)
            } else {
                content
            };
            fs::write(path, content)?;
        }
    }
    Ok(())
}

fn guard_tonic_modules(source: &str) -> String {
    let mut guarded = String::with_capacity(source.len() + 128);
    for line in source.lines() {
        if line.starts_with("pub mod ") {
            guarded.push_str("#[cfg(feature = \"grpc\")]\n");
        }
        guarded.push_str(line);
        guarded.push('\n');
    }
    if !source.ends_with('\n') {
        guarded.pop();
    }
    guarded
}

fn guard_tonic_include(source: &str) -> String {
    let mut guarded = String::with_capacity(source.len() + 64);
    for line in source.lines() {
        if line.trim_start().starts_with("include!(") && line.trim_end().ends_with(".tonic.rs\");")
        {
            guarded.push_str("#[cfg(feature = \"grpc\")]\n");
        }
        guarded.push_str(line);
        guarded.push('\n');
    }
    if !source.ends_with('\n') {
        guarded.pop();
    }
    guarded
}

fn code_generator_request(
    descriptors: &FileDescriptorSet,
    raw_descriptor_files: &[Vec<u8>],
    file_to_generate: &str,
    parameter: &str,
) -> Vec<u8> {
    let mut request = Vec::new();
    append_length_delimited(&mut request, 1, file_to_generate.as_bytes());
    if !parameter.is_empty() {
        append_length_delimited(&mut request, 2, parameter.as_bytes());
    }
    for raw in raw_descriptor_files {
        append_length_delimited(&mut request, 15, raw);
    }
    debug_assert_eq!(descriptors.file.len(), raw_descriptor_files.len());
    request
}

fn append_length_delimited(output: &mut Vec<u8>, tag: u64, value: &[u8]) {
    append_varint(output, (tag << 3) | 2);
    append_varint(output, value.len() as u64);
    output.extend_from_slice(value);
}

fn append_varint(output: &mut Vec<u8>, mut value: u64) {
    while value >= 0x80 {
        output.push((value as u8) | 0x80);
        value >>= 7;
    }
    output.push(value as u8);
}

/// Extract the exact length-delimited `FileDescriptorSet.file` payloads from
/// the model wire bytes. Decoding and re-encoding a descriptor would discard
/// unknown custom option fields, which are part of the Rust model authority.
fn raw_descriptor_files(bytes: &[u8]) -> Result<Vec<Vec<u8>>, BindingGenerationError> {
    let mut offset = 0usize;
    let mut files = Vec::new();
    while offset < bytes.len() {
        let tag = read_varint(bytes, &mut offset)?;
        if tag == 0 {
            return Err(BindingGenerationError::Plugin(
                "invalid zero descriptor-set field tag".into(),
            ));
        }
        let field = tag >> 3;
        let wire = (tag & 7) as u8;
        if field == 1 && wire == 2 {
            let length = read_varint(bytes, &mut offset)? as usize;
            let end = offset.checked_add(length).ok_or_else(|| {
                BindingGenerationError::Plugin("descriptor field length overflow".into())
            })?;
            if end > bytes.len() {
                return Err(BindingGenerationError::Plugin(
                    "descriptor field extends beyond model bytes".into(),
                ));
            }
            files.push(bytes[offset..end].to_vec());
            offset = end;
        } else {
            skip_wire(bytes, &mut offset, wire)?;
        }
    }
    Ok(files)
}

/// Add model-owned comments as a generation-only SourceCodeInfo overlay.
///
/// The canonical descriptor remains source-info-free and is still returned by
/// `BindingOutput`; this overlay exists solely so prost can emit Rust docs.
/// Raw model bytes are retained and the overlay is appended as a normal field,
/// preserving unknown option fields in the request.
fn raw_descriptor_files_with_docs(
    family: BindingFamily,
    bytes: &[u8],
) -> Result<Vec<Vec<u8>>, BindingGenerationError> {
    let raw_files = raw_descriptor_files(bytes)?;
    let descriptors = FileDescriptorSet::decode(bytes)?;
    let mut output = Vec::with_capacity(raw_files.len());
    for (raw, file) in raw_files.into_iter().zip(descriptors.file) {
        let locations = model_source_locations(family, &file);
        if locations.is_empty() {
            output.push(raw);
            continue;
        }
        let mut augmented = raw;
        append_length_delimited(
            &mut augmented,
            9,
            &SourceCodeInfo {
                location: locations,
            }
            .encode_to_vec(),
        );
        output.push(augmented);
    }
    Ok(output)
}

/// Return a generation-only descriptor set with Rust-owned source comments.
///
/// The input remains the canonical model or committed descriptor bytes: file
/// payloads are copied from their original wire representation and only a
/// `SourceCodeInfo` field is appended for the selected family.  This preserves
/// custom options and unknown fields while giving generic `prost-build`
/// consumers (including Filesystem and Harness build scripts) the same docs
/// surface as the direct plugins.  The returned bytes must not be used as a
/// normalized schema identity or a runtime handshake fixture.
pub fn descriptor_set_with_docs(
    family: BindingFamily,
    bytes: &[u8],
) -> Result<Vec<u8>, BindingGenerationError> {
    let raw_files = raw_descriptor_files(bytes)?;
    let descriptors = FileDescriptorSet::decode(bytes)?;
    if raw_files.len() != descriptors.file.len() {
        return Err(BindingGenerationError::Plugin(
            "descriptor-set file count changed while applying source docs".into(),
        ));
    }
    let mut output = Vec::with_capacity(bytes.len());
    for (raw, file) in raw_files.into_iter().zip(descriptors.file) {
        let locations = model_source_locations(family, &file);
        let augmented = if locations.is_empty() {
            raw
        } else {
            let mut augmented = raw;
            append_length_delimited(
                &mut augmented,
                9,
                &SourceCodeInfo {
                    location: locations,
                }
                .encode_to_vec(),
            );
            augmented
        };
        append_length_delimited(&mut output, 1, &augmented);
    }
    Ok(output)
}

fn model_source_locations(family: BindingFamily, file: &FileDescriptorProto) -> Vec<Location> {
    let package = file.package.as_deref().unwrap_or_default();
    // Dependency descriptors are part of the generation closure, but their
    // comments are owned by their upstream schema.  Only attach locations to
    // the selected Rust model package; this also avoids asking a model doc
    // table for WKT/protocol dependency messages.
    if package != family.package() {
        return Vec::new();
    }
    let mut locations = Vec::new();
    for (index, message) in file.message_type.iter().enumerate() {
        let path = vec![4, index as i32];
        add_location(
            &mut locations,
            path.clone(),
            model_message_docs(package, message.name.as_deref().unwrap_or_default()),
        );
        add_message_locations(&mut locations, package, message, &path);
    }
    for (index, enumeration) in file.enum_type.iter().enumerate() {
        let path = vec![5, index as i32];
        add_location(
            &mut locations,
            path,
            model_enum_docs(package, enumeration.name.as_deref().unwrap_or_default()),
        );
        for (value_index, value) in enumeration.value.iter().enumerate() {
            add_location(
                &mut locations,
                vec![5, index as i32, 2, value_index as i32],
                model_enum_value_docs(
                    package,
                    enumeration.name.as_deref().unwrap_or_default(),
                    value.name.as_deref().unwrap_or_default(),
                ),
            );
        }
    }
    for (index, service) in file.service.iter().enumerate() {
        let path = vec![6, index as i32];
        add_location(
            &mut locations,
            path.clone(),
            model_service_docs(package, service.name.as_deref().unwrap_or_default()),
        );
        for (method_index, method) in service.method.iter().enumerate() {
            let method_path = [path.as_slice(), &[2, method_index as i32]].concat();
            let docs = model_method_docs(
                family,
                package,
                service.name.as_deref().unwrap_or_default(),
                method.name.as_deref().unwrap_or_default(),
            );
            add_location(&mut locations, method_path, docs);
        }
    }
    locations.sort_by(|left, right| left.path.cmp(&right.path));
    locations
}

fn add_message_locations(
    locations: &mut Vec<Location>,
    package: &str,
    message: &prost_types::DescriptorProto,
    path: &[i32],
) {
    for (index, field) in message.field.iter().enumerate() {
        let field_path = [path, &[2, index as i32]].concat();
        add_location(
            locations,
            field_path,
            model_field_docs(
                package,
                message.name.as_deref().unwrap_or_default(),
                field.name.as_deref().unwrap_or_default(),
            ),
        );
    }
    for (index, nested) in message.nested_type.iter().enumerate() {
        let nested_path = [path, &[3, index as i32]].concat();
        add_location(
            locations,
            nested_path.clone(),
            model_message_docs(package, nested.name.as_deref().unwrap_or_default()),
        );
        add_message_locations(locations, package, nested, &nested_path);
    }
    for (index, enumeration) in message.enum_type.iter().enumerate() {
        let enum_path = [path, &[4, index as i32]].concat();
        add_location(
            locations,
            enum_path.clone(),
            model_enum_docs(package, enumeration.name.as_deref().unwrap_or_default()),
        );
        for (value_index, value) in enumeration.value.iter().enumerate() {
            add_location(
                locations,
                [enum_path.as_slice(), &[2, value_index as i32]].concat(),
                model_enum_value_docs(
                    package,
                    enumeration.name.as_deref().unwrap_or_default(),
                    value.name.as_deref().unwrap_or_default(),
                ),
            );
        }
    }
    for (index, oneof) in message.oneof_decl.iter().enumerate() {
        let oneof_path = [path, &[8, index as i32]].concat();
        add_location(
            locations,
            oneof_path,
            model_oneof_docs(
                package,
                message.name.as_deref().unwrap_or_default(),
                oneof.name.as_deref().unwrap_or_default(),
            ),
        );
    }
}

fn add_location(locations: &mut Vec<Location>, path: Vec<i32>, docs: &str) {
    locations.push(Location {
        path,
        leading_comments: (!docs.is_empty()).then(|| docs.to_owned()),
        ..Default::default()
    });
}

