//! Rust-owned Swift projection for the embedded C ABI.
//!
//! The generated source is a lifetime adapter around the versioned C ABI. It
//! deliberately owns no contract or provider behavior: Rust remains the only
//! implementation of the engine, reader, wire operations, and cancellation
//! semantics.

/// Installable generated Swift source for the embedded ABI adapter.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct EmbeddedSwiftOutput {
    pub path: &'static str,
    pub source: String,
}

/// The C module map for the generated cbindgen header uses this stable name.
pub const SWIFT_EMBEDDED_PATH: &str =
    "swift/embedded/Sources/AcyclicEmbedded/AcyclicEmbedded.swift";
pub const SWIFT_EMBEDDED_PACKAGE_PATH: &str = "swift/embedded/Package.swift";
pub const SWIFT_EMBEDDED_MODULEMAP_PATH: &str =
    "swift/embedded/Sources/AcyclicEmbeddedABI/module.modulemap";

/// Emit the Swift ownership adapter for the Rust-owned embedded C ABI.
pub fn generate_embedded_swift() -> EmbeddedSwiftOutput {
    EmbeddedSwiftOutput {
        path: SWIFT_EMBEDDED_PATH,
        source: swift_source(),
    }
}

/// Emit the SwiftPM package manifest for the embedded ABI adapter.
pub fn generate_embedded_swift_package() -> EmbeddedSwiftOutput {
    EmbeddedSwiftOutput {
        path: SWIFT_EMBEDDED_PACKAGE_PATH,
        source: String::from(
            r#"// swift-tools-version: 6.1
// Generated by acyclic-sdk-contract-wire; do not edit.
//
// The release package stages the exact Rust-generated cbindgen header under
// Sources/AcyclicEmbeddedABI and native assets under ../../native/<rid>.
// SwiftPM selects the supported host RID automatically; set
// ACYCLIC_EMBEDDED_NATIVE_RID when cross-compiling or when selecting musl.
import PackageDescription
import Foundation

let supportedRIDs = [
    "win-x64", "win-arm64", "linux-x64", "linux-arm64",
    "linux-musl-x64", "linux-musl-arm64", "osx-x64", "osx-arm64"
]
let nativeRID: String = {
    if let override = ProcessInfo.processInfo.environment["ACYCLIC_EMBEDDED_NATIVE_RID"] {
        precondition(supportedRIDs.contains(override), "unsupported ACYCLIC_EMBEDDED_NATIVE_RID: \(override)")
        return override
    }
#if os(Windows)
#if arch(arm64)
    return "win-arm64"
#else
    return "win-x64"
#endif
#elseif os(macOS)
#if arch(arm64)
    return "osx-arm64"
#else
    return "osx-x64"
#endif
#elseif os(Linux)
#if arch(arm64)
    return "linux-arm64"
#else
    return "linux-x64"
#endif
#else
    fatalError("AcyclicEmbeddedSwift supports Windows, Linux, and macOS only")
#endif
}()
let nativeSearchPath = "../../native/\(nativeRID)"
let nativeLibraryPath = nativeRID.hasPrefix("win")
    ? "\(nativeSearchPath)/acyclic_sdk_embedded_prototype.dll.lib"
    : "\(nativeSearchPath)/libacyclic_sdk_embedded_prototype." + (nativeRID.hasPrefix("osx") ? "dylib" : "so")

let package = Package(
    name: "AcyclicEmbeddedSwift",
    products: [
        .library(name: "AcyclicEmbeddedSwift", targets: ["AcyclicEmbedded"])
    ],
    targets: [
        .systemLibrary(
            name: "AcyclicEmbeddedABI",
            path: "Sources/AcyclicEmbeddedABI"
        ),
        .target(
            name: "AcyclicEmbedded",
            dependencies: ["AcyclicEmbeddedABI"],
            path: "Sources/AcyclicEmbedded",
            linkerSettings: [
                .unsafeFlags(["-L\(nativeSearchPath)"]),
                .unsafeFlags([nativeLibraryPath]),
                .linkedLibrary("acyclic_sdk_embedded_prototype")
            ]
        )
    ]
)
"#,
        ),
    }
}

/// Emit the SwiftPM system-library module map for the Rust-generated C ABI.
pub fn generate_embedded_swift_module_map() -> EmbeddedSwiftOutput {
    EmbeddedSwiftOutput {
        path: SWIFT_EMBEDDED_MODULEMAP_PATH,
        source: String::from(
            r#"// Generated by acyclic-sdk-contract-wire; do not edit.
// The package staging step supplies acyclic_embedded_prototype.h from the
// matching sdk-embedded-prototype artifact in this directory.
module AcyclicEmbeddedABI {
    header "acyclic_embedded_prototype.h"
    link "acyclic_sdk_embedded_prototype"
    export *
}
"#,
        ),
    }
}

fn swift_source() -> String {
    String::from(
        r#"// Generated by acyclic-sdk-contract-wire; do not edit.
//
// The package module map must expose the Rust-generated cbindgen header as
// AcyclicEmbeddedABI. This file owns handles and returned buffers only; all
// behavior remains in the Rust implementation behind that C ABI.
import Foundation
import AcyclicEmbeddedABI

public enum AcyclicEmbeddedStatus: UInt32, Sendable {
    case ok = 0
    case end = 1
    case pending = 2
    case cancelled = 3
    case invalidArgument = 4
    case providerError = 5
    case capacity = 6
    case panic = 7

    fileprivate init(code: UInt32) {
        self = Self(rawValue: code) ?? .panic
    }
}

public struct AcyclicEmbeddedError: Error, Sendable, CustomStringConvertible {
    public let status: AcyclicEmbeddedStatus
    public let message: String

    public init(status: AcyclicEmbeddedStatus, message: String = "") {
        self.status = status
        self.message = message
    }

    public var description: String {
        message.isEmpty ? String(describing: status) : "\(status): \(message)"
    }
}

public struct AcyclicEmbeddedAppend: Sendable {
    public let start: UInt64
    public let end: UInt64
    public let tail: UInt64
}

public enum AcyclicEmbeddedRead: Sendable {
    case record(sequence: UInt64, value: Data)
    case pending
    case end
    case cancelled
}

/// A nominal owner for one Rust-allocated byte buffer.
///
/// This is a class instead of a struct so ordinary Swift value copying cannot
/// duplicate the C allocation owner. The buffer is released exactly once by
/// deinitialization, and callers receive copied `Data` values at the public
/// API boundary.
public final class AcyclicEmbeddedBuffer: @unchecked Sendable {
    private var raw: AcyclicBuffer?

    fileprivate init(_ raw: AcyclicBuffer) {
        self.raw = raw.id == 0 ? nil : raw
    }

    deinit {
        if let raw {
            _ = acyclic_buffer_release(raw)
        }
    }

    public var data: Data {
        guard let raw, raw.len != 0, let pointer = raw.ptr else {
            return Data()
        }
        return Data(bytes: pointer, count: Int(raw.len))
    }

    public var count: Int {
        Int(raw?.len ?? 0)
    }
}

private func emptyBuffer() -> AcyclicBuffer {
    AcyclicBuffer(id: 0, ptr: nil, len: 0, capacity: 0)
}

private func copyAndDetach(_ buffer: inout AcyclicBuffer) -> Data {
    let owner = AcyclicEmbeddedBuffer(buffer)
    buffer = emptyBuffer()
    return owner.data
}

private func withBytes<T>(
    _ data: Data,
    _ body: (UnsafePointer<UInt8>?, UInt) throws -> T
) rethrows -> T {
    try data.withUnsafeBytes { raw in
        let bytes = raw.bindMemory(to: UInt8.self)
        return try body(bytes.baseAddress, UInt(bytes.count))
    }
}

private func errorFor(_ status: UInt32, _ message: Data) -> AcyclicEmbeddedError {
    AcyclicEmbeddedError(
        status: AcyclicEmbeddedStatus(code: status),
        message: String(decoding: message, as: UTF8.self)
    )
}

/// A nominal owner of one Rust engine handle.
public final class AcyclicEmbeddedEngine: @unchecked Sendable {
    private let handle: UInt64

    private init(handle: UInt64) {
        self.handle = handle
    }

    public static func open() throws -> AcyclicEmbeddedEngine {
        guard acyclic_embedded_abi_version() == 1 else {
            throw AcyclicEmbeddedError(
                status: .panic,
                message: "unsupported embedded ABI version"
            )
        }
        let handle = acyclic_embedded_engine_open()
        guard handle != 0 else {
            throw AcyclicEmbeddedError(
                status: .panic,
                message: "embedded engine could not be opened"
            )
        }
        return AcyclicEmbeddedEngine(handle: handle)
    }

    deinit {
        acyclic_embedded_engine_close(handle)
    }

    public func append(path: Data, value: Data) throws -> AcyclicEmbeddedAppend {
        var result = try withBytes(path) { pathPointer, pathLength in
            try withBytes(value) { valuePointer, valueLength in
                acyclic_embedded_engine_append(
                    handle,
                    pathPointer,
                    pathLength,
                    valuePointer,
                    valueLength
                )
            }
        }
        let message = copyAndDetach(&result.message)
        let status = UInt32(result.status)
        acyclic_append_result_release(result)
        guard status == AcyclicEmbeddedStatus.ok.rawValue else {
            throw errorFor(status, message)
        }
        return AcyclicEmbeddedAppend(
            start: result.start,
            end: result.end,
            tail: result.tail
        )
    }

    public func wireCall(operation: String, request: Data) throws -> Data {
        let operationData = Data(operation.utf8)
        var result = try withBytes(operationData) { operationPointer, operationLength in
            try withBytes(request) { requestPointer, requestLength in
                acyclic_embedded_engine_wire_call(
                    handle,
                    operationPointer,
                    operationLength,
                    requestPointer,
                    requestLength
                )
            }
        }
        let response = copyAndDetach(&result.response)
        let message = copyAndDetach(&result.message)
        let status = UInt32(result.status)
        acyclic_wire_result_release(result)
        guard status == AcyclicEmbeddedStatus.ok.rawValue else {
            throw errorFor(status, message)
        }
        return response
    }

    public func openReader(
        path: Data,
        from: UInt64 = 0,
        limit: UInt32 = 0,
        follow: Bool = false
    ) throws -> AcyclicEmbeddedReader {
        var result = try withBytes(path) { pathPointer, pathLength in
            acyclic_embedded_reader_open(
                handle,
                pathPointer,
                pathLength,
                from,
                limit,
                follow ? 1 : 0
            )
        }
        let reader = acyclic_open_result_take_reader(&result)
        let message = copyAndDetach(&result.message)
        let status = UInt32(result.status)
        acyclic_open_result_release(result)
        guard status == AcyclicEmbeddedStatus.ok.rawValue, reader != 0 else {
            if reader != 0 {
                acyclic_embedded_reader_close(reader)
            }
            throw errorFor(status, message)
        }
        return AcyclicEmbeddedReader(handle: reader)
    }
}

/// A nominal owner of one Rust reader handle. The Rust ABI makes cancellation
/// thread-safe; a reader may therefore be cancelled while `next()` is waiting.
public final class AcyclicEmbeddedReader: @unchecked Sendable {
    private let handle: UInt64

    fileprivate init(handle: UInt64) {
        self.handle = handle
    }

    deinit {
        acyclic_embedded_reader_close(handle)
    }

    public func cancel() {
        acyclic_embedded_reader_cancel(handle)
    }

    public func next() throws -> AcyclicEmbeddedRead {
        var result = acyclic_embedded_reader_next(handle)
        let value = copyAndDetach(&result.value)
        let message = copyAndDetach(&result.message)
        let status = UInt32(result.status)
        let sequence = result.sequence
        acyclic_next_result_release(result)
        switch AcyclicEmbeddedStatus(code: status) {
        case .ok:
            return .record(sequence: sequence, value: value)
        case .pending:
            return .pending
        case .end:
            return .end
        case .cancelled:
            return .cancelled
        case .invalidArgument, .providerError, .capacity, .panic:
            throw errorFor(status, message)
        }
    }
}
"#,
    )
}

#[cfg(test)]
mod tests {
    use super::{
        generate_embedded_swift, generate_embedded_swift_module_map,
        generate_embedded_swift_package, SWIFT_EMBEDDED_MODULEMAP_PATH,
        SWIFT_EMBEDDED_PACKAGE_PATH, SWIFT_EMBEDDED_PATH,
    };

    #[test]
    fn embedded_swift_is_rust_owned_and_registered() {
        let output = generate_embedded_swift();
        assert_eq!(output.path, SWIFT_EMBEDDED_PATH);
        assert!(output
            .source
            .starts_with("// Generated by acyclic-sdk-contract-wire"));
        assert!(output.source.contains("import AcyclicEmbeddedABI"));
        assert!(output.source.contains("final class AcyclicEmbeddedEngine"));
        assert!(output.source.contains("final class AcyclicEmbeddedReader"));
        assert!(output.source.contains("final class AcyclicEmbeddedBuffer"));
        assert!(output.source.contains("acyclic_buffer_release"));
        assert!(output.source.contains("acyclic_open_result_take_reader"));
        assert!(output.source.contains("acyclic_embedded_reader_cancel"));
        assert!(output.source.contains("acyclic_next_result_release"));
        assert!(!output.source.contains("struct AcyclicEmbeddedEngine"));
        assert!(!output.source.contains("struct AcyclicEmbeddedReader"));
    }

    #[test]
    fn embedded_swift_package_is_source_bound_to_the_abi_module() {
        let package = generate_embedded_swift_package();
        assert_eq!(package.path, SWIFT_EMBEDDED_PACKAGE_PATH);
        assert!(package.source.contains("AcyclicEmbeddedABI"));
        assert!(package.source.contains("Sources/AcyclicEmbedded"));
        assert!(package.source.contains("ACYCLIC_EMBEDDED_NATIVE_RID"));
        assert!(package.source.contains("nativeSearchPath"));
        assert!(package.source.contains("nativeLibraryPath"));
        assert!(package.source.contains("acyclic_sdk_embedded_prototype.dll.lib"));
        assert!(package.source.contains("linkedLibrary(\"acyclic_sdk_embedded_prototype\")"));
        assert!(package.source.contains("linux-musl-x64"));

        let module_map = generate_embedded_swift_module_map();
        assert_eq!(module_map.path, SWIFT_EMBEDDED_MODULEMAP_PATH);
        assert!(module_map.source.contains("header \"acyclic_embedded_prototype.h\""));
        assert!(module_map.source.contains("link \"acyclic_sdk_embedded_prototype\""));
    }

    #[test]
    fn embedded_swift_detaches_every_result_buffer_before_release() {
        let source = generate_embedded_swift().source;
        for release in [
            "acyclic_append_result_release(result)",
            "acyclic_wire_result_release(result)",
            "acyclic_open_result_release(result)",
            "acyclic_next_result_release(result)",
        ] {
            assert!(source.contains(release), "missing {release}");
        }
        assert!(source.contains("let owner = AcyclicEmbeddedBuffer(buffer)"));
        assert!(source.contains("buffer = emptyBuffer()"));
    }
}
