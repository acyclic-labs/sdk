fn render() -> String {
    validate_rust_field_resolution();
    let mut out = String::from(
        "// Generated by acyclic-sdk-contract-wire; do not edit.\n// All semantic constraints and public signatures originate in Rust type_policy.rs.\n#nullable enable\n\nusing System;\nusing System.Collections.Generic;\nusing System.Threading;\nusing System.Threading.Tasks;\nusing Google.Protobuf;\nusing Grpc.Core;\n\nnamespace Acyclic.Sdk.Transport;\n\n",
    );
    render_semantic_types(&mut out);
    render_machine_image(&mut out);
    render_unions(&mut out);
    render_request_models(&mut out);
    render_full_semantic_request_models(&mut out);
    render_nested_models(&mut out);
    render_object_stream(&mut out);
    render_object_info_response(&mut out);
    render_operation_validation(&mut out);
    render_operation_validation_policy(&mut out);
    render_clients(&mut out);
    out
}

fn validate_rust_field_resolution() {
    let fields = resolved_request_fields().expect("Rust request descriptors must resolve");
    for binding in PUBLIC_FIELD_BINDINGS
        .iter()
        .filter(|binding| binding.direction == PublicFieldDirection::Request)
    {
        let found = fields.iter().any(|field| {
            field.family == binding.family
                && field.root_message.rsplit('.').next() == Some(binding.message)
                && field.field == binding.wire_field
        });
        assert!(
            found,
            "Rust semantic binding {}.{} is absent from the resolved request graph",
            binding.family, binding.field
        );
    }
}

fn render_semantic_types(out: &mut String) {
    let mut emitted = BTreeSet::new();
    for item in SEMANTIC_TYPES {
        if item.id == "immutable_image" {
            continue;
        }
        let ty = item.rust_name;
        if !emitted.insert(ty) {
            continue;
        }
        match item.wire_kind {
            WireValueKind::String => {
                out.push_str(&format!("public readonly record struct {ty}\n{{\n    public {ty}(string value)\n    {{\n        if (string.IsNullOrEmpty(value)) throw new ArgumentException(\"{ty} must be non-empty\", nameof(value));\n        Value = value;\n    }}\n    public string Value {{ get; }}\n    internal string ToWire() => string.IsNullOrEmpty(Value) ? throw new ArgumentException(\"{ty} must be non-empty\", nameof(Value)) : Value;\n}}\n\n"));
            }
            WireValueKind::Bytes => {
                let constructor_checks = checks(item.rules, "value");
                let wire_checks = checks(item.rules, "Value");
                out.push_str(&format!("public readonly record struct {ty}\n{{\n    private readonly byte[] _value;\n    public {ty}(ReadOnlyMemory<byte> value)\n    {{\n        var bytes = value.ToArray();\n        {constructor_checks}        _value = bytes;\n    }}\n    public ReadOnlyMemory<byte> Value => _value ?? Array.Empty<byte>();\n    internal ByteString ToWire()\n    {{\n        var bytes = _value ?? Array.Empty<byte>();\n        {wire_checks}        return ByteString.CopyFrom(bytes);\n    }}\n}}\n\n"));
            }
            WireValueKind::UnsignedInteger => {
                let max = item.rules.iter().find_map(|rule| match rule {
                    SemanticRule::MaxItems(value) => Some(*value),
                    _ => None,
                });
                let max_check_constructor = max.map(|value| format!("        if (value > {value}) throw new ArgumentOutOfRangeException(nameof(value));\n")).unwrap_or_default();
                let max_check_wire = max.map(|value| format!("        if (Value > {value}) throw new ArgumentOutOfRangeException(nameof(Value));\n")).unwrap_or_default();
                out.push_str(&format!("public readonly record struct {ty}\n{{\n    public {ty}(ulong value)\n    {{\n        if (value == 0) throw new ArgumentOutOfRangeException(nameof(value));\n{max_check_constructor}        Value = value;\n    }}\n    public ulong Value {{ get; }}\n    internal ulong ToWire()\n    {{\n        if (Value == 0) throw new ArgumentOutOfRangeException(nameof(Value));\n{max_check_wire}        return Value;\n    }}\n}}\n\n"));
            }
            WireValueKind::SignedInteger => {
                let positive = item
                    .rules
                    .iter()
                    .any(|rule| matches!(rule, SemanticRule::StrictlyPositive));
                let check = positive.then(|| "        if (Value <= 0) throw new ArgumentOutOfRangeException(nameof(Value));\n").unwrap_or_default();
                out.push_str(&format!("public readonly record struct {ty}(long Value)\n{{\n    internal long ToWire()\n    {{\n{check}        return Value;\n    }}\n}}\n\n"));
            }
            WireValueKind::Boolean => {
                out.push_str(&format!("public readonly record struct {ty}(bool Value)\n{{\n    internal bool ToWire() => Value;\n}}\n\n"));
            }
            WireValueKind::Timestamp => {
                out.push_str(&format!("public readonly record struct {ty}(DateTimeOffset Value)\n{{\n    internal DateTimeOffset ToWire() => Value;\n}}\n\n"));
            }
            WireValueKind::Message => {
                if item.id == "idempotency_key_message" {
                    out.push_str(&format!("public readonly record struct {ty}\n{{\n    private readonly byte[] _value;\n    public {ty}(ReadOnlyMemory<byte> value)\n    {{\n        var bytes = value.ToArray();\n        if (bytes.Length != 16) throw new ArgumentException(\"{ty} must be a 16-byte UUID\", nameof(value));\n        _value = bytes;\n    }}\n    public ReadOnlyMemory<byte> Value => _value ?? Array.Empty<byte>();\n    internal ByteString ToWire()\n    {{\n        var bytes = _value ?? Array.Empty<byte>();\n        if (bytes.Length != 16) throw new ArgumentException(\"{ty} must be a 16-byte UUID\", nameof(Value));\n        return ByteString.CopyFrom(bytes);\n    }}\n}}\n\n"));
                } else {
                    out.push_str(&format!("public readonly record struct {ty}\n{{\n    public {ty}(string value)\n    {{\n        if (string.IsNullOrEmpty(value)) throw new ArgumentException(\"{ty} must be non-empty\", nameof(value));\n        Value = value;\n    }}\n    public string Value {{ get; }}\n    internal string ToWire() => string.IsNullOrEmpty(Value) ? throw new ArgumentException(\"{ty} must be non-empty\", nameof(Value)) : Value;\n}}\n\n"));
                }
            }
            WireValueKind::Enum | WireValueKind::Oneof => {}
        }
    }
}

fn render_machine_image(out: &mut String) {
    out.push_str(
        "public abstract record ImmutableImage\n{\n    public sealed record Managed(Sha256Digest Digest) : ImmutableImage;\n    public sealed record Custom(Sha256Digest Digest) : ImmutableImage;\n    public sealed record Checkpoint(CheckpointId Id) : ImmutableImage;\n\n    internal Acyclic.Machines.V1.Image ToWire() => this switch\n    {\n        Managed value => new Acyclic.Machines.V1.Image { Kind = Acyclic.Machines.V1.ImageKind.ManagedOci, ManagedDigest = value.Digest.ToWire() },\n        Custom value => new Acyclic.Machines.V1.Image { Kind = Acyclic.Machines.V1.ImageKind.Custom, CustomDigest = value.Digest.ToWire() },\n        Checkpoint value => new Acyclic.Machines.V1.Image { Kind = Acyclic.Machines.V1.ImageKind.Checkpoint, Checkpoint = new Acyclic.Machines.V1.CheckpointId { Value = value.Id.ToWire() } },\n        _ => throw new ArgumentOutOfRangeException(nameof(ImmutableImage)),\n    };\n}\n\n",
    );
}

fn checks(rules: &[SemanticRule], parameter: &str) -> String {
    let mut result = String::new();
    for rule in rules {
        match rule {
            SemanticRule::NonEmpty => result.push_str(&format!("        if (bytes.Length == 0) throw new ArgumentException(\"value must be non-empty\", nameof({parameter}));\n")),
            SemanticRule::FixedLength(length) => result.push_str(&format!("        if (bytes.Length != {length}) throw new ArgumentException(\"value has the wrong length\", nameof({parameter}));\n")),
            SemanticRule::Sha256Digest => result.push_str("        // Rust policy marks this as a SHA-256 digest; length is enforced above.\n"),
            _ => {}
        }
    }
    result
}

fn render_unions(out: &mut String) {
    let mut emitted = BTreeSet::new();
    for union in WIRE_UNION_VARIANTS {
        if !emitted.insert(union.union) {
            continue;
        }
        out.push_str(&format!(
            "public abstract record {}(string Tag, ByteString Payload)\n{{\n",
            union.union
        ));
        out.push_str(&format!(
            "    public sealed record {}(string Tag, ByteString Payload) : {}(Tag, Payload);\n",
            upper(union.variant),
            union.union
        ));
        out.push_str(&format!("    public sealed record Unknown(int RawTag, ByteString Payload) : {}(\"unknown\", Payload);\n", union.union));
        out.push_str("}\n\n");
    }
}

fn render_request_models(out: &mut String) {
    let mut groups: BTreeMap<(&str, &str), Vec<&PublicFieldBinding>> = BTreeMap::new();
    for binding in PUBLIC_FIELD_BINDINGS
        .iter()
        .filter(|binding| binding.direction == PublicFieldDirection::Request)
    {
        groups
            .entry((binding.module, binding.message))
            .or_default()
            .push(binding);
    }
    for ((module, message), fields) in groups {
        let name = format!("{}{}", upper(module), message);
        out.push_str(&format!("public sealed record {name}(\n"));
        for (index, binding) in fields.iter().enumerate() {
            let comma = if index + 1 == fields.len() { "" } else { "," };
            let semantic =
                semantic_type(binding.semantic_type).expect("Rust binding semantic type");
            let type_name = if binding.semantic_type == "immutable_image" {
                "ImmutableImage".to_owned()
            } else {
                csharp_type(semantic.wire_kind, semantic.rust_name)
            };
            out.push_str(&format!(
                "    {} {}{}\n",
                type_name,
                upper(binding.field),
                comma
            ));
        }
        out.push_str(")\n{\n    internal ");
        out.push_str(&format!(
            "{} ToWire()\n    {{\n        var wire = new {}();\n",
            qualified_message(module, message),
            qualified_message(module, message)
        ));
        for binding in fields {
            if let Some(assignment) = csharp_wire_assignment(module, binding) {
                out.push_str(&assignment);
            }
        }
        out.push_str("        return wire;\n    }\n");
        out.push_str("}\n\n");
    }
}

/// Emit complete request records for every descriptor root that carries a
/// Rust semantic binding. These records include ordinary fields as well as
/// refined fields, so a typed public method cannot accidentally discard
/// required, optional, repeated, or oneof wire members.
fn render_full_semantic_request_models(out: &mut String) {
    let fields = resolved_request_fields().expect("Rust request descriptors must resolve");
    let semantic_roots = fields
        .iter()
        .filter(|field| field.message_path == field.root_message && field.semantic_type.is_some())
        .map(|field| (field.family.clone(), field.root_message.clone()))
        .collect::<BTreeSet<_>>();
    let mut groups = BTreeMap::<(String, String), BTreeMap<String, ResolvedRequestField>>::new();
    for field in fields {
        if field.message_path != field.root_message
            || !semantic_roots.contains(&(field.family.clone(), field.root_message.clone()))
        {
            continue;
        }
        let key = (field.family.clone(), field.root_message.clone());
        let entry = groups.entry(key).or_default();
        entry
            .entry(field.field.clone())
            .and_modify(|existing| {
                if existing.semantic_type.is_none() && field.semantic_type.is_some() {
                    *existing = field.clone();
                }
            })
            .or_insert(field);
    }
    for ((family, root), fields) in groups {
        let short_root = root.rsplit('.').next().unwrap_or(root.as_str());
        let model_name = full_request_model_name(&family, short_root);
        out.push_str(&format!("public sealed record {model_name}(\n"));
        let fields = fields.into_values().collect::<Vec<_>>();
        for (index, field) in fields.iter().enumerate() {
            let comma = if index + 1 == fields.len() { "" } else { "," };
            out.push_str(&format!(
                "    {} {}{}\n",
                full_csharp_field_type(field, &family),
                upper(&field.field),
                comma
            ));
        }
        out.push_str(")\n{\n    internal ");
        out.push_str(&format!(
            "{} ToWire()\n    {{\n        var wire = new {}();\n",
            qualified_fq_message(&root, &family),
            qualified_fq_message(&root, &family)
        ));
        for field in &fields {
            for validation in &field.validation_rules {
                if operation_enforcement(validation) == OperationEnforcement::ClientLocal {
                    out.push_str(&format!(
                        "        RustOperationValidationPolicy.ValidateClientPolicy(\"{}\", {});\n",
                        validation,
                        upper(&field.field)
                    ));
                }
            }
            out.push_str(&full_csharp_wire_assignment(field, &family));
        }
        out.push_str("        return wire;\n    }\n}\n\n");
    }
}

fn full_request_model_name(family: &str, message: &str) -> String {
    format!("Rust{}{}", upper(family), message)
}

fn full_csharp_field_type(field: &ResolvedRequestField, family: &str) -> String {
    let mut base = if let Some(semantic_id) = field.semantic_type.as_deref() {
        let semantic = semantic_type(semantic_id).expect("Rust semantic type must resolve");
        if semantic_id == "immutable_image" {
            "ImmutableImage".to_owned()
        } else {
            csharp_type(semantic.wire_kind, semantic.rust_name)
        }
    } else {
        match field.wire_type {
            Some(kind) if kind == FieldType::String as i32 => "string".to_owned(),
            Some(kind) if kind == FieldType::Bytes as i32 => "ByteString".to_owned(),
            Some(kind) if kind == FieldType::Bool as i32 => "bool".to_owned(),
            Some(kind)
                if matches!(
                    kind,
                    x if x == FieldType::Uint32 as i32
                        || x == FieldType::Fixed32 as i32
                ) =>
            {
                "uint".to_owned()
            }
            Some(kind)
                if matches!(
                    kind,
                    x if x == FieldType::Uint64 as i32
                        || x == FieldType::Fixed64 as i32
                ) =>
            {
                "ulong".to_owned()
            }
            Some(kind)
                if matches!(
                    kind,
                    x if x == FieldType::Int32 as i32
                        || x == FieldType::Sint32 as i32
                        || x == FieldType::Sfixed32 as i32
                ) =>
            {
                "int".to_owned()
            }
            Some(kind)
                if matches!(
                    kind,
                    x if x == FieldType::Int64 as i32
                        || x == FieldType::Sint64 as i32
                        || x == FieldType::Sfixed64 as i32
                ) =>
            {
                "long".to_owned()
            }
            Some(kind) if kind == FieldType::Float as i32 => "float".to_owned(),
            Some(kind) if kind == FieldType::Double as i32 => "double".to_owned(),
            Some(kind) if kind == FieldType::Enum as i32 => "int".to_owned(),
            Some(kind) if kind == FieldType::Message as i32 || kind == FieldType::Group as i32 => {
                qualified_fq_message(
                    field
                        .type_name
                        .as_deref()
                        .unwrap_or("google.protobuf.Message"),
                    family,
                )
            }
            _ => "IMessage".to_owned(),
        }
    };
    if field.label == Some(prost_types::field_descriptor_proto::Label::Repeated as i32) {
        base = format!("IReadOnlyList<{base}>");
    } else if field.proto3_optional
        && matches!(
            field.wire_type,
            Some(kind)
                if kind != FieldType::Message as i32
                    && kind != FieldType::Group as i32
                    && kind != FieldType::String as i32
                    && kind != FieldType::Bytes as i32
        )
    {
        base.push('?');
    }
    base
}

fn full_csharp_wire_assignment(field: &ResolvedRequestField, family: &str) -> String {
    let property = upper(&field.field);
    if let Some(binding) = PUBLIC_FIELD_BINDINGS.iter().find(|binding| {
        binding.family == family
            && binding.message == field.root_message.rsplit('.').next().unwrap_or_default()
            && binding.wire_field == field.field
            && binding.direction == PublicFieldDirection::Request
    }) {
        if upper(binding.field) == property {
            if let Some(assignment) = csharp_wire_assignment(family, binding) {
                return assignment;
            }
        }
    }
    if let Some(semantic_id) = field.semantic_type.as_deref() {
        let semantic = semantic_type(semantic_id).expect("Rust semantic type must resolve");
        if family == "machines"
            && matches!(
                semantic_id,
                "machine_id" | "checkpoint_id" | "operation_id" | "idempotency_key_message"
            )
        {
            let message = match field.field.as_str() {
                "machine" => "MachineId",
                "checkpoint" => "CheckpointId",
                "operation" => "OperationId",
                "idempotency_key" => "IdempotencyKey",
                _ => return format!("        wire.{property} = {property}.ToWire();\n"),
            };
            return format!(
                "        wire.{property} = new Acyclic.Machines.V1.{message} {{ Value = {property}.ToWire() }};\n"
            );
        }
        return match semantic.wire_kind {
            WireValueKind::String
            | WireValueKind::Bytes
            | WireValueKind::SignedInteger
            | WireValueKind::Boolean
            | WireValueKind::Timestamp => {
                format!("        wire.{property} = {property}.ToWire();\n")
            }
            WireValueKind::UnsignedInteger => {
                format!("        wire.{property} = checked((uint){property}.ToWire());\n")
            }
            WireValueKind::Message if family == "machines" && field.field == "image" => {
                format!("        wire.{property} = {property}.ToWire();\n")
            }
            WireValueKind::Message if family == "machines" => {
                let message = match field.field.as_str() {
                    "machine" => "MachineId",
                    "checkpoint" => "CheckpointId",
                    "operation" => "OperationId",
                    "idempotency_key" => "IdempotencyKey",
                    _ => "",
                };
                if message.is_empty() {
                    format!("        wire.{property} = {property};\n")
                } else {
                    format!(
                        "        wire.{property} = new Acyclic.Machines.V1.{message} {{ Value = {property}.ToWire() }};\n"
                    )
                }
            }
            WireValueKind::Message | WireValueKind::Enum | WireValueKind::Oneof => {
                format!("        wire.{property} = {property};\n")
            }
        };
    }
    let repeated = field.label == Some(prost_types::field_descriptor_proto::Label::Repeated as i32);
    let message = matches!(
        field.wire_type,
        Some(kind) if kind == FieldType::Message as i32 || kind == FieldType::Group as i32
    );
    if repeated {
        return format!("        wire.{property}.AddRange({property});\n");
    }
    if message {
        return format!("        if ({property} is not null) wire.{property} = {property};\n");
    }
    if field.wire_type == Some(FieldType::Enum as i32) {
        let enum_type = qualified_fq_message(
            field
                .type_name
                .as_deref()
                .unwrap_or("google.protobuf.NullValue"),
            family,
        );
        return format!("        wire.{property} = ({enum_type}){property};\n");
    }
    if field.proto3_optional
        && matches!(
            field.wire_type,
            Some(kind)
                if kind == FieldType::Uint64 as i32
                    || kind == FieldType::Int64 as i32
                    || kind == FieldType::Uint32 as i32
                    || kind == FieldType::Int32 as i32
        )
    {
        return format!("        wire.{property} = {property} ?? 0;\n");
    }
    format!("        wire.{property} = {property};\n")
}

fn csharp_wire_assignment(module: &str, binding: &PublicFieldBinding) -> Option<String> {
    let semantic = semantic_type(binding.semantic_type).expect("Rust binding semantic type");
    let property = upper(binding.wire_field);
    let value = upper(binding.field);
    if module == "machines" {
        if binding.wire_field == "image" {
            return Some(format!("        wire.{property} = {value}.ToWire();\n"));
        }
        let message = match binding.wire_field {
            "machine" => Some("MachineId"),
            "checkpoint" => Some("CheckpointId"),
            "operation" => Some("OperationId"),
            "idempotency_key" => Some("IdempotencyKey"),
            _ => None,
        };
        if let Some(message) = message {
            return Some(format!(
                "        wire.{property} = new Acyclic.Machines.V1.{message} {{ Value = {value}.ToWire() }};\n"
            ));
        }
    }
    let line = match semantic.wire_kind {
        WireValueKind::String => format!("        wire.{property} = {value}.ToWire();\n"),
        WireValueKind::Bytes => format!("        wire.{property} = {value}.ToWire();\n"),
        WireValueKind::UnsignedInteger => {
            format!("        wire.{property} = checked((uint){value}.ToWire());\n")
        }
        WireValueKind::Message if module == "machines" => return None,
        WireValueKind::Message => return None,
        WireValueKind::SignedInteger
        | WireValueKind::Boolean
        | WireValueKind::Timestamp
        | WireValueKind::Enum
        | WireValueKind::Oneof => return None,
    };
    Some(line)
}

