fn go_constructor_name(item: &crate::type_policy::SemanticType) -> String {
    let duplicate = SEMANTIC_TYPES
        .iter()
        .filter(|other| other.rust_name == item.rust_name)
        .count()
        > 1;
    if !duplicate {
        return go_type_name(item.rust_name);
    }
    let mut result = String::new();
    for part in item.id.split('_') {
        if part.is_empty() {
            continue;
        }
        let mut chars = part.chars();
        if let Some(first) = chars.next() {
            result.push(first.to_ascii_uppercase());
            result.extend(chars);
        }
    }
    if result.ends_with("Id") {
        result.truncate(result.len() - 2);
        result.push_str("ID");
    }
    result
}

