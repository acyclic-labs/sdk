fn py_bool(value: bool) -> &'static str {
    if value { "True" } else { "False" }
}

fn py_strings(values: &[&str]) -> String {
    let values = values
        .iter()
        .map(|value| format!("{:?}", value))
        .collect::<Vec<_>>()
        .join(", ");
    format!("[{}]", values)
}

fn go_strings(values: &[&str]) -> String {
    let values = values
        .iter()
        .map(|value| format!("{:?}", value))
        .collect::<Vec<_>>()
        .join(", ");
    format!("[]string{{{}}}", values)
}
