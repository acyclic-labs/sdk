fn python_public_binding_annotation(
    binding: &PublicFieldBinding,
    item: &crate::type_policy::SemanticType,
) -> String {
    if matches!(
        binding.semantic_type,
        "machine_id" | "checkpoint_id" | "operation_id"
    ) {
        return item.rust_name.to_owned();
    }
    if public_binding_is_message(binding) {
        return match binding.semantic_type {
            "immutable_image" => "machines_pb2.Image".to_owned(),
            "idempotency_key_message" => "machines_pb2.IdempotencyKey".to_owned(),
            "machine_id" => "machines_pb2.MachineId".to_owned(),
            "checkpoint_id" => "machines_pb2.CheckpointId".to_owned(),
            "operation_id" => "machines_pb2.OperationId".to_owned(),
            _ => "object".to_owned(),
        };
    }
    match item.wire_kind {
        WireValueKind::Message => match binding.semantic_type {
            "immutable_image" => "machines_pb2.Image".to_owned(),
            "idempotency_key_message" => "machines_pb2.IdempotencyKey".to_owned(),
            _ => "object".to_owned(),
        },
        _ => format!("{}Value", item.rust_name),
    }
}

fn python_public_binding_wire_value(
    binding: &PublicFieldBinding,
    item: &crate::type_policy::SemanticType,
    field_name: &str,
    function: &str,
) -> String {
    if matches!(
        binding.semantic_type,
        "machine_id" | "checkpoint_id" | "operation_id"
    ) {
        let message = match binding.semantic_type {
            "machine_id" => "MachineId",
            "checkpoint_id" => "CheckpointId",
            "operation_id" => "OperationId",
            _ => unreachable!(),
        };
        return format!("machines_pb2.{message}(value={function}(self.{field_name}))");
    }
    if public_binding_is_message(binding) {
        return format!("self.{field_name}");
    }
    match item.wire_kind {
        WireValueKind::Message => format!("self.{field_name}"),
        _ => format!("{function}(self.{field_name})"),
    }
}

fn python_public_binding_from_wire_value(
    binding: &PublicFieldBinding,
    _field_name: &str,
    function: &str,
) -> String {
    if public_binding_requires_message_wrapper(binding) {
        return format!("{function}(message.{}.value)", binding.wire_field);
    }
    format!("{function}(message.{})", binding.wire_field)
}

