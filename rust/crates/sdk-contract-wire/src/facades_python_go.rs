/// Emit one concrete public model for each Rust-owned semantic field binding.
/// These models deliberately construct or decode the real generated protobuf
/// message; `SemanticFieldValues` remains only a compact inventory view.
fn python_public_field_models() -> String {
    let mut output = String::from(
        "# Concrete public request/response bindings; generated from Rust policy.\n\n",
    );
    output
        .push_str("PUBLIC_FIELD_BINDINGS: dict[tuple[str, str], tuple[str, str, str, str]] = {\n");
    for binding in PUBLIC_FIELD_BINDINGS {
        output.push_str(&format!(
            "    ({family:?}, {field:?}): ({module:?}, {message:?}, {wire_field:?}, {direction:?}),\n",
            family = binding.family,
            field = binding.field,
            module = binding.module,
            message = binding.message,
            wire_field = binding.wire_field,
            direction = python_binding_direction(binding.direction),
        ));
    }
    output.push_str("}\n\n");
    for binding in PUBLIC_FIELD_BINDINGS {
        let item = semantic_type(binding.semantic_type).expect("public field semantic type");
        let class_name = python_public_binding_name(binding);
        let field_name = snake_case(binding.field);
        let module = format!("{}_pb2", binding.module);
        let function = snake_case(item.id);
        let annotation = python_public_binding_annotation(binding, item);
        output.push_str("@dataclass(frozen=True)\n");
        output.push_str(&format!(
            "class {class_name}:\n    {field_name}: {annotation}\n\n"
        ));
        match binding.direction {
            PublicFieldDirection::Response => {
                output.push_str(&format!(
                    "    @classmethod\n    def from_wire(cls, message: {module}.{message}) -> \"{class_name}\":\n        return cls({field_name}={expression})\n\n",
                    module = module,
                    message = binding.message,
                    field_name = field_name,
                    class_name = class_name,
                    expression = python_public_binding_from_wire_value(binding, &field_name, &function),
                ));
            }
            PublicFieldDirection::Request | PublicFieldDirection::NestedMessage => {
                let expression =
                    python_public_binding_wire_value(binding, item, &field_name, &function);
                let presence = if public_binding_requires_presence(binding) {
                    format!(
                        "        if self.{field_name} is None:\n            raise ValueError(\"{field_name} must be present\")\n"
                    )
                } else {
                    String::new()
                };
                output.push_str(&format!(
                    "    def to_wire(self) -> {module}.{message}:\n{presence}        value = {expression}\n        return {module}.{message}({wire_field}=value)\n\n",
                    module = module,
                    message = binding.message,
                    expression = expression,
                    wire_field = binding.wire_field,
                    presence = presence,
                ));
            }
            PublicFieldDirection::EmbeddedOnly => {
                // Embedded bindings are usable in both directions: they are
                // carried by nested request messages, while the same Rust
                // semantic model must decode the nested value when it is
                // returned by an embedded operation. Keep both projections
                // generated from this single Rust-owned binding.
                let to_wire_expression =
                    python_public_binding_wire_value(binding, item, &field_name, &function);
                let from_wire_expression =
                    python_public_binding_from_wire_value(binding, &field_name, &function);
                output.push_str(&format!(
                    "    @classmethod\n    def from_wire(cls, message: {module}.{message}) -> \"{class_name}\":\n        return cls({field_name}={from_wire_expression})\n\n    def to_wire(self) -> {module}.{message}:\n        value = {to_wire_expression}\n        return {module}.{message}({wire_field}=value)\n\n",
                    module = module,
                    message = binding.message,
                    field_name = field_name,
                    class_name = class_name,
                    from_wire_expression = from_wire_expression,
                    to_wire_expression = to_wire_expression,
                    wire_field = binding.wire_field,
                ));
            }
        }
    }
    output
}

