//! Rust-owned PHP runtime shims used by generated message and remote facades.
//!
//! These are deliberately emitted from this crate instead of being maintained
//! as a second PHP implementation.  The PHP runtime still provides the native
//! scalar operations, but the public boundary and protobuf edge cases are
//! fixed by this Rust-owned template.

/// Generated PHP runtime paths emitted with the product bundle.
pub const PHP_UINT64_PATH: &str = "php/src/Acyclic/Runtime/UInt64.php";

/// Generate the PHP runtime bundle consumed by generated PHP messages.
pub fn generate_php_runtime_bundle() -> Vec<(&'static str, String)> {
    vec![(PHP_UINT64_PATH, render_uint64())]
}

fn render_uint64() -> String {
    r###"<?php

// Generated by acyclic-sdk-contract-wire; do not edit.

declare(strict_types=1);

namespace Acyclic\Runtime;

use InvalidArgumentException;
use JsonSerializable;
use Stringable;

/**
 * Exact unsigned 64-bit value for PHP boundaries.
 *
 * PHP's integer representation cannot carry the complete uint64 range on
 * every supported runtime. Keep values above PHP_INT_MAX as decimal strings
 * and encode/decode their protobuf varints without floating-point conversion.
 */
final class UInt64 implements JsonSerializable, Stringable
{
    private const MAX = '18446744073709551615';
    private readonly string $decimal;

    /** Construct the exact decimal representation used by generated defaults. */
    public function __construct(string $decimal)
    {
        self::validateDecimal($decimal);
        $this->decimal = $decimal;
    }

    private static function validateDecimal(string $value): void
    {
        if (!preg_match('/^(?:0|[1-9][0-9]*)$/', $value)) {
            throw new InvalidArgumentException('uint64 must be a non-negative decimal string');
        }
        if (self::compare($value, self::MAX) > 0) {
            throw new InvalidArgumentException('uint64 is greater than 18446744073709551615');
        }
    }

    public static function fromString(string $value): self
    {
        self::validateDecimal($value);
        return new self($value);
    }

    public static function fromInt(int $value): self
    {
        if ($value < 0) {
            throw new InvalidArgumentException('uint64 cannot be negative');
        }
        return new self((string) $value);
    }

    /** Accept the official protobuf PHP scalar without narrowing it. */
    public static function fromWireScalar(int|string $value): self
    {
        return is_int($value) ? self::fromInt($value) : self::fromString($value);
    }

    /** Validate a generated protobuf scalar without silent narrowing. */
    public static function validateGeneratedScalar(int|string $value): int|string
    {
        if (is_int($value)) {
            if ($value < 0) {
                throw new InvalidArgumentException('uint64 cannot be negative');
            }
            return $value;
        }

        $exact = self::fromString($value)->toString();
        if (self::compare($exact, (string) PHP_INT_MAX) > 0) {
            throw new InvalidArgumentException(
                'uint64 above PHP_INT_MAX requires Acyclic\\Runtime\\UInt64 for exact representation'
            );
        }
        return (int) $exact;
    }

    public static function fromWireVarint(string $wire): self
    {
        if ($wire === '') {
            throw new InvalidArgumentException('uint64 varint cannot be empty');
        }
        $value = '0';
        $multiplier = '1';
        $length = strlen($wire);
        for ($index = 0; $index < $length; $index++) {
            $byte = ord($wire[$index]);
            if ($index === 9 && ($byte & 0x7e) !== 0) {
                throw new InvalidArgumentException('uint64 varint exceeds 64 bits');
            }
            $value = self::add($value, self::multiplySmall($multiplier, $byte & 0x7f));
            $multiplier = self::multiplySmall($multiplier, 128);
            if (($byte & 0x80) === 0) {
                if ($index !== $length - 1) {
                    throw new InvalidArgumentException('uint64 varint has trailing bytes');
                }
                return self::fromString($value);
            }
            if ($index === 9) {
                throw new InvalidArgumentException('uint64 varint exceeds 64 bits');
            }
        }
        throw new InvalidArgumentException('uint64 varint is unterminated');
    }

    public function toString(): string
    {
        return $this->decimal;
    }

    public function __toString(): string
    {
        return $this->decimal;
    }

    /** Return the exact decimal scalar expected by generated protobuf setters. */
    public function toWire(): string
    {
        return $this->decimal;
    }

    public function jsonSerialize(): string
    {
        return $this->decimal;
    }

    /** Return the protobuf wire value for a uint64 field without clamping. */
    public function toWireVarint(): string
    {
        $value = $this->decimal;
        $wire = '';
        while ($value !== '0') {
            [$value, $remainder] = self::divideSmall($value, 128);
            $wire .= chr($remainder | ($value !== '0' ? 0x80 : 0));
        }
        return $wire === '' ? "\x00" : $wire;
    }

    private static function compare(string $left, string $right): int
    {
        $left = ltrim($left, '0') ?: '0';
        $right = ltrim($right, '0') ?: '0';
        return strlen($left) <=> strlen($right) ?: strcmp($left, $right);
    }

    private static function add(string $left, string $right): string
    {
        $index = strlen($left) - 1;
        $other = strlen($right) - 1;
        $carry = 0;
        $result = '';
        while ($index >= 0 || $other >= 0 || $carry !== 0) {
            $sum = $carry + ($index >= 0 ? (int) $left[$index--] : 0)
                + ($other >= 0 ? (int) $right[$other--] : 0);
            $result = (string) ($sum % 10) . $result;
            $carry = intdiv($sum, 10);
        }
        return ltrim($result, '0') ?: '0';
    }

    private static function multiplySmall(string $value, int $factor): string
    {
        $carry = 0;
        $result = '';
        for ($index = strlen($value) - 1; $index >= 0; $index--) {
            $product = ((int) $value[$index] * $factor) + $carry;
            $result = (string) ($product % 10) . $result;
            $carry = intdiv($product, 10);
        }
        while ($carry > 0) {
            $result = (string) ($carry % 10) . $result;
            $carry = intdiv($carry, 10);
        }
        return ltrim($result, '0') ?: '0';
    }

    /** @return array{string, int} */
    private static function divideSmall(string $value, int $divisor): array
    {
        $quotient = '';
        $carry = 0;
        for ($index = 0; $index < strlen($value); $index++) {
            $current = ($carry * 10) + (int) $value[$index];
            $digit = intdiv($current, $divisor);
            if ($quotient !== '' || $digit !== 0) {
                $quotient .= (string) $digit;
            }
            $carry = $current % $divisor;
        }
        return [$quotient === '' ? '0' : $quotient, $carry];
    }
}
"###.to_owned()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn uint64_runtime_is_a_generated_product() {
        let bundle = generate_php_runtime_bundle();
        assert_eq!(bundle.len(), 1);
        assert_eq!(bundle[0].0, PHP_UINT64_PATH);
        assert!(bundle[0].1.contains("Generated by acyclic-sdk-contract-wire"));
        assert!(bundle[0].1.contains("fromWireScalar"));
        assert!(bundle[0].1.contains("fromWireVarint"));
        assert!(bundle[0].1.contains("function toWire(): string"));
        assert!(bundle[0].1.contains("validateGeneratedScalar"));
        assert!(bundle[0].1.contains("public function __construct(string $decimal)"));
    }
}
