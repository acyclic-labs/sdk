//! Actual Daytona retained-session and PTY transports.
//!
//! Wire contract: official `daytona/clients` revision
//! `04f85030edec67095cf38f06fce01ee0082d9a2e`, `openapi-specs/toolbox.json`
//! and `sdk-typescript/src/{Process,PtyHandle}.ts`. Caller-owned operation and
//! session identities must be committed at Root before any mutation. No method
//! retries an effect, invents a command ID, or treats an empty observation as
//! permission to replace a command after a lost ACK.
//!
//! Session input is a provider line/FIFO API, NOT raw process stdin. For genuine
//! non-PTY process semantics, run the pinned official Codex executable with
//! `exec-server --listen stdio` in a dedicated owned session. Its canonical
//! JSON-lines transport carries raw child stdin/EOF/Interrupt inside protocol
//! messages; the provider FIFO's newline is only transport framing.
