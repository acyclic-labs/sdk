fn original_mutation<T>(result: Result<T, ProviderError>, operation: OperationId) -> Result<T, ProviderError> {
    match result {
        // A transport failure, server failure or malformed success body may
        // follow an accepted effect. Preserve the caller's original identity.
        Err(ProviderError::Unavailable | ProviderError::Rejected(_)) =>
            Err(ProviderError::OperationIndeterminate(operation)),
        result => result,
    }
}

fn observe_original_command(
    session: Session,
    original: &SessionExecuteRequest,
) -> Result<SessionCommandObservation, ProviderError> {
    let mut commands = session.commands.into_iter();
    match (commands.next(), commands.next()) {
        (None, None) => Ok(SessionCommandObservation::NotObserved),
        (Some(command), None) if command.command == original.command =>
            Ok(SessionCommandObservation::Observed(command)),
        _ => Err(ProviderError::Conflict("dedicated original session contains a different command intent".into())),
    }
}

fn checked_segment(value: &str) -> Result<(), ProviderError> {
    if value.is_empty() || matches!(value, "." | "..") {
        return Err(ProviderError::Invalid("provider identity is not a path segment".into()));
    }
    Ok(())
}

impl DaytonaApi {
    async fn session_route(&self, sandbox_id: &str, route: &str, segments: &[&str]) -> Result<Url, ProviderError> {
        for segment in segments { checked_segment(segment)?; }
        let url = self.toolbox_url(sandbox_id, route).await?;
        let mut url = Url::parse(&url)
            .map_err(|_| ProviderError::Rejected("invalid owned toolbox route".into()))?;
        url.path_segments_mut().map_err(|_| ProviderError::Rejected("toolbox route cannot hold path segments".into()))?
            .extend(segments.iter().copied());
        Ok(url)
    }

    /// Creates exactly the caller-retained session. Conflict requires readback,
    /// not a fabricated success or a new session identity.
    pub async fn create_session(&self, sandbox_id: &str, request: &CreateSessionRequest, operation: OperationId) -> Result<(), ProviderError> {
        checked_segment(&request.session_id)?;
        let url = self.session_route(sandbox_id, "process/session", &[]).await?;
        original_mutation(self.empty("create_session", self.authorized(self.http.post(url)).json(request)).await, operation)
    }

    /// Gets actual retained session/command records from its owned sandbox.
    pub async fn get_session(&self, sandbox_id: &str, session_id: &str) -> Result<Session, ProviderError> {
        let url = self.session_route(sandbox_id, "process/session", &[session_id]).await?;
        let session: Session = self.json("get_session", self.authorized(self.http.get(url))).await?;
        if session.session_id != session_id {
            return Err(ProviderError::Rejected("provider returned another session".into()));
        }
        Ok(session)
    }

    /// Lists actual retained provider sessions.
    pub async fn list_sessions(&self, sandbox_id: &str) -> Result<Vec<Session>, ProviderError> {
        let url = self.session_route(sandbox_id, "process/session", &[]).await?;
        self.json("list_sessions", self.authorized(self.http.get(url))).await
    }

    /// Deletes the exact retained session. The provider's acknowledgment is not
    /// a substitute for Root's A/B/Fs physical finality or an invented exit code.
    pub async fn delete_session(&self, sandbox_id: &str, session_id: &str, operation: OperationId) -> Result<(), ProviderError> {
        let url = self.session_route(sandbox_id, "process/session", &[session_id]).await?;
        original_mutation(self.empty("delete_session", self.authorized(self.http.delete(url))).await, operation)
    }

    /// Starts the actual provider command once. Commit the stable dedicated
    /// session and exact request before calling. Never retry after uncertainty;
    /// reconcile the retained singleton and preserve its actual generated ID.
    pub async fn execute_session_command(&self, sandbox_id: &str, session_id: &str, request: &SessionExecuteRequest, operation: OperationId) -> Result<SessionExecuteResponse, ProviderError> {
        let url = self.session_route(sandbox_id, "process/session", &[session_id, "exec"]).await?;
        original_mutation(self.json("execute_session_command", self.authorized(self.http.post(url))
            .header(SPLIT_OUTPUT_HEADER, "true").json(request)).await, operation)
    }

    /// Observes the exact original command in a dedicated singleton session.
    /// An empty or missing session remains `NotObserved`, NOT safely retryable.
    pub async fn reconcile_session_command(&self, sandbox_id: &str, session_id: &str, original: &SessionExecuteRequest) -> Result<SessionCommandObservation, ProviderError> {
        let session = match self.get_session(sandbox_id, session_id).await {
            Ok(session) => session,
            Err(ProviderError::NotFound(_)) => return Ok(SessionCommandObservation::NotObserved),
            Err(error) => return Err(error),
        };
        observe_original_command(session, original)
    }

    /// Gets actual command metadata, including an optional observed exit code.
    pub async fn get_session_command(&self, sandbox_id: &str, session_id: &str, command_id: &str) -> Result<SessionCommand, ProviderError> {
        let url = self.session_route(sandbox_id, "process/session", &[session_id, "command", command_id]).await?;
        let command: SessionCommand = self.json("get_session_command", self.authorized(self.http.get(url))).await?;
        if command.id != command_id {
            return Err(ProviderError::Rejected("provider returned another command".into()));
        }
        Ok(command)
    }

    /// Reads actual multiplexed provider log bytes. `X-Daytona-Split-Output`
    /// negotiates the documented labels without pretending to be an official
    /// Daytona SDK package/version. No UTF-8 replacement or terminal conversion.
    pub async fn get_session_command_logs(&self, sandbox_id: &str, session_id: &str, command_id: &str) -> Result<SessionLogSnapshot, ProviderError> {
        let url = self.session_route(sandbox_id, "process/session", &[session_id, "command", command_id, "logs"]).await?;
        self.send("get_session_command_logs", self.authorized(self.http.get(url))
            .header(SPLIT_OUTPUT_HEADER, "true"), |bytes| Ok(SessionLogSnapshot { bytes })).await
    }

    /// Writes provider line input. The provider may append a newline; this is
    /// NOT raw child stdin, descriptor closure, a signal or an execution ACK.
    pub async fn send_session_command_input(&self, sandbox_id: &str, session_id: &str, command_id: &str, data: &str, operation: OperationId) -> Result<(), ProviderError> {
        let url = self.session_route(sandbox_id, "process/session", &[session_id, "command", command_id, "input"]).await?;
        original_mutation(self.empty("send_session_command_input", self.authorized(self.http.post(url))
            .json(&serde_json::json!({"data": data}))).await, operation)
    }

    /// Creates the real provider terminal using the retained original ID.
    pub async fn create_pty(&self, sandbox_id: &str, request: &PtyCreateRequest, operation: OperationId) -> Result<PtyCreateResponse, ProviderError> {
        checked_segment(&request.id)?;
        let url = self.session_route(sandbox_id, "process/pty", &[]).await?;
        let result: Result<PtyCreateResponse, ProviderError> = self.json("create_pty", self.authorized(self.http.post(url)).json(request)).await;
        let result = result.and_then(|response| {
            if response.session_id == request.id { Ok(response) }
            else { Err(ProviderError::Rejected("provider returned another PTY".into())) }
        });
        original_mutation(result, operation)
    }

    /// Reads the actual provider PTY record. An active flag is not finality.
    pub async fn get_pty_session(&self, sandbox_id: &str, session_id: &str) -> Result<PtySessionInfo, ProviderError> {
        let url = self.session_route(sandbox_id, "process/pty", &[session_id]).await?;
        let info: PtySessionInfo = self.json("get_pty_session", self.authorized(self.http.get(url))).await?;
        if info.id != session_id { return Err(ProviderError::Rejected("provider returned another PTY".into())); }
        Ok(info)
    }

    /// Lists actual provider terminal records.
    pub async fn list_pty_sessions(&self, sandbox_id: &str) -> Result<Vec<PtySessionInfo>, ProviderError> {
        let url = self.session_route(sandbox_id, "process/pty", &[]).await?;
        let response: PtyListResponse = self.json("list_pty_sessions", self.authorized(self.http.get(url))).await?;
        Ok(response.sessions)
    }

    /// Resizes the real provider terminal; caller retains the mutation identity.
    pub async fn resize_pty_session(&self, sandbox_id: &str, session_id: &str, size: PtyResizeRequest, operation: OperationId) -> Result<PtySessionInfo, ProviderError> {
        let url = self.session_route(sandbox_id, "process/pty", &[session_id, "resize"]).await?;
        let result: Result<PtySessionInfo, ProviderError> = self.json("resize_pty_session", self.authorized(self.http.post(url)).json(&size)).await;
        original_mutation(result.and_then(|info| {
            if info.id == session_id { Ok(info) }
            else { Err(ProviderError::Rejected("provider returned another PTY".into())) }
        }), operation)
    }

    /// Deletes the real provider terminal, without inventing a process exit ACK.
    pub async fn kill_pty_session(&self, sandbox_id: &str, session_id: &str, operation: OperationId) -> Result<(), ProviderError> {
        let url = self.session_route(sandbox_id, "process/pty", &[session_id]).await?;
        original_mutation(self.empty("kill_pty_session", self.authorized(self.http.delete(url))).await, operation)
    }

    /// Opens a real retained-command log stream. Each connection starts with
    /// provider-retained logs; the original owner must persist its read cursor.
    pub async fn connect_session_command_logs(&self, sandbox_id: &str, session_id: &str, command_id: &str) -> Result<SessionLogStream, ProviderError> {
        let mut url = self.session_route(sandbox_id, "process/session", &[session_id, "command", command_id, "logs"]).await?;
        url.query_pairs_mut().append_pair("follow", "true");
        let socket = self.upgrade_toolbox(self.authorized(self.http.get(url))
            .header(SPLIT_OUTPUT_HEADER, "true"), None).await?;
        Ok(SessionLogStream { socket })
    }

    /// Connects to the real retained PTY. A lazy-start PTY can start here, so the
    /// caller must commit and authorize the operation before opening the socket.
    pub async fn connect_pty(&self, sandbox_id: &str, session_id: &str, operation: OperationId) -> Result<PtyConnection, ProviderError> {
        let url = self.session_route(sandbox_id, "process/pty", &[session_id, "connect"]).await?;
        let socket = original_mutation(self.upgrade_toolbox(self.authorized(self.http.get(url)), Some(PTY_EXIT_CONTROL)).await, operation)?;
        Ok(PtyConnection { socket, session_id: session_id.to_owned(), connected: false })
    }

    async fn upgrade_toolbox(&self, builder: RequestBuilder, subprotocol: Option<&str>) -> Result<WebSocketStream<reqwest::Upgraded>, ProviderError> {
        use reqwest::header::{CONNECTION, UPGRADE, SEC_WEBSOCKET_ACCEPT, SEC_WEBSOCKET_KEY, SEC_WEBSOCKET_PROTOCOL, SEC_WEBSOCKET_VERSION};
        let key = tokio_tungstenite::tungstenite::handshake::client::generate_key();
        let expected = tokio_tungstenite::tungstenite::handshake::derive_accept_key(key.as_bytes());
        let builder = builder.version(reqwest::Version::HTTP_11)
            .header(CONNECTION, "Upgrade").header(UPGRADE, "websocket")
            .header(SEC_WEBSOCKET_VERSION, "13").header(SEC_WEBSOCKET_KEY, key);
        let builder = match subprotocol {
            Some(protocol) => builder.header(SEC_WEBSOCKET_PROTOCOL, protocol),
            None => builder,
        };
        // Reuses this exact native client's HTTP/TLS, org and credential binding.
        // No alternate connector, public preview token, new API key or retry.
        let response = builder.send().await.map_err(|error| transport_error(&error))?;
        let status = response.status();
        if status != reqwest::StatusCode::SWITCHING_PROTOCOLS {
            let body = response.bytes().await.map_err(|error| transport_error(&error))?;
            return Err(status_error(status, &String::from_utf8_lossy(&body)));
        }
        let headers = response.headers();
        let accepted = headers.get(SEC_WEBSOCKET_ACCEPT).and_then(|value| value.to_str().ok()) == Some(expected.as_str());
        let upgraded = headers.get(UPGRADE).and_then(|value| value.to_str().ok()).is_some_and(|value| value.eq_ignore_ascii_case("websocket"));
        let connected = headers.get(CONNECTION).and_then(|value| value.to_str().ok()).is_some_and(|value| value.split(',').any(|token| token.trim().eq_ignore_ascii_case("upgrade")));
        let protocol = headers.get(SEC_WEBSOCKET_PROTOCOL).and_then(|value| value.to_str().ok());
        if !accepted || !upgraded || !connected || protocol != subprotocol {
            return Err(ProviderError::Rejected("invalid owned provider WebSocket upgrade".into()));
        }
        let stream = response.upgrade().await.map_err(|error| transport_error(&error))?;
        let config = WebSocketConfig::default().max_message_size(Some(MAX_MESSAGE_BYTES))
            .max_frame_size(Some(MAX_MESSAGE_BYTES)).max_write_buffer_size(MAX_MESSAGE_BYTES + 128 * 1024);
        Ok(WebSocketStream::from_raw_socket(stream, Role::Client, Some(config)).await)
    }
}

/// Genuine provider log frames. Socket closure is not a command exit receipt.
pub struct SessionLogStream { socket: WebSocketStream<reqwest::Upgraded> }
impl SessionLogStream {
    /// Reads the next actual binary/text log frame; does not fabricate output or
    /// suppress transport loss. Caller demultiplexes the documented raw labels.
    pub async fn next_frame(&mut self) -> Result<Option<Message>, ProviderError> {
        loop {
            match self.socket.next().await {
                Some(Ok(message @ (Message::Binary(_) | Message::Text(_)))) => return Ok(Some(message)),
                Some(Ok(Message::Ping(bytes))) => self.socket.send(Message::Pong(bytes)).await.map_err(|_| ProviderError::Unavailable)?,
                Some(Ok(Message::Pong(_))) => {},
                Some(Ok(Message::Close(_))) | None => return Ok(None),
                _ => return Err(ProviderError::Unavailable),
            }
        }
    }
    /// Closes only this log observer, never the retained original command.
    pub async fn disconnect(mut self) -> Result<(), ProviderError> {
        self.socket.close(None).await.map_err(|_| ProviderError::Unavailable)
    }
}

/// Genuine provider PTY events. Terminal bytes remain distinct from native
/// process pipes; a connection close is not synthesized into an exit code.
#[derive(Debug)]
pub enum PtyEvent {
    /// Actual provider connected control frame.
    Connected,
    /// Actual terminal text/binary bytes, without lossy conversion or copying.
    Output(Message),
    /// Actual provider exit control frame. A missing exit code remains unknown.
    Exited {
        /// Actual provider-reported process status; absence remains unknown.
        exit_code: Option<i64>,
        /// Actual provider exit reason, when present.
        reason: Option<String>,
    },
    /// Actual provider control error.
    Error(String),
    /// WebSocket closed without a native exit receipt.
    Closed,
}

/// A transport fact, NOT an application acknowledgment or consumed-stdin proof.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct PtyInputFlushed {
    /// Bytes flushed to the WebSocket transport; no provider write-ID ACK exists.
    pub bytes: usize,
}

/// Real provider terminal connection; Root credentials are not retained here.
pub struct PtyConnection {
    socket: WebSocketStream<reqwest::Upgraded>,
    session_id: String,
    connected: bool,
}
impl std::fmt::Debug for PtyConnection {
    fn fmt(&self, formatter: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        formatter.debug_struct("PtyConnection").field("session_id", &self.session_id)
            .field("connected", &self.connected).finish_non_exhaustive()
    }
}
#[derive(Deserialize)]
#[serde(rename_all = "camelCase")]
struct PtyControl {
    #[serde(rename = "type")]
    kind: String,
    status: String,
    #[serde(default)]
    exit_code: Option<i64>,
    #[serde(default)]
    exit_reason: Option<String>,
    #[serde(default)]
    error: Option<String>,
}
impl PtyConnection {
    /// Reads a genuine terminal event. Only the actual connected control frame
    /// authorizes this handle to send terminal input.
    pub async fn next_event(&mut self) -> Result<PtyEvent, ProviderError> {
        loop {
            match self.socket.next().await {
                Some(Ok(Message::Text(text))) => {
                    if let Ok(control) = serde_json::from_str::<PtyControl>(&text) {
                        if control.kind == "control" {
                            return match control.status.as_str() {
                                "connected" => { self.connected = true; Ok(PtyEvent::Connected) },
                                "exited" => { self.connected = false; Ok(PtyEvent::Exited { exit_code: control.exit_code, reason: control.exit_reason }) },
                                "error" => { self.connected = false; Ok(PtyEvent::Error(control.error.unwrap_or_else(|| "provider PTY control error".into()))) },
                                _ => Err(ProviderError::Rejected("unsupported provider PTY control frame".into())),
                            };
                        }
                    }
                    return Ok(PtyEvent::Output(Message::Text(text)));
                },
                Some(Ok(message @ Message::Binary(_))) => return Ok(PtyEvent::Output(message)),
                Some(Ok(Message::Ping(bytes))) => self.socket.send(Message::Pong(bytes)).await.map_err(|_| ProviderError::Unavailable)?,
                Some(Ok(Message::Pong(_))) => {},
                Some(Ok(Message::Close(_))) | None => { self.connected = false; return Ok(PtyEvent::Closed); },
                _ => { self.connected = false; return Err(ProviderError::Unavailable); },
            }
        }
    }
    /// Sends actual binary terminal input once. ETX is terminal input, NOT an
    /// OS-signal API. Flush success is not an application ACK; do not replay an
    /// uncertain write or translate this into Codex's native write receipt.
    pub async fn send_input(&mut self, bytes: Vec<u8>, operation: OperationId) -> Result<PtyInputFlushed, ProviderError> {
        if !self.connected { return Err(ProviderError::Invalid("provider PTY connection is not confirmed".into())); }
        let count = bytes.len();
        self.socket.send(Message::Binary(bytes.into())).await
            .map_err(|_| ProviderError::OperationIndeterminate(operation))?;
        Ok(PtyInputFlushed { bytes: count })
    }
    /// Closes only this terminal observer, not its retained provider process.
    pub async fn disconnect(mut self) -> Result<(), ProviderError> {
        self.socket.close(None).await.map_err(|_| ProviderError::Unavailable)
    }
}

/// Canonical protocol of the actual pinned native process producer. This is the
/// same upstream revision as the native Codex frontend, not a second RPC schema.
pub use codex_exec_server_protocol as exec_server_protocol;

/// Actual retained identity of a pinned native exec-server session. Constructed
/// only after provider readback of the exact original launch command. This is
/// provider identity, NOT Root authority or a native artifact/inode proof.
#[derive(Debug)]
pub struct ExecServerSession {
    sandbox_id: String,
    session_id: String,
    command_id: String,
}

impl DaytonaApi {
    /// Attaches to the real already-started native producer. Root must provision
    /// and bind the pinned executable's actual bytes/inode before the original
    /// launch, then retain its exact command intent and dedicated session.
    pub async fn attach_exec_server_session(
        &self,
        sandbox_id: &str,
        session_id: &str,
        command_id: &str,
        original_launch: &SessionExecuteRequest,
    ) -> Result<ExecServerSession, ProviderError> {
        if !original_launch.run_async || !original_launch.suppress_input_echo {
            return Err(ProviderError::Invalid("native protocol requires asynchronous unechoed session input".into()));
        }
        match self.reconcile_session_command(sandbox_id, session_id, original_launch).await? {
            SessionCommandObservation::Observed(command) if command.id == command_id => {
                Ok(ExecServerSession {
                    sandbox_id: sandbox_id.to_owned(),
                    session_id: session_id.to_owned(),
                    command_id: command.id,
                })
            }
            _ => Err(ProviderError::Conflict("native producer is not the retained original command".into())),
        }
    }
}

impl ExecServerSession {
    /// Actual retained provider sandbox identity.
    pub fn sandbox_id(&self) -> &str { &self.sandbox_id }
    /// Actual retained caller-owned session identity.
    pub fn session_id(&self) -> &str { &self.session_id }
    /// Actual provider-generated command identity, not an SDK-generated UUID.
    pub fn command_id(&self) -> &str { &self.command_id }

    /// Writes one canonical upstream JSON-RPC line through the actual provider
    /// FIFO. This HTTP ACK acknowledges ONLY line delivery, NOT execution.
    /// The original owner must wait for the genuine correlated native response
    /// in retained stdout before acknowledging execution or applying results.
    /// Never replay this line after uncertainty or mint a replacement ID.
    pub async fn send_message(
        &self,
        api: &DaytonaApi,
        message: &exec_server_protocol::JSONRPCMessage,
        operation: OperationId,
    ) -> Result<(), ProviderError> {
        let line = serde_json::to_string(message)
            .map_err(|_| ProviderError::Invalid("canonical native protocol serialization failed".into()))?;
        if line.len() > MAX_MESSAGE_BYTES {
            return Err(ProviderError::Invalid("canonical native protocol message exceeds its pinned bound".into()));
        }
        api.send_session_command_input(&self.sandbox_id, &self.session_id, &self.command_id, &line, operation).await
    }

    /// Reads actual retained native stdout/stderr bytes for original recovery.
    pub async fn logs(&self, api: &DaytonaApi) -> Result<SessionLogSnapshot, ProviderError> {
        api.get_session_command_logs(&self.sandbox_id, &self.session_id, &self.command_id).await
    }

    /// Observes actual native producer output without a new launch or identity.
    pub async fn connect_logs(&self, api: &DaytonaApi) -> Result<SessionLogStream, ProviderError> {
        api.connect_session_command_logs(&self.sandbox_id, &self.session_id, &self.command_id).await
    }

    /// Reads the native producer's actual provider command status. Absence of an
    /// exit code is never converted into completion or successful termination.
    pub async fn status(&self, api: &DaytonaApi) -> Result<SessionCommand, ProviderError> {
        api.get_session_command(&self.sandbox_id, &self.session_id, &self.command_id).await
    }

    /// Deletes the dedicated provider session once, under the original mutation
    /// identity. Its HTTP acknowledgment does not replace native exit events,
    /// the original's durable outcomes, or Root's physical-finality checks.
    pub async fn terminate(&self, api: &DaytonaApi, operation: OperationId) -> Result<(), ProviderError> {
        api.delete_session(&self.sandbox_id, &self.session_id, operation).await
    }
}

/// Original read cursor persisted only after native messages/events were
/// durably retained by Root. It contains no credential or execution authority.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub struct ExecServerLogCursor {
    /// Exact multiplexed provider bytes incorporated into this cursor.
    pub bytes: u64,
    /// SHA-256 of the exact original prefix, not merely its length.
    pub prefix_sha256: [u8; 32],
}

/// Genuine output from the pinned native producer, not translated FIFO/PTY
/// semantics. Only canonical protocol messages can carry process receipts.
#[derive(Debug)]
pub enum ExecServerLogEvent {
    /// Actual upstream response, notification or server request.
    Message(exec_server_protocol::JSONRPCMessage),
    /// Actual producer stderr diagnostic bytes, never fabricated tool output.
    Diagnostics(Vec<u8>),
}

#[derive(Clone, Copy)]
enum OutputStream { Stdout, Stderr }

/// Decoder of the documented provider multiplex labels plus the pinned native
/// exec-server's bounded JSON-lines protocol. Marker and JSON boundaries may
/// cross arbitrary real WebSocket frames. Native data is never terminal input.
pub struct ExecServerLogReader {
    hash: sha2::Sha256,
    bytes: u64,
    stream: Option<OutputStream>,
    candidate: u8,
    candidate_len: usize,
    line: Vec<u8>,
}

impl Default for ExecServerLogReader {
    fn default() -> Self {
        use sha2::Digest;
        Self {
            hash: sha2::Sha256::new(), bytes: 0, stream: None,
            candidate: 0, candidate_len: 0, line: Vec::new(),
        }
    }
}

impl ExecServerLogReader {
    /// Restores a cursor only by verifying and replaying the exact actual
    /// provider prefix. Truncation/replacement fails without adopting new logs.
    /// Completed historical messages are not redispatched or emitted again.
    pub fn restore(
        snapshot: &SessionLogSnapshot,
        cursor: &ExecServerLogCursor,
    ) -> Result<Self, ProviderError> {
        use sha2::Digest;
        let end = usize::try_from(cursor.bytes)
            .map_err(|_| ProviderError::Rejected("original native log cursor exceeds this platform".into()))?;
        let prefix = snapshot.bytes.get(..end)
            .ok_or_else(|| ProviderError::Conflict("original native logs were truncated".into()))?;
        let actual: [u8; 32] = sha2::Sha256::digest(prefix).into();
        if actual != cursor.prefix_sha256 {
            return Err(ProviderError::Conflict("original native log prefix was replaced".into()));
        }
        let mut reader = Self::default();
        reader.feed_inner(prefix, false)?;
        Ok(reader)
    }

    /// Returns exact prefix evidence for Root's canonical durable read cursor.
    /// Persist it only alongside the actual messages/results already retained.
    pub fn cursor(&self) -> ExecServerLogCursor {
        use sha2::Digest;
        ExecServerLogCursor { bytes: self.bytes, prefix_sha256: self.hash.clone().finalize().into() }
    }

    /// Incorporates actual provider bytes exactly once. An observer reconnect
    /// starts at provider offset zero: restore/skip its already-retained prefix,
    /// never silently append old bytes or duplicate execution/event receipts.
    pub fn feed(&mut self, bytes: &[u8]) -> Result<Vec<ExecServerLogEvent>, ProviderError> {
        self.feed_inner(bytes, true)
    }

    /// Consumes only the unread suffix of a readback snapshot after verifying
    /// its retained prefix. A shorter or changed prefix is a causal conflict,
    /// not a reason to manufacture a new producer or cursor.
    pub fn feed_snapshot(&mut self, snapshot: &SessionLogSnapshot) -> Result<Vec<ExecServerLogEvent>, ProviderError> {
        use sha2::Digest;
        let end = usize::try_from(self.bytes)
            .map_err(|_| ProviderError::Rejected("original native log cursor exceeds this platform".into()))?;
        let (prefix, unread) = snapshot.bytes.split_at_checked(end)
            .ok_or_else(|| ProviderError::Conflict("original native logs were truncated".into()))?;
        let actual: [u8; 32] = sha2::Sha256::digest(prefix).into();
        if actual != self.cursor().prefix_sha256 {
            return Err(ProviderError::Conflict("original native log prefix was replaced".into()));
        }
        self.feed(unread)
    }

    fn feed_inner(&mut self, bytes: &[u8], emit: bool) -> Result<Vec<ExecServerLogEvent>, ProviderError> {
        use sha2::Digest;
        let count = u64::try_from(bytes.len())
            .map_err(|_| ProviderError::Rejected("native log frame exceeds cursor range".into()))?;
        self.bytes = self.bytes.checked_add(count)
            .ok_or_else(|| ProviderError::Rejected("native log cursor overflow".into()))?;
        self.hash.update(bytes);
        let mut events = Vec::new();
        let mut diagnostics = Vec::new();
        for &byte in bytes {
            if self.candidate_len != 0 {
                if byte == self.candidate {
                    self.candidate_len += 1;
                    if self.candidate_len == 3 {
                        self.stream = Some(if byte == 1 { OutputStream::Stdout } else { OutputStream::Stderr });
                        self.candidate_len = 0;
                    }
                    continue;
                }
                for _ in 0..self.candidate_len {
                    self.payload(self.candidate, emit, &mut events, &mut diagnostics)?;
                }
                self.candidate_len = 0;
            }
            if matches!(byte, 1 | 2) {
                self.candidate = byte;
                self.candidate_len = 1;
            } else {
                self.payload(byte, emit, &mut events, &mut diagnostics)?;
            }
        }
        if !diagnostics.is_empty() { events.push(ExecServerLogEvent::Diagnostics(diagnostics)); }
        Ok(events)
    }

    fn payload(
        &mut self,
        byte: u8,
        emit: bool,
        events: &mut Vec<ExecServerLogEvent>,
        diagnostics: &mut Vec<u8>,
    ) -> Result<(), ProviderError> {
        match self.stream {
            Some(OutputStream::Stdout) => {
                if !diagnostics.is_empty() {
                    events.push(ExecServerLogEvent::Diagnostics(std::mem::take(diagnostics)));
                }
                if byte == b'\n' {
                    if self.line.last() == Some(&b'\r') { self.line.pop(); }
                    if emit && !self.line.iter().all(u8::is_ascii_whitespace) {
                        let message = serde_json::from_slice::<exec_server_protocol::JSONRPCMessage>(&self.line)
                            .map_err(|_| ProviderError::Rejected("invalid pinned native protocol output".into()))?;
                        events.push(ExecServerLogEvent::Message(message));
                    }
                    self.line.clear();
                } else {
                    if self.line.len() >= MAX_MESSAGE_BYTES {
                        return Err(ProviderError::Rejected("native protocol output exceeds its pinned bound".into()));
                    }
                    self.line.push(byte);
                }
            }
            Some(OutputStream::Stderr) => {
                if emit { diagnostics.push(byte); }
            }
            None => return Err(ProviderError::Rejected("provider log bytes lack their actual stream label".into())),
        }
        Ok(())
    }

    /// Finishes only an observer stream. Partial native JSON remains lost-ACK
    /// uncertainty; socket EOF alone never becomes a process exit receipt.
    pub fn finish(&mut self) -> Result<Vec<ExecServerLogEvent>, ProviderError> {
        let mut events = Vec::new();
        let mut diagnostics = Vec::new();
        for _ in 0..self.candidate_len {
            self.payload(self.candidate, true, &mut events, &mut diagnostics)?;
        }
        self.candidate_len = 0;
        if !self.line.is_empty() {
            return Err(ProviderError::Unavailable);
        }
        if !diagnostics.is_empty() { events.push(ExecServerLogEvent::Diagnostics(diagnostics)); }
        Ok(events)
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use exec_server_protocol::{JSONRPCMessage, JSONRPCNotification, JSONRPCResponse, RequestId};

    fn native_output(message: &JSONRPCMessage) -> Vec<u8> {
        let mut output = vec![1, 1, 1];
        output.extend(serde_json::to_vec(message).expect("upstream protocol fixture"));
        output.push(b'\n');
        output
    }

    fn response() -> JSONRPCMessage {
        JSONRPCMessage::Response(JSONRPCResponse {
            id: RequestId::String("read-original".into()),
            result: serde_json::json!({"rawData": "AQAC/w==", "unicode": "λ"}),
        })
    }

    #[test]
    fn native_rpc_and_binary_stderr_survive_every_byte_boundary() {
        let expected = response();
        let mut bytes = native_output(&expected);
        bytes.extend_from_slice(&[2, 2, 2, 0xff, 0, b'\n']);
        let notification = JSONRPCMessage::Notification(JSONRPCNotification {
            method: exec_server_protocol::EXEC_CLOSED_METHOD.into(),
            params: Some(serde_json::json!({"processId": "original-process"})),
        });
        bytes.extend(native_output(&notification));
        let mut reader = ExecServerLogReader::default();
        let mut messages = Vec::new();
        let mut diagnostics = Vec::new();
        for byte in &bytes {
            for event in reader.feed(std::slice::from_ref(byte)).expect("actual protocol decode") {
                match event {
                    ExecServerLogEvent::Message(message) => messages.push(message),
                    ExecServerLogEvent::Diagnostics(chunk) => diagnostics.extend(chunk),
                }
            }
        }
        assert_eq!(messages, vec![expected, notification]);
        assert_eq!(diagnostics, vec![0xff, 0, b'\n']);
        assert!(reader.finish().expect("complete observer stream").is_empty());
        use sha2::Digest;
        let digest: [u8; 32] = sha2::Sha256::digest(&bytes).into();
        assert_eq!(reader.cursor(), ExecServerLogCursor { bytes: bytes.len() as u64, prefix_sha256: digest });
    }

    #[test]
    fn original_cursor_restores_partial_line_without_reemitting_committed_messages() {
        let first = response();
        let second = JSONRPCMessage::Response(JSONRPCResponse {
            id: RequestId::Integer(19),
            result: serde_json::json!({"exitCode": 7}),
        });
        let first_bytes = native_output(&first);
        let second_bytes = native_output(&second);
        let prefix = first_bytes.len() + second_bytes.len() / 2;
        let mut full = first_bytes;
        full.extend(second_bytes);
        let snapshot = SessionLogSnapshot { bytes: full };
        let mut original = ExecServerLogReader::default();
        let before = original.feed(&snapshot.bytes[..prefix]).expect("partial original feed");
        assert!(matches!(before.as_slice(), [ExecServerLogEvent::Message(message)] if message == &first));
        let cursor = original.cursor();
        let mut restored = ExecServerLogReader::restore(&snapshot, &cursor).expect("verified original prefix");
        let after = restored.feed_snapshot(&snapshot).expect("unread native suffix");
        assert!(matches!(after.as_slice(), [ExecServerLogEvent::Message(message)] if message == &second));
        assert!(restored.feed_snapshot(&snapshot).expect("same retained snapshot").is_empty());
        let mut replaced = snapshot.clone();
        replaced.bytes[3] ^= 1;
        assert!(matches!(ExecServerLogReader::restore(&replaced, &cursor), Err(ProviderError::Conflict(_))));
        let truncated = SessionLogSnapshot { bytes: snapshot.bytes[..prefix - 1].to_vec() };
        assert!(matches!(ExecServerLogReader::restore(&truncated, &cursor), Err(ProviderError::Conflict(_))));
        assert!(matches!(restored.feed_snapshot(&replaced), Err(ProviderError::Conflict(_))));
    }

    #[test]
    fn malformed_unlabelled_and_truncated_native_output_never_become_exit_receipts() {
        let mut reader = ExecServerLogReader::default();
        assert!(matches!(reader.feed(b"{\"id\":1,\"result\":{}}\n"), Err(ProviderError::Rejected(_))));
        let mut reader = ExecServerLogReader::default();
        assert!(matches!(reader.feed(b"\x01\x01\x01not-json\n"), Err(ProviderError::Rejected(_))));
        let mut reader = ExecServerLogReader::default();
        reader.feed(b"\x01\x01\x01{\"id\":1,\"result\":").expect("partial actual line");
        assert_eq!(reader.finish().err(), Some(ProviderError::Unavailable));
    }

    #[test]
    fn ambiguous_mutations_keep_the_exact_original_operation_without_replacement() {
        let original = OperationId::parse("a663a8b1-9a49-4d33-9b40-576b99627f28").expect("retained operation");
        assert_eq!(original_mutation::<()>(Err(ProviderError::Unavailable), original),
            Err(ProviderError::OperationIndeterminate(original)));
        assert_eq!(original_mutation::<()>(Err(ProviderError::Rejected("malformed success".into())), original),
            Err(ProviderError::OperationIndeterminate(original)));
        let conflict = ProviderError::Conflict("already retained".into());
        assert_eq!(original_mutation::<()>(Err(conflict.clone()), original), Err(conflict));
    }

    #[test]
    fn dedicated_session_reconciliation_preserves_generated_identity_and_rejects_foreign_or_multiple_commands() {
        let original = SessionExecuteRequest {
            command: "printf 'one\\n'".into(), run_async: true, suppress_input_echo: true,
        };
        let command = SessionCommand {
            id: "provider-generated-original".into(), command: original.command.clone(),
            exit_code: Some(7), extra: Map::new(),
        };
        let session = |commands| Session { session_id: "caller-retained-session".into(), commands, extra: Map::new() };
        assert_eq!(observe_original_command(session(vec![]), &original).expect("read-only absent observation"),
            SessionCommandObservation::NotObserved);
        assert_eq!(observe_original_command(session(vec![command.clone()]), &original).expect("exact singleton"),
            SessionCommandObservation::Observed(command.clone()));
        assert!(matches!(observe_original_command(session(vec![command.clone(), command.clone()]), &original),
            Err(ProviderError::Conflict(_))));
        let mut foreign = command;
        foreign.command = "printf 'different\\n'".into();
        assert!(matches!(observe_original_command(session(vec![foreign]), &original),
            Err(ProviderError::Conflict(_))));
    }
}
