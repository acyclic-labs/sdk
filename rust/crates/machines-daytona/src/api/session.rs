/// Read-only reconciliation of a dedicated, one-command original session.
#[derive(Clone, Debug, PartialEq)]
pub enum SessionCommandObservation {
    /// Exact single retained command corresponding to the original intent.
    Observed(SessionCommand),
    /// No command was observed. This NEVER proves that a previous start cannot
    /// still complete and NEVER permits automatic replacement or re-execution.
    NotObserved,
}

