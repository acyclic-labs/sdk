// Punctuation and symbols from pulldown-cmark 0.13.4's puncttable.rs.
// Keep this data pinned with the parser; newer Unicode categories can differ.
pub(super) fn punctuation(character: char) -> bool {
    #[cfg(test)]
    crate::work::scan(1);
    if character.is_ascii() {
        return character.is_ascii_punctuation();
    }
    let code = u32::from(character);
    PUNCTUATION
        .binary_search_by_key(&(code >> 4), |(bucket, _)| {
            #[cfg(test)]
            crate::work::scan(1);
            u32::from(*bucket)
        })
        .ok()
        .and_then(|index| PUNCTUATION.get(index))
        .is_some_and(|(_, mask)| mask & (1 << (code & 15)) != 0)
}

