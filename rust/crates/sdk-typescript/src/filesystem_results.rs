fn hosted_public_values(source: &str, constant: &str) -> Result<Vec<String>, Error> {
    let body = named_const_array(source, constant)?;
    let values = body
        .lines()
        .filter_map(|line| {
            let marker = "Some(\"";
            let start = line.find(marker)? + marker.len();
            let end = line[start..].find('\"')? + start;
            Some(line[start..end].to_owned())
        })
        .collect::<Vec<_>>();
    if values.is_empty() {
        return Err(Error::Missing(format!(
            "filesystem hosted contract has no public values for {constant}"
        )));
    }
    Ok(values)
}

fn rust_enum_variants(source: &str, name: &str) -> Result<Vec<String>, Error> {
    let body = named_block(source, "enum", name)?;
    Ok(body
        .lines()
        .filter_map(|line| {
            let trimmed = line.trim();
            let name = trimmed.split(['(', '{', ',', ' ']).next()?;
            (name.chars().next()?.is_ascii_uppercase()).then(|| {
                name.chars()
                    .enumerate()
                    .map(|(index, ch)| if index == 0 { ch.to_ascii_lowercase() } else { ch })
                    .collect::<String>()
            })
        })
        .collect())
}

fn public_bound_fields(source: &str, function: &str) -> Result<Vec<String>, Error> {
    let marker = format!("fn {function}(");
    let start = source
        .find(&marker)
        .ok_or_else(|| Error::Missing(format!("filesystem source missing {function}")))?
        + marker.len();
    let end = source[start..]
        .find(')')
        .ok_or_else(|| Error::Missing(format!("filesystem source has unterminated {function}")))?
        + start;
    Ok(source[start..end]
        .lines()
        .filter_map(|line| {
            let field = line.trim().split(':').next()?.trim();
            (field.starts_with("maximum_") && field != "maximum_page_items")
                .then(|| snake_to_camel(field))
        })
        .collect())
}

fn named_block<'a>(source: &'a str, kind: &str, name: &str) -> Result<&'a str, Error> {
    let marker = format!("{kind} {name} {{");
    let marker_start = source
        .find(&marker)
        .ok_or_else(|| Error::Missing(format!("filesystem source missing {kind} {name}")))?;
    let start = marker_start + marker.len();
    let mut depth = 1usize;
    for (offset, character) in source[start..].char_indices() {
        match character {
            '{' => depth += 1,
            '}' => {
                depth -= 1;
                if depth == 0 {
                    return Ok(&source[start..start + offset]);
                }
            }
            _ => {}
        }
    }
    Err(Error::Missing(format!(
        "filesystem source has unterminated {kind} {name}"
    )))
}

fn require_values(name: &str, actual: &[String], expected: &[&str]) -> Result<(), Error> {
    if expected.iter().all(|value| actual.iter().any(|candidate| candidate == value)) {
        Ok(())
    } else {
        Err(Error::Missing(format!("filesystem {name} status model drifted")))
    }
}

fn require_fields(actual: &[String], expected: &[&str]) -> Result<(), Error> {
    if expected.iter().all(|value| actual.iter().any(|candidate| candidate == value)) {
        Ok(())
    } else {
        Err(Error::Missing("filesystem result limit fields drifted".to_owned()))
    }
}

fn named_const_array<'a>(source: &'a str, name: &str) -> Result<&'a str, Error> {
    let marker = format!("pub const {name}:");
    let start = source
        .find(&marker)
        .ok_or_else(|| Error::Missing(format!("filesystem source missing {name}")))?;
    let array_start = source[start..]
        .find("&[")
        .map(|offset| start + offset + 2)
        .ok_or_else(|| Error::Missing(format!("filesystem source has no array for {name}")))?;
    let end = source[array_start..]
        .find("];")
        .map(|offset| array_start + offset)
        .ok_or_else(|| Error::Missing(format!("filesystem source has unterminated {name}")))?;
    Ok(&source[array_start..end])
}

fn literals(values: &[String]) -> String {
    values
        .iter()
        .map(|value| format!(r#""{value}""#))
        .collect::<Vec<_>>()
        .join(", ")
}

fn snake_to_camel(value: &str) -> String {
    let mut result = String::new();
    for (index, part) in value.split('_').enumerate() {
        if index == 0 {
            result.push_str(part);
        } else {
            let mut chars = part.chars();
            if let Some(first) = chars.next() {
                result.push(first.to_ascii_uppercase());
                result.extend(chars);
            }
        }
    }
    result
}

#[cfg(test)]
mod tests {
    use super::{hosted_public_values, public_bound_fields, rust_enum_variants};

    #[test]
    fn hosted_values_skip_wire_only_entries() {
        let source = r#"
pub const STATUS: &[HostedEnumEntry<Status>] = &[
    entry(Status::Unspecified, None),
    entry(Status::Ready, Some("ready")),
    entry(Status::Indeterminate, None),
];
"#;
        assert_eq!(
            hosted_public_values(source, "STATUS").unwrap(),
            vec!["ready".to_owned()]
        );
    }

    #[test]
    fn generation_bounds_expose_only_caller_limits() {
        let source = r#"
pub const fn validate_generation_bounds(
    maximum_generations: u32,
    maximum_changes: u32,
    maximum_conflicts: u32,
    maximum_page_items: u32,
) -> Result<(), &'static str> { Ok(()) }
"#;
        assert_eq!(
            public_bound_fields(source, "validate_generation_bounds").unwrap(),
            vec![
                "maximumGenerations".to_owned(),
                "maximumChanges".to_owned(),
                "maximumConflicts".to_owned(),
            ]
        );
    }

    #[test]
    fn merge_result_variants_follow_rust_enum() {
        let source = r#"
pub enum MergePreparation {
    Prepared { generation_id: GenerationId },
    Conflicted { conflicts: Vec<MergeConflict> },
}
"#;
        assert_eq!(
            rust_enum_variants(source, "MergePreparation").unwrap(),
            vec!["prepared".to_owned(), "conflicted".to_owned()]
        );
    }
}
