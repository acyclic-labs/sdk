import { pathToFileURL } from "node:url";
import { writeFile } from "node:fs/promises";
const fixturePath = `${import.meta.dirname}/package-all-ops-actors-live-fixture.mjs`;
const { startConformanceFixture } = await import(pathToFileURL(fixturePath));
let fixture; let handled = false; let closed = false;
const closeAndExit = async () => { if (closed) return; closed = true; await fixture.close(); process.stderr.write(JSON.stringify({handled}) + "\n"); process.exit(handled ? 0 : 2); };
fixture = await startConformanceFixture({ onUnaryRequest: async method => { if (method.name === "CheckpointActor" && !handled) { handled = true; setTimeout(() => void closeAndExit(), 1000).unref(); } } });
process.stdout.write(JSON.stringify({ endpoint: fixture.options.endpoint, token: fixture.options.token, caCertificate: fixture.options.caCertificate }) + "\n");
if (process.env.ACYCLIC_CA_PATH) await writeFile(process.env.ACYCLIC_CA_PATH, fixture.options.caCertificate);
setTimeout(() => void closeAndExit(), 120000).unref();
