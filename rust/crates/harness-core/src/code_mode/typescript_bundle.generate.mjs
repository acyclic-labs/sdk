/**
 * Rebuild the embedded TypeScript eraser with pinned, published inputs.
 *
 * Copy typescript_bundle.package.json and typescript_bundle.lock.json into an
 * empty temporary directory as package.json and package-lock.json. Then run:
 *   npm ci --prefix <directory> --ignore-scripts --no-audit --no-fund
 *   node typescript_bundle.generate.mjs <directory>
 *
 * Node and esbuild are generation tools only. The emitted IIFE needs no module
 * loader or host capabilities. Sucrase's source is unchanged; the entry below
 * specializes its original getSucraseContext/RootTransformer composition to
 * fixed options, omitting option-validation and source-map dependencies.
 */
import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const destination = dirname(fileURLToPath(import.meta.url));
const dependencyRoot = process.argv[2] && resolve(process.argv[2]);
const entry = String.raw`
import {parse} from "sucrase/dist/esm/parser/index.js";
import NameManager from "sucrase/dist/esm/NameManager.js";
import {HelperManager} from "sucrase/dist/esm/HelperManager.js";
import TokenProcessor from "sucrase/dist/esm/TokenProcessor.js";
import RootTransformer from "sucrase/dist/esm/transformers/RootTransformer.js";

// These are Sucrase's fixed TypeScript-only options, not caller configuration.
const options = Object.freeze({
  transforms: Object.freeze(["typescript"]),
  disableESTransforms: true,
  keepUnusedImports: true,
  production: true,
});

export function transform(source) {
  if (typeof source !== "string") {
    throw new TypeError("TypeScript source must be a string");
  }
  const file = parse(source, false, true, false);
  const nameManager = new NameManager(source, file.tokens);
  const helperManager = new HelperManager(nameManager);
  const tokenProcessor = new TokenProcessor(
    source, file.tokens, false, true, helperManager,
  );
  const context = {
    tokenProcessor, scopes: file.scopes, nameManager,
    importProcessor: null, helperManager,
  };
  return new RootTransformer(
    context, options.transforms, false, options,
  ).transform().code;
}
`;

function sha256(bytes) {
  return createHash("sha256").update(bytes).digest("hex");
}

async function main() {
  if (!dependencyRoot) {
    throw new Error("missing dependency directory");
  }
  const lockBytes = await readFile(join(destination, "typescript_bundle.lock.json"));
  const expected = JSON.parse(lockBytes);
  const actual = JSON.parse(await readFile(join(dependencyRoot, "package-lock.json")));
  if (JSON.stringify(actual) !== JSON.stringify(expected)) {
    throw new Error("dependency lock differs from the pinned generation lock");
  }
  for (const name of ["sucrase", "esbuild"]) {
    const installed = JSON.parse(await readFile(join(dependencyRoot, "node_modules", name, "package.json")));
    if (installed.version !== expected.packages[`node_modules/${name}`].version) {
      throw new Error(`installed ${name} differs from the pinned version`);
    }
  }
  const esbuild = await import(pathToFileURL(join(dependencyRoot, "node_modules/esbuild/lib/main.js")).href);
  const result = await esbuild.build({
    absWorkingDir: dependencyRoot,
    stdin: { contents: entry, resolveDir: dependencyRoot, sourcefile: "typescript-entry.js" },
    bundle: true,
    platform: "neutral",
    mainFields: ["module", "main"],
    format: "iife",
    globalName: "__harness_typescript",
    target: "es2020",
    charset: "ascii",
    minify: true,
    treeShaking: true,
    legalComments: "none",
    banner: { js: "/*! Sucrase 3.35.1; MIT. See typescript_bundle.LICENSE. Generated by typescript_bundle.generate.mjs. */" },
    metafile: true,
    write: false,
  });
  const files = [];
  for (const [path, metadata] of Object.entries(result.metafile.inputs)) {
    if (path === "typescript-entry.js") {
      continue;
    }
    const canonical = path.replaceAll("\\", "/");
    if (!canonical.startsWith("node_modules/sucrase/dist/esm/")) {
      throw new Error(`unexpected bundled dependency: ${canonical}`);
    }
    if (metadata.imports.some((item) => item.external)) {
      throw new Error(`unresolved import in ${canonical}`);
    }
    files.push({ path: canonical, sha256: sha256(await readFile(resolve(dependencyRoot, path))) });
  }
  if (Object.values(result.metafile.outputs).some((item) => item.imports.length !== 0)) {
    throw new Error("bundle retains a module import");
  }
  files.sort((left, right) => left.path < right.path ? -1 : left.path > right.path ? 1 : 0);
  const output = result.outputFiles[0].contents;
  const license = await readFile(join(dependencyRoot, "node_modules/sucrase/LICENSE"));
  const metadata = {
    format: 1,
    upstream: "https://github.com/alangpierce/sucrase",
    package: { name: "sucrase", ...expected.packages["node_modules/sucrase"] },
    generator: { name: "esbuild", version: esbuild.version, integrity: expected.packages["node_modules/esbuild"].integrity },
    exports: { global: "__harness_typescript", method: "transform", input: "string", output: "string" },
    transforms: ["typescript"],
    disableESTransforms: true,
    keepUnusedImports: true,
    entrySha256: sha256(entry),
    lockSha256: sha256(lockBytes),
    licenseSha256: sha256(license),
    bundleSha256: sha256(output),
    bundleBytes: output.length,
    inputs: files,
  };
  await writeFile(join(destination, "typescript_bundle.js"), output);
  await writeFile(join(destination, "typescript_bundle.LICENSE"), license);
  await writeFile(join(destination, "typescript_bundle.sources.json"), `${JSON.stringify(metadata, null, 2)}\n`);
  console.log(`Generated ${relative(process.cwd(), join(destination, "typescript_bundle.js"))}: ${output.length} bytes, SHA256 ${metadata.bundleSha256}`);
}

main().catch((cause) => {
  console.error(`TypeScript asset generation failed: ${cause.message}; recovery: install the supplied pinned package/lock in an empty dependency directory, then run node ${JSON.stringify(fileURLToPath(import.meta.url))} <directory>`);
  process.exitCode = 1;
});
